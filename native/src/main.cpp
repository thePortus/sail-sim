// Copy the just-rendered swapchain texture to the CPU and write a PNG (BGRA->RGBA).
static void captureSurface(WGPUDevice device, WGPUQueue queue, WGPUTexture tex,
                           uint32_t w, uint32_t h, const char* path) {
  const uint32_t rowBytes = ((w * 4) + 255u) & ~255u;   // 256-aligned for copyTextureToBuffer
  const size_t bufSize = (size_t)rowBytes * h;
  WGPUBufferDescriptor bd = {};
  bd.size = bufSize; bd.usage = WGPUBufferUsage_CopyDst | WGPUBufferUsage_MapRead;
  WGPUBuffer rb = wgpuDeviceCreateBuffer(device, &bd);

  WGPUCommandEncoder enc = wgpuDeviceCreateCommandEncoder(device, nullptr);
  WGPUImageCopyTexture src = {}; src.texture = tex; src.aspect = WGPUTextureAspect_All;
  WGPUImageCopyBuffer dst = {}; dst.buffer = rb; dst.layout.bytesPerRow = rowBytes; dst.layout.rowsPerImage = h;
  WGPUExtent3D ext = { w, h, 1 };
  wgpuCommandEncoderCopyTextureToBuffer(enc, &src, &dst, &ext);
  WGPUCommandBuffer cmd = wgpuCommandEncoderFinish(enc, nullptr);
  wgpuQueueSubmit(queue, 1, &cmd);
  wgpuCommandBufferRelease(cmd);
  wgpuCommandEncoderRelease(enc);

  struct St { bool done; } st{ false };
  wgpuBufferMapAsync(rb, WGPUMapMode_Read, 0, bufSize,
    [](WGPUBufferMapAsyncStatus, void* ud) { ((St*)ud)->done = true; }, &st);
  while (!st.done) {
#if defined(WEBGPU_BACKEND_WGPU)
    wgpuDevicePoll(device, true, nullptr);
#endif
  }
  const uint8_t* mapped = (const uint8_t*)wgpuBufferGetConstMappedRange(rb, 0, bufSize);
  std::vector<uint8_t> rgba((size_t)w * h * 4);
  for (uint32_t y = 0; y < h; ++y) {
    const uint8_t* srcRow = mapped + (size_t)y * rowBytes;
    uint8_t* dstRow = rgba.data() + (size_t)y * w * 4;
    for (uint32_t x = 0; x < w; ++x) {
      dstRow[x * 4 + 0] = srcRow[x * 4 + 2];   // R <- B
      dstRow[x * 4 + 1] = srcRow[x * 4 + 1];   // G
      dstRow[x * 4 + 2] = srcRow[x * 4 + 0];   // B <- R
      dstRow[x * 4 + 3] = srcRow[x * 4 + 3];   // A
    }
  }
  wgpuBufferUnmap(rb);
  wgpuBufferRelease(rb);
  int ok = stbi_write_png(path, (int)w, (int)h, 4, rgba.data(), (int)w * 4);
  std::printf("[spike] screenshot %s -> %s\n", ok ? "wrote" : "FAILED", path);
}

// ── Terrain rendering ─────────────────────────────────────────────────────────
struct TerrainU { glm::mat4 viewProj; glm::vec4 eye; glm::vec4 bounds; glm::vec4 misc; glm::vec4 sun; glm::vec4 extra; };
struct SeaFarU  { glm::mat4 viewProj; glm::vec4 eye; glm::vec4 sun; glm::vec4 origin; };

// A camera-following grid displaced by the world height texture. Pipeline/grid are
// built up front; the height texture + bind group are filled once terrain data
// arrives (uploadTerrainHeight), so rendering waits on the async fetch.
struct TerrainRender {
  WGPURenderPipeline pipeline; WGPUShaderModule module;
  WGPUBuffer vbuf, ibuf, uniformBuf; WGPUBindGroupLayout bgl;
  WGPUTexture heightTex = nullptr; WGPUTextureView heightView = nullptr;
  WGPUBindGroup bindGroup = nullptr;
  uint32_t indexCount = 0; bool ready = false;
  // Biome skinning (Angular terrain.service port): splat map + 5 diffuse tiles +
  // 3 normal tiles. All slots point at a 1x1 placeholder until the async fetch
  // lands (the shader gates on extra.y), then the bind group is rebuilt.
  WGPUTexture placeTex = nullptr; WGPUTextureView placeView = nullptr;
  WGPUTexture splatTex = nullptr; WGPUTextureView splatView = nullptr;
  WGPUTexture diffTex[5] = {}; WGPUTextureView diffView[5] = {};
  WGPUTexture diff2Tex[2] = {}; WGPUTextureView diff2View[2] = {};   // grass2, rock2 variety
  WGPUTexture norTex[3] = {};  WGPUTextureView norView[3] = {};
  WGPUSampler tileSamp = nullptr, splatSamp = nullptr;
  bool  hasBiome = false;
  float peakH = 217.0f;   // Palau default until the heightfield is scanned
};

// (Re)build the terrain bind group from whatever views are currently live
// (placeholders until the heightfield / biome tiles arrive).
static void rebuildTerrainBind(WGPUDevice device, TerrainRender& t) {
  if (!t.heightView) return;   // height is the gate for drawing at all
  if (t.bindGroup) wgpuBindGroupRelease(t.bindGroup);
  WGPUBindGroupEntry bge[15] = {};
  bge[0].binding = 0; bge[0].buffer = t.uniformBuf; bge[0].size = sizeof(TerrainU);
  bge[1].binding = 1; bge[1].textureView = t.heightView;
  bge[2].binding = 2; bge[2].textureView = t.splatView ? t.splatView : t.placeView;
  for (int i = 0; i < 5; ++i) {
    bge[3 + i].binding = 3 + (uint32_t)i;
    bge[3 + i].textureView = t.diffView[i] ? t.diffView[i] : t.placeView;
  }
  for (int i = 0; i < 3; ++i) {
    bge[8 + i].binding = 8 + (uint32_t)i;
    bge[8 + i].textureView = t.norView[i] ? t.norView[i] : t.placeView;
  }
  for (int i = 0; i < 2; ++i) {
    bge[11 + i].binding = 11 + (uint32_t)i;
    bge[11 + i].textureView = t.diff2View[i] ? t.diff2View[i] : t.placeView;
  }
  bge[13].binding = 13; bge[13].sampler = t.tileSamp;
  bge[14].binding = 14; bge[14].sampler = t.splatSamp;
  WGPUBindGroupDescriptor bgd = {}; bgd.layout = t.bgl; bgd.entryCount = 15; bgd.entries = bge;
  t.bindGroup = wgpuDeviceCreateBindGroup(device, &bgd);
}

static WGPUShaderModule makeWGSL(WGPUDevice device, const char* code) {
  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = code;
  WGPUShaderModuleDescriptor smd = {};
  smd.nextInChain = &wgsl.chain;
  return wgpuDeviceCreateShaderModule(device, &smd);
}

// Grid of XZ positions spanning [-half, half]; the shader recentres it on the ship.
static void makeXZGrid(int N, float half, std::vector<float>& v, std::vector<uint32_t>& idx) {
  v.reserve((size_t)(N + 1) * (N + 1) * 2);
  for (int j = 0; j <= N; ++j)
    for (int i = 0; i <= N; ++i) {
      v.push_back(-half + (float)i / N * 2.0f * half);
      v.push_back(-half + (float)j / N * 2.0f * half);
    }
  idx.reserve((size_t)N * N * 6);
  for (int j = 0; j < N; ++j)
    for (int i = 0; i < N; ++i) {
      uint32_t a = (uint32_t)(j * (N + 1) + i), b = a + 1, c = a + (N + 1), d = c + 1;
      idx.insert(idx.end(), { a, c, b, b, c, d });
    }
}

static TerrainRender createTerrainRender(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat) {
  TerrainRender t;
  std::vector<float> v; std::vector<uint32_t> idx;
  makeXZGrid(512, 4000.0f, v, idx);   // +/-4 km around the ship, ~15.6 m cells
  t.indexCount = (uint32_t)idx.size();

  WGPUBufferDescriptor vbd = {}; vbd.usage = WGPUBufferUsage_Vertex | WGPUBufferUsage_CopyDst;
  vbd.size = v.size() * sizeof(float); t.vbuf = wgpuDeviceCreateBuffer(device, &vbd);
  wgpuQueueWriteBuffer(queue, t.vbuf, 0, v.data(), vbd.size);
  WGPUBufferDescriptor ibd = {}; ibd.usage = WGPUBufferUsage_Index | WGPUBufferUsage_CopyDst;
  ibd.size = idx.size() * sizeof(uint32_t); t.ibuf = wgpuDeviceCreateBuffer(device, &ibd);
  wgpuQueueWriteBuffer(queue, t.ibuf, 0, idx.data(), ibd.size);
  WGPUBufferDescriptor ubd = {}; ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst;
  ubd.size = sizeof(TerrainU); t.uniformBuf = wgpuDeviceCreateBuffer(device, &ubd);

  t.module = makeWGSL(device, TERRAIN_WGSL);

  WGPUBindGroupLayoutEntry ble[15] = {};
  ble[0].binding = 0; ble[0].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
  ble[0].buffer.type = WGPUBufferBindingType_Uniform;
  ble[1].binding = 1; ble[1].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
  ble[1].texture.sampleType = WGPUTextureSampleType_UnfilterableFloat;   // R32F
  ble[1].texture.viewDimension = WGPUTextureViewDimension_2D;
  for (int i = 2; i <= 12; ++i) {   // splat + 5 diffuse + 3 normal + 2 variety tiles
    ble[i].binding = (uint32_t)i; ble[i].visibility = WGPUShaderStage_Fragment;
    ble[i].texture.sampleType = WGPUTextureSampleType_Float;
    ble[i].texture.viewDimension = WGPUTextureViewDimension_2D;
  }
  ble[13].binding = 13; ble[13].visibility = WGPUShaderStage_Fragment;
  ble[13].sampler.type = WGPUSamplerBindingType_Filtering;
  ble[14].binding = 14; ble[14].visibility = WGPUShaderStage_Fragment;
  ble[14].sampler.type = WGPUSamplerBindingType_Filtering;
  WGPUBindGroupLayoutDescriptor bgld = {}; bgld.entryCount = 15; bgld.entries = ble;
  t.bgl = wgpuDeviceCreateBindGroupLayout(device, &bgld);

  // Samplers: tiles repeat with trilinear + anisotropy (they tile at 12-55 m);
  // the splat map clamps (it spans the whole world exactly once).
  {
    WGPUSamplerDescriptor sd = {};
    sd.addressModeU = WGPUAddressMode_Repeat; sd.addressModeV = WGPUAddressMode_Repeat;
    sd.addressModeW = WGPUAddressMode_Repeat;
    sd.magFilter = WGPUFilterMode_Linear; sd.minFilter = WGPUFilterMode_Linear;
    sd.mipmapFilter = WGPUMipmapFilterMode_Linear;
    sd.lodMaxClamp = 32.0f; sd.maxAnisotropy = 4;
    t.tileSamp = wgpuDeviceCreateSampler(device, &sd);
    sd.addressModeU = WGPUAddressMode_ClampToEdge; sd.addressModeV = WGPUAddressMode_ClampToEdge;
    sd.addressModeW = WGPUAddressMode_ClampToEdge;
    sd.mipmapFilter = WGPUMipmapFilterMode_Nearest; sd.lodMaxClamp = 0.0f; sd.maxAnisotropy = 1;
    t.splatSamp = wgpuDeviceCreateSampler(device, &sd);
  }
  // 1x1 mid-grey placeholder for every tile slot until the fetch lands.
  {
    const uint8_t grey[4] = { 128, 128, 128, 255 };
    t.placeTex = makeSampledRGBA(device, queue, 1, 1, grey, false);
    t.placeView = wgpuTextureCreateView(t.placeTex, nullptr);
  }
  WGPUPipelineLayoutDescriptor pld = {}; pld.bindGroupLayoutCount = 1; pld.bindGroupLayouts = &t.bgl;
  WGPUPipelineLayout pl = wgpuDeviceCreatePipelineLayout(device, &pld);

  WGPUVertexAttribute attr = {}; attr.format = WGPUVertexFormat_Float32x2; attr.offset = 0; attr.shaderLocation = 0;
  WGPUVertexBufferLayout vbl = {}; vbl.arrayStride = 2 * sizeof(float); vbl.attributeCount = 1; vbl.attributes = &attr;
  WGPUDepthStencilState ds = {}; ds.format = kDepthFormat; ds.depthWriteEnabled = true; ds.depthCompare = WGPUCompareFunction_Less;
  ds.stencilFront.compare = WGPUCompareFunction_Always; ds.stencilBack.compare = WGPUCompareFunction_Always;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;
  WGPUColorTargetState target = {}; target.format = colorFormat; target.writeMask = WGPUColorWriteMask_All;
  WGPUFragmentState frag = {}; frag.module = t.module; frag.entryPoint = "fs_main"; frag.targetCount = 1; frag.targets = &target;
  WGPURenderPipelineDescriptor rpd = {}; rpd.layout = pl;
  rpd.vertex.module = t.module; rpd.vertex.entryPoint = "vs_main"; rpd.vertex.bufferCount = 1; rpd.vertex.buffers = &vbl;
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList; rpd.primitive.frontFace = WGPUFrontFace_CCW; rpd.primitive.cullMode = WGPUCullMode_None;
  rpd.depthStencil = &ds; rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu; rpd.fragment = &frag;
  t.pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  wgpuPipelineLayoutRelease(pl);
  return t;
}

static void uploadTerrainHeight(WGPUDevice device, WGPUQueue queue, TerrainRender& t,
                                int W, int H, const float* data) {
  WGPUTextureDescriptor td = {};
  td.usage = WGPUTextureUsage_TextureBinding | WGPUTextureUsage_CopyDst;
  td.dimension = WGPUTextureDimension_2D; td.size = { (uint32_t)W, (uint32_t)H, 1 };
  td.format = WGPUTextureFormat_R32Float; td.mipLevelCount = 1; td.sampleCount = 1;
  t.heightTex = wgpuDeviceCreateTexture(device, &td);
  WGPUImageCopyTexture dst = {}; dst.texture = t.heightTex; dst.aspect = WGPUTextureAspect_All;
  WGPUTextureDataLayout dl = {}; dl.bytesPerRow = (uint32_t)W * 4; dl.rowsPerImage = (uint32_t)H;
  WGPUExtent3D ext = { (uint32_t)W, (uint32_t)H, 1 };
  wgpuQueueWriteTexture(queue, &dst, data, (size_t)W * H * 4, &dl, &ext);
  t.heightView = wgpuTextureCreateView(t.heightTex, nullptr);

  // Peak elevation for the biome shader's normalised height bands.
  float peak = 1.0f;
  for (size_t i = 0, n = (size_t)W * H; i < n; ++i) peak = std::max(peak, data[i]);
  t.peakH = peak;

  rebuildTerrainBind(device, t);
  t.ready = true;
}

// Upload the fetched biome tiles + splat map and rewire the terrain bind group.
static void uploadTerrainBiome(WGPUDevice device, WGPUQueue queue, TerrainRender& t,
                               const biome::Set& s) {
  t.splatTex = makeSampledRGBA(device, queue, (uint32_t)s.splat.w, (uint32_t)s.splat.h,
                               s.splat.rgba.data(), false);   // linear weights
  t.splatView = wgpuTextureCreateView(t.splatTex, nullptr);
  for (int i = 0; i < 5; ++i) {
    t.diffTex[i] = makeMippedRGBA(device, queue, (uint32_t)s.diff[i].w, (uint32_t)s.diff[i].h,
                                  s.diff[i].rgba.data(), true);    // sRGB colour
    t.diffView[i] = wgpuTextureCreateView(t.diffTex[i], nullptr);
  }
  for (int i = 0; i < 3; ++i) {
    t.norTex[i] = makeMippedRGBA(device, queue, (uint32_t)s.nor[i].w, (uint32_t)s.nor[i].h,
                                 s.nor[i].rgba.data(), false);     // linear normals
    t.norView[i] = wgpuTextureCreateView(t.norTex[i], nullptr);
  }
  for (int i = 0; i < 2; ++i) {
    t.diff2Tex[i] = makeMippedRGBA(device, queue, (uint32_t)s.diff2[i].w, (uint32_t)s.diff2[i].h,
                                   s.diff2[i].rgba.data(), true);  // grass2/rock2 variety (sRGB)
    t.diff2View[i] = wgpuTextureCreateView(t.diff2Tex[i], nullptr);
  }
  t.hasBiome = true;
  rebuildTerrainBind(device, t);   // no-op until the heightfield is in; re-run there
}

