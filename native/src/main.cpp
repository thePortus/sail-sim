// Sampled RGBA8 texture from CPU pixels (sky moon/star maps, small placeholders).
static WGPUTexture makeSampledRGBA(WGPUDevice device, WGPUQueue queue, uint32_t w, uint32_t h,
                                   const uint8_t* rgba, bool srgb) {
  WGPUTextureDescriptor td = {};
  td.usage = WGPUTextureUsage_TextureBinding | WGPUTextureUsage_CopyDst;
  td.dimension = WGPUTextureDimension_2D;
  td.size = { w, h, 1 };
  td.format = srgb ? WGPUTextureFormat_RGBA8UnormSrgb : WGPUTextureFormat_RGBA8Unorm;
  td.mipLevelCount = 1; td.sampleCount = 1;
  WGPUTexture tex = wgpuDeviceCreateTexture(device, &td);
  WGPUImageCopyTexture dst = {}; dst.texture = tex; dst.aspect = WGPUTextureAspect_All;
  WGPUTextureDataLayout layout = {}; layout.bytesPerRow = w * 4; layout.rowsPerImage = h;
  WGPUExtent3D ext = { w, h, 1 };
  wgpuQueueWriteTexture(queue, &dst, rgba, (size_t)w * h * 4, &layout, &ext);
  return tex;
}

// Like makeSampledRGBA but with a full CPU-built mip chain (box filter), so tiled
// detail textures (terrain biomes) minify cleanly instead of shimmering.
static WGPUTexture makeMippedRGBA(WGPUDevice device, WGPUQueue queue, uint32_t w, uint32_t h,
                                  const uint8_t* rgba, bool srgb) {
  uint32_t mips = 1;
  for (uint32_t m = (w > h ? w : h); m > 1; m >>= 1) ++mips;
  WGPUTextureDescriptor td = {};
  td.usage = WGPUTextureUsage_TextureBinding | WGPUTextureUsage_CopyDst;
  td.dimension = WGPUTextureDimension_2D;
  td.size = { w, h, 1 };
  td.format = srgb ? WGPUTextureFormat_RGBA8UnormSrgb : WGPUTextureFormat_RGBA8Unorm;
  td.mipLevelCount = mips; td.sampleCount = 1;
  WGPUTexture tex = wgpuDeviceCreateTexture(device, &td);

  std::vector<uint8_t> level(rgba, rgba + (size_t)w * h * 4);
  uint32_t lw = w, lh = h;
  for (uint32_t mip = 0; mip < mips; ++mip) {
    WGPUImageCopyTexture dst = {}; dst.texture = tex; dst.mipLevel = mip; dst.aspect = WGPUTextureAspect_All;
    WGPUTextureDataLayout layout = {}; layout.bytesPerRow = lw * 4; layout.rowsPerImage = lh;
    WGPUExtent3D ext = { lw, lh, 1 };
    wgpuQueueWriteTexture(queue, &dst, level.data(), (size_t)lw * lh * 4, &layout, &ext);
    if (mip + 1 == mips) break;
    // Box-filter the next level (clamped taps handle odd dimensions).
    uint32_t nw = lw > 1 ? lw >> 1 : 1, nh = lh > 1 ? lh >> 1 : 1;
    std::vector<uint8_t> next((size_t)nw * nh * 4);
    for (uint32_t y = 0; y < nh; ++y)
      for (uint32_t x = 0; x < nw; ++x) {
        uint32_t x0 = x * 2, y0 = y * 2;
        uint32_t x1 = x0 + 1 < lw ? x0 + 1 : x0, y1 = y0 + 1 < lh ? y0 + 1 : y0;
        for (int c = 0; c < 4; ++c) {
          uint32_t s = level[((size_t)y0 * lw + x0) * 4 + c] + level[((size_t)y0 * lw + x1) * 4 + c]
                     + level[((size_t)y1 * lw + x0) * 4 + c] + level[((size_t)y1 * lw + x1) * 4 + c];
          next[((size_t)y * nw + x) * 4 + c] = (uint8_t)(s / 4);
        }
      }
    level = std::move(next); lw = nw; lh = nh;
  }
  return tex;
}

// FFT ocean surface: a large grid displaced/shaded by sampling the compute
// cascade's textures. Its bind group (which references per-frame ping-ponged
// textures) is rebuilt each frame, so only the layout + sampler are kept here.
struct Ocean {
  WGPURenderPipeline  pipeline;
  WGPUBuffer          vbuf, ibuf, uniformBuf;
  WGPUShaderModule    module;
  WGPUSampler         sampler;
  WGPUBindGroupLayout bgl;
  uint32_t            indexCount;
  // Coarse, geometrically-flat FAR ring: same ocean shader (wave normals, foam,
  // reflection) so the real ocean look reaches the horizon without displacement
  // aliasing. Its own uniform (displacement amp 0, inner discard radius set).
  WGPUBuffer          farVbuf, farIbuf, farUniformBuf;
  uint32_t            farIndexCount;
};

static Ocean createOcean(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat) {
  // Grid of XZ positions centred on the origin; the shader displaces + normals it.
  const int   N = 600;
  const float half = 1500.0f;   // detailed FFT ocean out to +/-1.5 km (was 300 m — its
                                // square edge was visible up close); flat far-sea beyond
  std::vector<float> gv;    gv.reserve((size_t)(N + 1) * (N + 1) * 2);
  std::vector<uint32_t> gi; gi.reserve((size_t)N * N * 6);
  for (int j = 0; j <= N; ++j)
    for (int i = 0; i <= N; ++i) {
      gv.push_back(-half + (float)i / N * 2.0f * half);
      gv.push_back(-half + (float)j / N * 2.0f * half);
    }
  for (int j = 0; j < N; ++j)
    for (int i = 0; i < N; ++i) {
      uint32_t a = (uint32_t)(j * (N + 1) + i), b = a + 1, c = a + (N + 1), d = c + 1;
      gi.insert(gi.end(), { a, c, b, b, c, d });
    }

  Ocean o;
  o.indexCount = (uint32_t)gi.size();

  WGPUBufferDescriptor vbd = {};
  vbd.usage = WGPUBufferUsage_Vertex | WGPUBufferUsage_CopyDst; vbd.size = gv.size() * sizeof(float);
  o.vbuf = wgpuDeviceCreateBuffer(device, &vbd);
  wgpuQueueWriteBuffer(queue, o.vbuf, 0, gv.data(), vbd.size);

  WGPUBufferDescriptor ibd = {};
  ibd.usage = WGPUBufferUsage_Index | WGPUBufferUsage_CopyDst; ibd.size = gi.size() * sizeof(uint32_t);
  o.ibuf = wgpuDeviceCreateBuffer(device, &ibd);
  wgpuQueueWriteBuffer(queue, o.ibuf, 0, gi.data(), ibd.size);

  WGPUBufferDescriptor ubd = {};
  ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; ubd.size = sizeof(OceanCamera);
  o.uniformBuf = wgpuDeviceCreateBuffer(device, &ubd);

  // Coarse, flat FAR ring (+/-20 km, ~200 m cells). Flat, so cell size doesn't
  // alias; the fragment still samples the FFT normal/foam per pixel.
  {
    const int fN = 200; const float fhalf = 20000.0f;
    std::vector<float> fv; std::vector<uint32_t> fi;
    fv.reserve((size_t)(fN + 1) * (fN + 1) * 2);
    for (int j = 0; j <= fN; ++j)
      for (int i = 0; i <= fN; ++i) {
        fv.push_back(-fhalf + (float)i / fN * 2.0f * fhalf);
        fv.push_back(-fhalf + (float)j / fN * 2.0f * fhalf);
      }
    for (int j = 0; j < fN; ++j)
      for (int i = 0; i < fN; ++i) {
        uint32_t a = (uint32_t)(j * (fN + 1) + i), b = a + 1, c = a + (fN + 1), d = c + 1;
        fi.insert(fi.end(), { a, c, b, b, c, d });
      }
    o.farIndexCount = (uint32_t)fi.size();
    WGPUBufferDescriptor fvbd = {}; fvbd.usage = WGPUBufferUsage_Vertex | WGPUBufferUsage_CopyDst; fvbd.size = fv.size() * sizeof(float);
    o.farVbuf = wgpuDeviceCreateBuffer(device, &fvbd); wgpuQueueWriteBuffer(queue, o.farVbuf, 0, fv.data(), fvbd.size);
    WGPUBufferDescriptor fibd = {}; fibd.usage = WGPUBufferUsage_Index | WGPUBufferUsage_CopyDst; fibd.size = fi.size() * sizeof(uint32_t);
    o.farIbuf = wgpuDeviceCreateBuffer(device, &fibd); wgpuQueueWriteBuffer(queue, o.farIbuf, 0, fi.data(), fibd.size);
    WGPUBufferDescriptor fubd = {}; fubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; fubd.size = sizeof(OceanCamera);
    o.farUniformBuf = wgpuDeviceCreateBuffer(device, &fubd);
  }

  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = OCEAN_SURFACE_WGSL;
  WGPUShaderModuleDescriptor smd = {};
  smd.nextInChain = &wgsl.chain;
  o.module = wgpuDeviceCreateShaderModule(device, &smd);

  // Linear, repeating sampler for the tiling FFT textures.
  WGPUSamplerDescriptor sd = {};
  sd.addressModeU = WGPUAddressMode_Repeat;
  sd.addressModeV = WGPUAddressMode_Repeat;
  sd.addressModeW = WGPUAddressMode_Repeat;
  sd.magFilter = WGPUFilterMode_Linear;
  sd.minFilter = WGPUFilterMode_Linear;
  sd.mipmapFilter = WGPUMipmapFilterMode_Nearest;
  sd.lodMinClamp = 0.0f; sd.lodMaxClamp = 1.0f; sd.maxAnisotropy = 1;
  o.sampler = wgpuDeviceCreateSampler(device, &sd);

  WGPUVertexAttribute attr = {};
  attr.format = WGPUVertexFormat_Float32x2; attr.offset = 0; attr.shaderLocation = 0;
  WGPUVertexBufferLayout vbl = {};
  vbl.arrayStride = 2 * sizeof(float);
  vbl.stepMode = WGPUVertexStepMode_Vertex;
  vbl.attributeCount = 1; vbl.attributes = &attr;

  WGPUDepthStencilState ds = {};
  ds.format = kDepthFormat;
  ds.depthWriteEnabled = true;
  ds.depthCompare = WGPUCompareFunction_Less;
  // Hull water mask: reject pixels the hull stencil stamped (ref written = 1, pass
  // reference = kHullStencilRef) so the sea never draws over an open deck.
  ds.stencilFront.compare = WGPUCompareFunction_NotEqual;
  ds.stencilFront.failOp = WGPUStencilOperation_Keep;
  ds.stencilFront.depthFailOp = WGPUStencilOperation_Keep;
  ds.stencilFront.passOp = WGPUStencilOperation_Keep;
  ds.stencilBack = ds.stencilFront;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0;   // test only, never write

  WGPUColorTargetState target = {};
  target.format = colorFormat; target.writeMask = WGPUColorWriteMask_All;
  WGPUFragmentState frag = {};
  frag.module = o.module; frag.entryPoint = "fs_main";
  frag.targetCount = 1; frag.targets = &target;

  // Explicit bind group layout (auto-layout misrouted binding 11): uniform (0),
  // 9 cascade textures (1-9), sampler (10), reflection (11). All float/filtering.
  WGPUBindGroupLayoutEntry be[12] = {};
  be[0].binding = 0; be[0].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
  be[0].buffer.type = WGPUBufferBindingType_Uniform;
  for (int i = 1; i <= 9; ++i) {
    be[i].binding = (uint32_t)i; be[i].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
    be[i].texture.sampleType = WGPUTextureSampleType_Float;
    be[i].texture.viewDimension = WGPUTextureViewDimension_2D;
  }
  be[10].binding = 10; be[10].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
  be[10].sampler.type = WGPUSamplerBindingType_Filtering;
  be[11].binding = 11; be[11].visibility = WGPUShaderStage_Fragment;
  be[11].texture.sampleType = WGPUTextureSampleType_Float;
  be[11].texture.viewDimension = WGPUTextureViewDimension_2D;
  WGPUBindGroupLayoutDescriptor bld = {}; bld.entryCount = 12; bld.entries = be;
  o.bgl = wgpuDeviceCreateBindGroupLayout(device, &bld);
  WGPUPipelineLayoutDescriptor pld = {}; pld.bindGroupLayoutCount = 1; pld.bindGroupLayouts = &o.bgl;
  WGPUPipelineLayout pl = wgpuDeviceCreatePipelineLayout(device, &pld);

  WGPURenderPipelineDescriptor rpd = {};
  rpd.layout = pl;
  rpd.vertex.module = o.module; rpd.vertex.entryPoint = "vs_main";
  rpd.vertex.bufferCount = 1; rpd.vertex.buffers = &vbl;
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  rpd.primitive.frontFace = WGPUFrontFace_CCW;
  rpd.primitive.cullMode = WGPUCullMode_None;
  rpd.depthStencil = &ds;
  rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu;
  rpd.fragment = &frag;
  o.pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  wgpuPipelineLayoutRelease(pl);
  return o;
}

// Procedural gradient sky drawn as a full-screen triangle (no vertex buffer).
// Unit vector FROM origin TOWARD the sun for a game hour (0..24) — port of the
// client's scene.service computeSunDir: a smooth sine arc (sunrise h=6, noon h=12,
// sunset h=18). The X term is negated so the sun rises in the east (+X) / sets in
// the west (-X), matching the world's cardinal convention. Drives the sky scatter,
// sun disc, and (blended with the moon) all scene lighting so they stay consistent.
static glm::vec3 computeSunDir(float gameHours) {
  const float PI = glm::pi<float>();
  float elev  = std::sin(((gameHours - 6.0f) / 12.0f) * PI);
  float az    = (gameHours / 24.0f) * 2.0f * PI - PI;
  float horiz = std::sqrt(std::max(0.0f, 1.0f - elev * elev));
  return glm::normalize(glm::vec3(-horiz * std::sin(az), elev, horiz * std::cos(az)));
}

struct SkyUniform {
  glm::mat4 invViewProj;
  glm::vec4 eye;    // xyz camera
  glm::vec4 sun;    // xyz = toward-sun
  glm::vec4 moon;   // xyz = toward-moon; w = moon fade
  glm::vec4 params; // x = star fade; y = stars available; z = moon tex available; w unused
};
struct Sky {
  WGPURenderPipeline pipeline; WGPUBuffer uniformBuf; WGPUBindGroup bindGroup; WGPUShaderModule module;
  WGPUSampler sampler;
  WGPUTexture moonTex, starsTex;      // owned (1x1 placeholders until the real maps load)
  WGPUTextureView moonView, starsView;
};

// (Re)build the sky bind group from the current uniform buffer + moon/star views.
static void rebuildSkyBind(WGPUDevice device, Sky& s) {
  if (s.bindGroup) wgpuBindGroupRelease(s.bindGroup);
  WGPUBindGroupLayout bgl = wgpuRenderPipelineGetBindGroupLayout(s.pipeline, 0);
  WGPUBindGroupEntry be[4] = {};
  be[0].binding = 0; be[0].buffer = s.uniformBuf; be[0].size = sizeof(SkyUniform);
  be[1].binding = 1; be[1].textureView = s.moonView;
  be[2].binding = 2; be[2].textureView = s.starsView;
  be[3].binding = 3; be[3].sampler = s.sampler;
  WGPUBindGroupDescriptor bgd = {}; bgd.layout = bgl; bgd.entryCount = 4; bgd.entries = be;
  s.bindGroup = wgpuDeviceCreateBindGroup(device, &bgd);
  wgpuBindGroupLayoutRelease(bgl);
}

static Sky createSky(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat) {
  Sky s;
  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = SKY_WGSL;
  WGPUShaderModuleDescriptor smd = {}; smd.nextInChain = &wgsl.chain;
  s.module = wgpuDeviceCreateShaderModule(device, &smd);

  WGPUDepthStencilState ds = {};
  ds.format = kDepthFormat;
  ds.depthWriteEnabled = false;              // background — don't occlude anything
  ds.depthCompare = WGPUCompareFunction_Always;
  ds.stencilFront.compare = WGPUCompareFunction_Always;
  ds.stencilFront.failOp = WGPUStencilOperation_Keep;
  ds.stencilFront.depthFailOp = WGPUStencilOperation_Keep;
  ds.stencilFront.passOp = WGPUStencilOperation_Keep;
  ds.stencilBack = ds.stencilFront;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;

  WGPUColorTargetState target = {}; target.format = colorFormat; target.writeMask = WGPUColorWriteMask_All;
  WGPUFragmentState frag = {}; frag.module = s.module; frag.entryPoint = "fs_main"; frag.targetCount = 1; frag.targets = &target;

  WGPURenderPipelineDescriptor rpd = {};
  rpd.layout = nullptr;
  rpd.vertex.module = s.module; rpd.vertex.entryPoint = "vs_main";   // vertices generated in-shader
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  rpd.primitive.cullMode = WGPUCullMode_None;
  rpd.depthStencil = &ds;
  rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu;
  rpd.fragment = &frag;
  s.pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);

  WGPUBufferDescriptor ubd = {};
  ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; ubd.size = sizeof(SkyUniform);
  s.uniformBuf = wgpuDeviceCreateBuffer(device, &ubd);

  // Linear sampler; repeat U (equirect longitude wraps) / clamp V (poles).
  WGPUSamplerDescriptor sd = {};
  sd.addressModeU = WGPUAddressMode_Repeat;
  sd.addressModeV = WGPUAddressMode_ClampToEdge;
  sd.addressModeW = WGPUAddressMode_ClampToEdge;
  sd.magFilter = WGPUFilterMode_Linear; sd.minFilter = WGPUFilterMode_Linear;
  sd.mipmapFilter = WGPUMipmapFilterMode_Linear;
  sd.lodMaxClamp = 1.0f; sd.maxAnisotropy = 1;
  s.sampler = wgpuDeviceCreateSampler(device, &sd);

  // 1x1 placeholders until the real /sky maps decode: black moon (invisible), black
  // stars. params.y/z flag "unavailable" so the shader draws neutral fallbacks.
  const uint8_t black[4] = { 0, 0, 0, 255 };
  s.moonTex  = makeSampledRGBA(device, queue, 1, 1, black, true);
  s.starsTex = makeSampledRGBA(device, queue, 1, 1, black, true);
  s.moonView  = wgpuTextureCreateView(s.moonTex, nullptr);
  s.starsView = wgpuTextureCreateView(s.starsTex, nullptr);

  s.bindGroup = nullptr;
  rebuildSkyBind(device, s);
  return s;
}

// ── God rays (crepuscular shafts): occlusion mask + additive radial-blur ──────
static const WGPUTextureFormat kGodrayFormat = WGPUTextureFormat_RGBA8Unorm;
struct GodrayOcc  { glm::mat4 invViewProj; glm::vec4 eye; glm::vec4 sun; };   // sun.w = brightness
struct GodrayBlur { glm::vec4 sunUV; glm::vec4 params; };   // sunUV=(u,v,exposure,decay); params=(weight,density,samples,inView)
struct Godrays {
  WGPUShaderModule module;
  WGPURenderPipeline occPipeline, blurPipeline;
  WGPUBuffer occUniform, blurUniform;
  WGPUBindGroup occBind, blurBind;   // blurBind references the occlusion texture (rebuilt on resize)
};

// (Re)build the blur bind group against the current occlusion-mask view.
static void rebuildGodrayBlurBind(WGPUDevice device, Godrays& g, WGPUTextureView occView, WGPUSampler samp) {
  if (g.blurBind) wgpuBindGroupRelease(g.blurBind);
  WGPUBindGroupLayout bgl = wgpuRenderPipelineGetBindGroupLayout(g.blurPipeline, 0);
  WGPUBindGroupEntry be[3] = {};
  be[0].binding = 0; be[0].buffer = g.blurUniform; be[0].size = sizeof(GodrayBlur);
  be[1].binding = 1; be[1].textureView = occView;
  be[2].binding = 2; be[2].sampler = samp;
  WGPUBindGroupDescriptor bgd = {}; bgd.layout = bgl; bgd.entryCount = 3; bgd.entries = be;
  g.blurBind = wgpuDeviceCreateBindGroup(device, &bgd);
  wgpuBindGroupLayoutRelease(bgl);
}

static Godrays createGodrays(WGPUDevice device, WGPUTextureFormat colorFormat, WGPUSampler samp,
                             WGPUTextureView occView) {
  Godrays g = {};
  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = GODRAYS_WGSL;
  WGPUShaderModuleDescriptor smd = {}; smd.nextInChain = &wgsl.chain;
  g.module = wgpuDeviceCreateShaderModule(device, &smd);

  // Occlusion pipeline: draw the sun mask into kGodrayFormat, depth-tested (LessEqual,
  // no write) so only sky pixels (scene depth == 1.0) pass and geometry occludes.
  {
    WGPUDepthStencilState ds = {};
    ds.format = kDepthFormat; ds.depthWriteEnabled = false; ds.depthCompare = WGPUCompareFunction_LessEqual;
    ds.stencilFront.compare = WGPUCompareFunction_Always; ds.stencilBack.compare = WGPUCompareFunction_Always;
    ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;
    WGPUColorTargetState target = {}; target.format = kGodrayFormat; target.writeMask = WGPUColorWriteMask_All;
    WGPUFragmentState frag = {}; frag.module = g.module; frag.entryPoint = "fs_occlusion"; frag.targetCount = 1; frag.targets = &target;
    WGPURenderPipelineDescriptor rpd = {};
    rpd.vertex.module = g.module; rpd.vertex.entryPoint = "vs_main";
    rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList; rpd.primitive.cullMode = WGPUCullMode_None;
    rpd.depthStencil = &ds; rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu;
    rpd.fragment = &frag;
    g.occPipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  }
  // Blur pipeline: additive shafts onto the swapchain in the final pass (which has a
  // depth attachment, so declare a matching no-write/Always depth state).
  {
    WGPUBlendState blend = {};
    blend.color.srcFactor = WGPUBlendFactor_One; blend.color.dstFactor = WGPUBlendFactor_One; blend.color.operation = WGPUBlendOperation_Add;
    blend.alpha.srcFactor = WGPUBlendFactor_One; blend.alpha.dstFactor = WGPUBlendFactor_One; blend.alpha.operation = WGPUBlendOperation_Add;
    WGPUColorTargetState target = {}; target.format = colorFormat; target.writeMask = WGPUColorWriteMask_All; target.blend = &blend;
    WGPUDepthStencilState ds = {};
    ds.format = kDepthFormat; ds.depthWriteEnabled = false; ds.depthCompare = WGPUCompareFunction_Always;
    ds.stencilFront.compare = WGPUCompareFunction_Always; ds.stencilBack.compare = WGPUCompareFunction_Always;
    ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;
    WGPUFragmentState frag = {}; frag.module = g.module; frag.entryPoint = "fs_blur"; frag.targetCount = 1; frag.targets = &target;
    WGPURenderPipelineDescriptor rpd = {};
    rpd.vertex.module = g.module; rpd.vertex.entryPoint = "vs_main";
    rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList; rpd.primitive.cullMode = WGPUCullMode_None;
    rpd.depthStencil = &ds; rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu;
    rpd.fragment = &frag;
    g.blurPipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  }

  WGPUBufferDescriptor ubd = {}; ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst;
  ubd.size = sizeof(GodrayOcc);  g.occUniform  = wgpuDeviceCreateBuffer(device, &ubd);
  ubd.size = sizeof(GodrayBlur); g.blurUniform = wgpuDeviceCreateBuffer(device, &ubd);

  WGPUBindGroupLayout obgl = wgpuRenderPipelineGetBindGroupLayout(g.occPipeline, 0);
  WGPUBindGroupEntry obe = {}; obe.binding = 0; obe.buffer = g.occUniform; obe.size = sizeof(GodrayOcc);
  WGPUBindGroupDescriptor obgd = {}; obgd.layout = obgl; obgd.entryCount = 1; obgd.entries = &obe;
  g.occBind = wgpuDeviceCreateBindGroup(device, &obgd);
  wgpuBindGroupLayoutRelease(obgl);

  rebuildGodrayBlurBind(device, g, occView, samp);
  return g;
}

