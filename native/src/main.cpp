static const WGPUTextureFormat kDepthFormat = WGPUTextureFormat_Depth24Plus;

// A framebuffer-sized depth texture, recreated on resize.
static WGPUTexture makeDepthTexture(WGPUDevice device, uint32_t w, uint32_t h) {
  WGPUTextureDescriptor td = {};
  td.usage = WGPUTextureUsage_RenderAttachment;
  td.dimension = WGPUTextureDimension_2D;
  td.size = { w, h, 1 };
  td.format = kDepthFormat;
  td.mipLevelCount = 1;
  td.sampleCount = 1;
  return wgpuDeviceCreateTexture(device, &td);
}

// Uniforms uploaded per frame: clip matrix, model matrix (for normals + world
// position), and the camera position (for the PBR view vector).
struct MeshUniforms {
  glm::mat4 mvp;
  glm::mat4 model;
  glm::vec4 eye;
};

// A depth-tested, PBR-shaded mesh (glTF-loaded or the fallback cube). Holds the
// pipeline, buffers, decoded textures, and one bind group per texture; draws as a
// sequence of submeshes, each selecting its material's base-colour texture.
// How many ships (you + remote players) one vessel mesh can draw per frame via
// dynamic uniform offsets. Each instance uses one aligned MeshUniforms slot.
static constexpr uint32_t kMaxShipInstances = 64;

struct Mesh {
  WGPURenderPipeline           pipeline;
  WGPUBuffer                   vbuf, ibuf, uniformBuf;
  WGPUShaderModule             module;
  WGPUSampler                  sampler;
  std::vector<WGPUTexture>     textures;     // decoded maps + 1x1 white + flat-normal defaults
  std::vector<WGPUTextureView> views;        // aligned with textures
  std::vector<WGPUBindGroup>   bindGroups;   // one per submesh
  std::vector<Submesh>         submeshes;
  uint32_t                     uniformStride = 0;   // bytes between per-ship uniform slots
  // Placement, computed at load from the model's bounds (see loadVessel).
  float     shipScale = 1.0f;
  float     draft = 0.0f;
  glm::vec3 keelCenter = glm::vec3(0.0f);
};

static Mesh createMesh(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat, const MeshData& data) {
  Mesh mesh;
  mesh.submeshes = data.submeshes;

  WGPUBufferDescriptor vbd = {};
  vbd.usage = WGPUBufferUsage_Vertex | WGPUBufferUsage_CopyDst;
  vbd.size = data.vertices.size() * sizeof(float);
  mesh.vbuf = wgpuDeviceCreateBuffer(device, &vbd);
  wgpuQueueWriteBuffer(queue, mesh.vbuf, 0, data.vertices.data(), vbd.size);

  WGPUBufferDescriptor ibd = {};
  ibd.usage = WGPUBufferUsage_Index | WGPUBufferUsage_CopyDst;
  ibd.size = data.indices.size() * sizeof(uint32_t);
  mesh.ibuf = wgpuDeviceCreateBuffer(device, &ibd);
  wgpuQueueWriteBuffer(queue, mesh.ibuf, 0, data.indices.data(), ibd.size);

  // One uniform slot per ship instance, at a 256-byte-aligned stride so each can be
  // selected by a dynamic bind-group offset (min offset alignment is 256).
  mesh.uniformStride = (uint32_t)((sizeof(MeshUniforms) + 255u) & ~size_t(255u));
  WGPUBufferDescriptor ubd = {};
  ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst;
  ubd.size = (uint64_t)mesh.uniformStride * kMaxShipInstances;
  mesh.uniformBuf = wgpuDeviceCreateBuffer(device, &ubd);

  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = MESH_WGSL;
  WGPUShaderModuleDescriptor smd = {};
  smd.nextInChain = &wgsl.chain;
  mesh.module = wgpuDeviceCreateShaderModule(device, &smd);

  // bind group layout: uniform (b0), base/normal/metal-rough textures (b1-3), sampler (b4)
  WGPUBindGroupLayoutEntry ble[5] = {};
  ble[0].binding = 0; ble[0].visibility = WGPUShaderStage_Vertex | WGPUShaderStage_Fragment;
  ble[0].buffer.type = WGPUBufferBindingType_Uniform;
  ble[0].buffer.hasDynamicOffset = true;   // select the per-ship slot at draw time
  for (int i = 1; i <= 3; ++i) {
    ble[i].binding = (uint32_t)i; ble[i].visibility = WGPUShaderStage_Fragment;
    ble[i].texture.sampleType = WGPUTextureSampleType_Float;
    ble[i].texture.viewDimension = WGPUTextureViewDimension_2D;
  }
  ble[4].binding = 4; ble[4].visibility = WGPUShaderStage_Fragment;
  ble[4].sampler.type = WGPUSamplerBindingType_Filtering;
  WGPUBindGroupLayoutDescriptor bgld = {};
  bgld.entryCount = 5; bgld.entries = ble;
  WGPUBindGroupLayout bgl = wgpuDeviceCreateBindGroupLayout(device, &bgld);

  WGPUPipelineLayoutDescriptor pld = {};
  pld.bindGroupLayoutCount = 1; pld.bindGroupLayouts = &bgl;
  WGPUPipelineLayout pl = wgpuDeviceCreatePipelineLayout(device, &pld);

  WGPUVertexAttribute attrs[5] = {};
  attrs[0].format = WGPUVertexFormat_Float32x3; attrs[0].offset = 0;                  attrs[0].shaderLocation = 0; // position
  attrs[1].format = WGPUVertexFormat_Float32x3; attrs[1].offset = 3  * sizeof(float); attrs[1].shaderLocation = 1; // normal
  attrs[2].format = WGPUVertexFormat_Float32x2; attrs[2].offset = 6  * sizeof(float); attrs[2].shaderLocation = 2; // uv
  attrs[3].format = WGPUVertexFormat_Float32x3; attrs[3].offset = 8  * sizeof(float); attrs[3].shaderLocation = 3; // albedo
  attrs[4].format = WGPUVertexFormat_Float32x2; attrs[4].offset = 11 * sizeof(float); attrs[4].shaderLocation = 4; // metallic, roughness
  WGPUVertexBufferLayout vbl = {};
  vbl.arrayStride = kFloatsPerVertex * sizeof(float);
  vbl.stepMode = WGPUVertexStepMode_Vertex;
  vbl.attributeCount = 5; vbl.attributes = attrs;

  WGPUDepthStencilState ds = {};
  ds.format = kDepthFormat;
  ds.depthWriteEnabled = true;
  ds.depthCompare = WGPUCompareFunction_Less;
  ds.stencilFront.compare = WGPUCompareFunction_Always;
  ds.stencilFront.failOp = WGPUStencilOperation_Keep;
  ds.stencilFront.depthFailOp = WGPUStencilOperation_Keep;
  ds.stencilFront.passOp = WGPUStencilOperation_Keep;
  ds.stencilBack = ds.stencilFront;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;

  WGPUColorTargetState target = {};
  target.format = colorFormat;
  target.writeMask = WGPUColorWriteMask_All;
  WGPUFragmentState frag = {};
  frag.module = mesh.module; frag.entryPoint = "fs_main";
  frag.targetCount = 1; frag.targets = &target;

  WGPURenderPipelineDescriptor rpd = {};
  rpd.layout = pl;
  rpd.vertex.module = mesh.module;
  rpd.vertex.entryPoint = "vs_main";
  rpd.vertex.bufferCount = 1; rpd.vertex.buffers = &vbl;
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  rpd.primitive.frontFace = WGPUFrontFace_CCW;
  rpd.primitive.cullMode = WGPUCullMode_None;   // depth test handles occlusion
  rpd.depthStencil = &ds;
  rpd.multisample.count = 1;
  rpd.multisample.mask = 0xFFFFFFFFu;
  rpd.fragment = &frag;
  mesh.pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  wgpuPipelineLayoutRelease(pl);

  // linear, repeating sampler
  WGPUSamplerDescriptor sd = {};
  sd.addressModeU = WGPUAddressMode_Repeat;
  sd.addressModeV = WGPUAddressMode_Repeat;
  sd.addressModeW = WGPUAddressMode_Repeat;
  sd.magFilter = WGPUFilterMode_Linear;
  sd.minFilter = WGPUFilterMode_Linear;
  sd.mipmapFilter = WGPUMipmapFilterMode_Nearest;
  sd.lodMinClamp = 0.0f; sd.lodMaxClamp = 1.0f; sd.maxAnisotropy = 1;
  mesh.sampler = wgpuDeviceCreateSampler(device, &sd);

  // Upload decoded textures (sRGB for base colour, linear for normal/metal-rough),
  // then two neutral defaults: white and a flat (0,0,1) normal.
  auto uploadTexture = [&](uint32_t w, uint32_t h, const uint8_t* rgba, bool srgb) {
    WGPUTextureDescriptor td = {};
    td.usage = WGPUTextureUsage_TextureBinding | WGPUTextureUsage_CopyDst;
    td.dimension = WGPUTextureDimension_2D;
    td.size = { w, h, 1 };
    td.format = srgb ? WGPUTextureFormat_RGBA8UnormSrgb : WGPUTextureFormat_RGBA8Unorm;
    td.mipLevelCount = 1; td.sampleCount = 1;
    WGPUTexture tex = wgpuDeviceCreateTexture(device, &td);
    WGPUImageCopyTexture dst = {}; dst.texture = tex; dst.aspect = WGPUTextureAspect_All;
    WGPUTextureDataLayout layout = {}; layout.bytesPerRow = w * 4; layout.rowsPerImage = h;
    WGPUExtent3D ext = { w, h, 1 };
    wgpuQueueWriteTexture(queue, &dst, rgba, (size_t)w * h * 4, &layout, &ext);
    mesh.textures.push_back(tex);
    mesh.views.push_back(wgpuTextureCreateView(tex, nullptr));
    return (int)mesh.views.size() - 1;
  };
  for (const TextureData& t : data.textures)
    uploadTexture((uint32_t)t.width, (uint32_t)t.height, t.rgba.data(), t.srgb);
  const uint8_t white[4]      = { 255, 255, 255, 255 };
  const uint8_t flatNormal[4] = { 128, 128, 255, 255 };   // tangent-space (0,0,1)
  const int whiteIndex      = uploadTexture(1, 1, white, false);
  const int flatNormalIndex = uploadTexture(1, 1, flatNormal, false);

  // One bind group per submesh: uniform + its base/normal/metal-rough views (or defaults).
  for (const Submesh& sm : mesh.submeshes) {
    WGPUTextureView baseView   = mesh.views[sm.baseColor  >= 0 ? sm.baseColor  : whiteIndex];
    WGPUTextureView normalView = mesh.views[sm.normal     >= 0 ? sm.normal     : flatNormalIndex];
    WGPUTextureView mrView     = mesh.views[sm.metalRough >= 0 ? sm.metalRough : whiteIndex];
    WGPUBindGroupEntry bge[5] = {};
    bge[0].binding = 0; bge[0].buffer = mesh.uniformBuf; bge[0].size = sizeof(MeshUniforms);
    bge[1].binding = 1; bge[1].textureView = baseView;
    bge[2].binding = 2; bge[2].textureView = normalView;
    bge[3].binding = 3; bge[3].textureView = mrView;
    bge[4].binding = 4; bge[4].sampler = mesh.sampler;
    WGPUBindGroupDescriptor bgd = {};
    bgd.layout = bgl; bgd.entryCount = 5; bgd.entries = bge;
    mesh.bindGroups.push_back(wgpuDeviceCreateBindGroup(device, &bgd));
  }

  wgpuBindGroupLayoutRelease(bgl);
  return mesh;
}

// Load a vessel GLB and derive its on-water placement — a uniform scale to a
// consistent size, the keel origin (X/Z centred, lowest point to y=0), and a
// beam-based draught so the hull sits low in the water. Falls back to a cube.
static Mesh loadVessel(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat fmt, const std::string& path) {
  MeshData data = loadGltfMesh(path.c_str());
  if (!data.ok) data = makeCubeMesh();
  glm::vec3 bbMin(data.bbMin[0], data.bbMin[1], data.bbMin[2]);
  glm::vec3 bbMax(data.bbMax[0], data.bbMax[1], data.bbMax[2]);
  glm::vec3 center = 0.5f * (bbMin + bbMax);
  glm::vec3 extent = bbMax - bbMin;
  float maxExtent = std::max(extent.x, std::max(extent.y, extent.z));
  float fit = (maxExtent > 1e-6f) ? (2.0f / maxExtent) : 1.0f;
  Mesh mesh = createMesh(device, queue, fmt, data);
  mesh.shipScale  = fit * 3.0f;
  mesh.keelCenter = glm::vec3(center.x, bbMin.y, center.z);
  mesh.draft      = 0.53f * std::min(extent.x, extent.z) * mesh.shipScale;   // see JS floatDraft
  return mesh;
}

// Vessel slug -> GLB path (mirrors server/controllers/vessels.controller.js). The
// ship GLBs sit beside the baked SAILSIM_SHIP_MODEL (…/server/assets/geometry/).
static std::string geometryDir() {
  std::string m = SAILSIM_SHIP_MODEL;
  size_t slash = m.find_last_of('/');
  return slash == std::string::npos ? std::string(".") : m.substr(0, slash);
}
static std::string glbForSlug(const std::string& slug) {
  std::string file =
      slug == "sloop"       ? "bermuda_sloop_rigged.glb" :
      slug == "brig"        ? "brig.glb" :
      slug == "merchantman" ? "merchantman.glb" :
      slug == "pinnace"     ? "pinnace.glb" :
                              "pinnace.glb";   // starter hull is the safe fallback
  return geometryDir() + "/" + file;
}

