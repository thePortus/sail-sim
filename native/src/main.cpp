// Tiling value noise (the client bakes an equivalent 3-D noise atlas + weather map).
static float cn_lattice(int x, int y, int z, int P) {
  x = ((x % P) + P) % P; y = ((y % P) + P) % P; z = ((z % P) + P) % P;
  uint32_t n = (uint32_t)(x * 73856093) ^ (uint32_t)(y * 19349663) ^ (uint32_t)(z * 83492791);
  n = (n << 13) ^ n;
  n = n * (n * n * 15731u + 789221u) + 1376312589u;
  return (float)(n & 0x7fffffffu) / (float)0x7fffffff;
}
static float cn_smooth(float t) { return t * t * (3.0f - 2.0f * t); }
static float cn_lerp(float a, float b, float t) { return a + (b - a) * t; }
static float cn_valueNoise3(float fx, float fy, float fz, int P) {
  float ux = fx * P, uy = fy * P, uz = fz * P;
  int ix = (int)std::floor(ux), iy = (int)std::floor(uy), iz = (int)std::floor(uz);
  float tx = cn_smooth(ux - ix), ty = cn_smooth(uy - iy), tz = cn_smooth(uz - iz);
  auto L = [&](int dx, int dy, int dz) { return cn_lattice(ix + dx, iy + dy, iz + dz, P); };
  float c00 = cn_lerp(L(0,0,0), L(1,0,0), tx), c10 = cn_lerp(L(0,1,0), L(1,1,0), tx);
  float c01 = cn_lerp(L(0,0,1), L(1,0,1), tx), c11 = cn_lerp(L(0,1,1), L(1,1,1), tx);
  return cn_lerp(cn_lerp(c00, c10, ty), cn_lerp(c01, c11, ty), tz);
}

static Clouds createClouds(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat) {
  Clouds c;
  // 3-D noise atlas: 32^3 tiling value noise packed 8x4 into 256x128 R8.
  std::vector<uint8_t> atlas((size_t)256 * 128, 0);
  for (int z = 0; z < 32; ++z) {
    int col = z % 8, row = z / 8;
    for (int y = 0; y < 32; ++y)
      for (int x = 0; x < 32; ++x) {
        float f = 0.55f * cn_valueNoise3(x / 32.0f, y / 32.0f, z / 32.0f, 4)
                + 0.30f * cn_valueNoise3(x / 32.0f, y / 32.0f, z / 32.0f, 8)
                + 0.15f * cn_valueNoise3(x / 32.0f, y / 32.0f, z / 32.0f, 16);
        atlas[(size_t)(row * 32 + y) * 256 + (col * 32 + x)] = (uint8_t)(glm::clamp(f, 0.0f, 1.0f) * 255.0f);
      }
  }
  // Weather map: 256^2 tiling FBM (use z=0 slice of the value noise across octaves).
  std::vector<uint8_t> weather((size_t)256 * 256, 0);
  for (int y = 0; y < 256; ++y)
    for (int x = 0; x < 256; ++x) {
      float fx = x / 256.0f, fy = y / 256.0f, w = 0.0f, amp = 0.5f; int P = 3;
      for (int o = 0; o < 5; ++o) { w += amp * cn_valueNoise3(fx, fy, 0.37f, P); amp *= 0.5f; P *= 2; }
      weather[(size_t)y * 256 + x] = (uint8_t)(glm::clamp(w, 0.0f, 1.0f) * 255.0f);
    }

  auto makeR8 = [&](int w, int h, const uint8_t* data) {
    WGPUTextureDescriptor td = {}; td.usage = WGPUTextureUsage_TextureBinding | WGPUTextureUsage_CopyDst;
    td.dimension = WGPUTextureDimension_2D; td.size = { (uint32_t)w, (uint32_t)h, 1 };
    td.format = WGPUTextureFormat_R8Unorm; td.mipLevelCount = 1; td.sampleCount = 1;
    WGPUTexture tex = wgpuDeviceCreateTexture(device, &td);
    WGPUImageCopyTexture dst = {}; dst.texture = tex; dst.aspect = WGPUTextureAspect_All;
    WGPUTextureDataLayout dl = {}; dl.bytesPerRow = (uint32_t)w; dl.rowsPerImage = (uint32_t)h;
    WGPUExtent3D ext = { (uint32_t)w, (uint32_t)h, 1 };
    wgpuQueueWriteTexture(queue, &dst, data, (size_t)w * h, &dl, &ext);
    return tex;
  };
  c.noiseTex   = makeR8(256, 128, atlas.data());
  c.weatherTex = makeR8(256, 256, weather.data());
  c.noiseView   = wgpuTextureCreateView(c.noiseTex, nullptr);
  c.weatherView = wgpuTextureCreateView(c.weatherTex, nullptr);

  auto makeSampler = [&](WGPUAddressMode mode) {
    WGPUSamplerDescriptor sd = {}; sd.addressModeU = mode; sd.addressModeV = mode; sd.addressModeW = mode;
    sd.magFilter = WGPUFilterMode_Linear; sd.minFilter = WGPUFilterMode_Linear; sd.mipmapFilter = WGPUMipmapFilterMode_Nearest;
    sd.lodMinClamp = 0.0f; sd.lodMaxClamp = 1.0f; sd.maxAnisotropy = 1;
    return wgpuDeviceCreateSampler(device, &sd);
  };
  c.noiseSamp   = makeSampler(WGPUAddressMode_ClampToEdge);
  c.weatherSamp = makeSampler(WGPUAddressMode_MirrorRepeat);

  WGPUBufferDescriptor ubd = {}; ubd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; ubd.size = sizeof(CloudU);
  c.uniformBuf = wgpuDeviceCreateBuffer(device, &ubd);
  c.module = makeWGSL(device, CLOUDS_WGSL);

  WGPUBindGroupLayoutEntry ble[5] = {};
  ble[0].binding = 0; ble[0].visibility = WGPUShaderStage_Fragment; ble[0].buffer.type = WGPUBufferBindingType_Uniform;
  ble[1].binding = 1; ble[1].visibility = WGPUShaderStage_Fragment; ble[1].texture.sampleType = WGPUTextureSampleType_Float; ble[1].texture.viewDimension = WGPUTextureViewDimension_2D;
  ble[2].binding = 2; ble[2].visibility = WGPUShaderStage_Fragment; ble[2].sampler.type = WGPUSamplerBindingType_Filtering;
  ble[3].binding = 3; ble[3].visibility = WGPUShaderStage_Fragment; ble[3].texture.sampleType = WGPUTextureSampleType_Float; ble[3].texture.viewDimension = WGPUTextureViewDimension_2D;
  ble[4].binding = 4; ble[4].visibility = WGPUShaderStage_Fragment; ble[4].sampler.type = WGPUSamplerBindingType_Filtering;
  WGPUBindGroupLayoutDescriptor bgld = {}; bgld.entryCount = 5; bgld.entries = ble;
  WGPUBindGroupLayout bgl = wgpuDeviceCreateBindGroupLayout(device, &bgld);
  WGPUPipelineLayoutDescriptor pld = {}; pld.bindGroupLayoutCount = 1; pld.bindGroupLayouts = &bgl;
  WGPUPipelineLayout pl = wgpuDeviceCreatePipelineLayout(device, &pld);

  // March writes the offscreen RGBA16F cloud buffer (no blend — cleared to 0, the
  // depth test lets geometry occlude); depth-test (no write) against the scene.
  WGPUColorTargetState target = {}; target.format = kCloudFormat; target.writeMask = WGPUColorWriteMask_All;
  WGPUDepthStencilState ds = {}; ds.format = kDepthFormat; ds.depthWriteEnabled = false; ds.depthCompare = WGPUCompareFunction_LessEqual;
  ds.stencilFront.compare = WGPUCompareFunction_Always; ds.stencilBack.compare = WGPUCompareFunction_Always;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;
  WGPUFragmentState frag = {}; frag.module = c.module; frag.entryPoint = "fs_main"; frag.targetCount = 1; frag.targets = &target;
  WGPURenderPipelineDescriptor rpd = {}; rpd.layout = pl;
  rpd.vertex.module = c.module; rpd.vertex.entryPoint = "vs_main";
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  rpd.depthStencil = &ds; rpd.multisample.count = 1; rpd.multisample.mask = 0xFFFFFFFFu; rpd.fragment = &frag;
  c.pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);
  wgpuPipelineLayoutRelease(pl);

  WGPUBindGroupEntry bge[5] = {};
  bge[0].binding = 0; bge[0].buffer = c.uniformBuf; bge[0].size = sizeof(CloudU);
  bge[1].binding = 1; bge[1].textureView = c.noiseView;
  bge[2].binding = 2; bge[2].sampler = c.noiseSamp;
  bge[3].binding = 3; bge[3].textureView = c.weatherView;
  bge[4].binding = 4; bge[4].sampler = c.weatherSamp;
  WGPUBindGroupDescriptor bgd = {}; bgd.layout = bgl; bgd.entryCount = 5; bgd.entries = bge;
  c.bindGroup = wgpuDeviceCreateBindGroup(device, &bgd);
  wgpuBindGroupLayoutRelease(bgl);

  // ── Denoise / composite pipeline: 5x5 bilateral over the cloud buffer, blended
  //    (premultiplied) onto the swapchain. Its bind group (which references the
  //    resizable cloud buffer) is rebuilt in the render loop. ──
  c.cloudSamp = makeSampler(WGPUAddressMode_ClampToEdge);
  WGPUBufferDescriptor dud = {}; dud.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; dud.size = 16;
  c.denoiseUniform = wgpuDeviceCreateBuffer(device, &dud);
  c.denoiseModule = makeWGSL(device, CLOUDS_DENOISE_WGSL);

  WGPUBindGroupLayoutEntry dble[3] = {};
  dble[0].binding = 0; dble[0].visibility = WGPUShaderStage_Fragment; dble[0].buffer.type = WGPUBufferBindingType_Uniform;
  dble[1].binding = 1; dble[1].visibility = WGPUShaderStage_Fragment; dble[1].texture.sampleType = WGPUTextureSampleType_Float; dble[1].texture.viewDimension = WGPUTextureViewDimension_2D;
  dble[2].binding = 2; dble[2].visibility = WGPUShaderStage_Fragment; dble[2].sampler.type = WGPUSamplerBindingType_Filtering;
  WGPUBindGroupLayoutDescriptor dbgld = {}; dbgld.entryCount = 3; dbgld.entries = dble;
  c.denoiseBGL = wgpuDeviceCreateBindGroupLayout(device, &dbgld);
  WGPUPipelineLayoutDescriptor dpld = {}; dpld.bindGroupLayoutCount = 1; dpld.bindGroupLayouts = &c.denoiseBGL;
  WGPUPipelineLayout dpl = wgpuDeviceCreatePipelineLayout(device, &dpld);

  WGPUBlendState dblend = {};
  dblend.color.srcFactor = WGPUBlendFactor_One; dblend.color.dstFactor = WGPUBlendFactor_OneMinusSrcAlpha; dblend.color.operation = WGPUBlendOperation_Add;
  dblend.alpha = dblend.color;
  WGPUColorTargetState dtarget = {}; dtarget.format = colorFormat; dtarget.writeMask = WGPUColorWriteMask_All; dtarget.blend = &dblend;
  WGPUDepthStencilState dds = {}; dds.format = kDepthFormat; dds.depthWriteEnabled = false; dds.depthCompare = WGPUCompareFunction_Always;
  dds.stencilFront.compare = WGPUCompareFunction_Always; dds.stencilBack.compare = WGPUCompareFunction_Always;
  dds.stencilReadMask = 0xFFFFFFFFu; dds.stencilWriteMask = 0xFFFFFFFFu;
  WGPUFragmentState dfrag = {}; dfrag.module = c.denoiseModule; dfrag.entryPoint = "fs_main"; dfrag.targetCount = 1; dfrag.targets = &dtarget;
  WGPURenderPipelineDescriptor drpd = {}; drpd.layout = dpl;
  drpd.vertex.module = c.denoiseModule; drpd.vertex.entryPoint = "vs_main";
  drpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  drpd.depthStencil = &dds; drpd.multisample.count = 1; drpd.multisample.mask = 0xFFFFFFFFu; drpd.fragment = &dfrag;
  c.denoisePipeline = wgpuDeviceCreateRenderPipeline(device, &drpd);
  wgpuPipelineLayoutRelease(dpl);
  return c;
}

int main(int argc, char** argv) {
  // Flush per line so `[spike] …` progress shows even when piped or killed.
  std::setvbuf(stdout, nullptr, _IOLBF, 0);

  // Model to draw: argv[1] > $SAILSIM_MODEL > the ship (default) > rock > cube.
  const char* modelArg = (argc > 1) ? argv[1] : std::getenv("SAILSIM_MODEL");

  // Optional headless cap: render N frames then exit cleanly (for CI / smoke tests).
  const char* maxFramesEnv = std::getenv("SAILSIM_MAX_FRAMES");
  const long maxFrames = maxFramesEnv ? std::atol(maxFramesEnv) : 0;
  long frame = 0;

  // Headless screenshot: SAILSIM_SHOT=out.png renders to a chosen frame (default
  // 240, so the FFT/foam has settled), writes a PNG, and exits.
  const char* shotPath = std::getenv("SAILSIM_SHOT");
  const long shotFrame = shotPath ? (maxFramesEnv ? maxFrames : 240) : -1;

  // Headless auth round-trip test: exercises net_auth against the live server with
  // no window. SAILSIM_AUTH_TEST=login|register, SAILSIM_AUTH_USER / _PASS / _CALLSIGN.
  // With no user set it posts a bogus login to verify connectivity + error parsing.
  if (const char* authMode = std::getenv("SAILSIM_AUTH_TEST")) {
    const char* host = std::getenv("SAILSIM_HOST"); if (!host) host = "localhost";
    const char* portEnv = std::getenv("SAILSIM_PORT");
    const int port = portEnv ? std::atoi(portEnv) : 9080;
    const char* u  = std::getenv("SAILSIM_AUTH_USER");
    const char* p  = std::getenv("SAILSIM_AUTH_PASS");
    const char* cs = std::getenv("SAILSIM_AUTH_CALLSIGN");
    std::string user = u ? u : "no_such_user_probe";
    std::string pass = p ? p : "definitely_wrong_password";
    const char* tok = std::getenv("SAILSIM_AUTH_TOKEN");
    net::AuthResult r =
        (std::string(authMode) == "register") ? net::registerUser(host, port, user, cs ? cs : user, pass)
      : (std::string(authMode) == "me")       ? net::me(host, port, tok ? tok : "")
      :                                          net::login(host, port, user, pass);
    std::printf("[auth-test] %s %s:%d user=%s -> ok=%d status=%d\n",
                authMode, host, port, user.c_str(), (int)r.ok, r.status);
    if (r.ok) std::printf("[auth-test] callsign=%s role=%s token=%.16s...\n",
                          r.callsign.c_str(), r.role.c_str(), r.token.c_str());
    else      std::printf("[auth-test] error=\"%s\"\n", r.error.c_str());
    return r.ok ? EXIT_SUCCESS : EXIT_FAILURE;
  }

  // Headless WebSocket gameplay test: login, open the socket, exchange a few
  // messages, report what came back. SAILSIM_WS_TEST=1 (+ SAILSIM_AUTH_USER/_PASS).
  if (std::getenv("SAILSIM_WS_TEST")) {
    const char* host = std::getenv("SAILSIM_HOST"); if (!host) host = "localhost";
    const char* portEnv = std::getenv("SAILSIM_PORT");
    const int port = portEnv ? std::atoi(portEnv) : 9080;
    const char* u = std::getenv("SAILSIM_AUTH_USER");
    const char* p = std::getenv("SAILSIM_AUTH_PASS");
    net::AuthResult lr = net::login(host, port, u ? u : "native_probe_01", p ? p : "testpass123");
    if (!lr.ok) { std::printf("[ws-test] login failed: %s\n", lr.error.c_str()); return EXIT_FAILURE; }

    mp::Client c;
    c.connect(host, port, lr.token);
    for (int i = 0; i < 60 && c.state() == mp::ConnState::Connecting; ++i)
      std::this_thread::sleep_for(std::chrono::milliseconds(50));   // await open (<=3s)

    if (c.state() == mp::ConnState::Open) {
      mp::PlayerUpdate pu; pu.x = 10; pu.z = 20; pu.heading = 1.0f; pu.speed = 3.0f;
      pu.sailState = "full"; pu.vesselName = "Merchantman"; pu.vesselSlug = "merchantman";
      pu.callsign = lr.callsign;
      c.sendUpdate(pu, 0);
      c.sendChat("ahoy from the native ws-test");   // global chat echoes back to the sender
      std::this_thread::sleep_for(std::chrono::milliseconds(1200));   // let snapshot/wave/chat arrive
    }
    mp::WaveState wv = c.wave();
    std::vector<mp::ChatMessage> chat = c.drainChat();
    std::printf("[ws-test] state=%d myId=%s players=%d wave.valid=%d wind=%.1f beaufort=%d\n",
                (int)c.state(), c.myId().c_str(), (int)c.players().size(),
                (int)wv.valid, wv.windSpeed, wv.beaufort);
    std::printf("[ws-test] chat lines=%d%s%s\n", (int)chat.size(),
                chat.empty() ? "" : ", last: ", chat.empty() ? "" : chat.back().text.c_str());
    bool ok = (c.state() == mp::ConnState::Open);
    c.close();
    return ok ? EXIT_SUCCESS : EXIT_FAILURE;
  }

  // Headless admin-endpoint test: login, set a weather override, confirm the WS
  // wave_state pins to it, then clear it and check the teleport gate.
  // SAILSIM_ADMIN_TEST=1 (+ SAILSIM_AUTH_USER/_PASS — needs role admin|owner).
  if (std::getenv("SAILSIM_ADMIN_TEST")) {
    const char* host = std::getenv("SAILSIM_HOST"); if (!host) host = "localhost";
    const char* portEnv = std::getenv("SAILSIM_PORT");
    const int port = portEnv ? std::atoi(portEnv) : 9080;
    const char* u = std::getenv("SAILSIM_AUTH_USER");
    const char* p = std::getenv("SAILSIM_AUTH_PASS");
    net::AuthResult lr = net::login(host, port, u ? u : "sail-sim-owner", p ? p : "password");
    if (!lr.ok) { std::printf("[admin-test] login failed: %s\n", lr.error.c_str()); return EXIT_FAILURE; }
    std::printf("[admin-test] logged in as %s (role=%s)\n", lr.username.c_str(), lr.role.c_str());

    net::AdminResult r = net::setWeatherOverride(host, port, lr.token, 17.5f, 123.0f, 0.9f);
    std::printf("[admin-test] set override    -> ok=%d status=%d %s\n", (int)r.ok, r.status, r.error.c_str());

    mp::Client c;                       // watch the broadcast pin to the override
    c.connect(host, port, lr.token);
    for (int i = 0; i < 80 && c.state() == mp::ConnState::Connecting; ++i)
      std::this_thread::sleep_for(std::chrono::milliseconds(50));
    std::this_thread::sleep_for(std::chrono::milliseconds(1500));
    mp::WaveState wv = c.wave();
    std::printf("[admin-test] wave_state      -> valid=%d wind=%.1f from=%.0f cloud=%.2f override=%d\n",
                (int)wv.valid, wv.windSpeed, wv.windBearing, wv.cloudiness, (int)wv.overrideOn);
    bool pinned = wv.valid && wv.overrideOn &&
                  std::abs(wv.windSpeed - 17.5f) < 0.1f && std::abs(wv.windBearing - 123.0f) < 0.1f;

    net::AdminResult tp = net::teleport(host, port, lr.token, 1000.0f, -2000.0f);
    std::printf("[admin-test] teleport gate   -> ok=%d status=%d %s\n", (int)tp.ok, tp.status, tp.error.c_str());
    net::AdminResult to = net::setTimeOffset(host, port, lr.token, 6.5f);
    std::printf("[admin-test] time offset     -> ok=%d status=%d %s\n", (int)to.ok, to.status, to.error.c_str());
    net::AdminResult tc = net::clearTimeOffset(host, port, lr.token);
    std::printf("[admin-test] clear time      -> ok=%d status=%d %s\n", (int)tc.ok, tc.status, tc.error.c_str());
    net::AdminResult cl = net::clearWeatherOverride(host, port, lr.token);
    std::printf("[admin-test] clear override  -> ok=%d status=%d %s\n", (int)cl.ok, cl.status, cl.error.c_str());
    c.close();

    bool ok = r.ok && pinned && tp.ok && to.ok && tc.ok && cl.ok;
    std::printf("[admin-test] %s\n", ok ? "PASS" : "FAIL");
    return ok ? EXIT_SUCCESS : EXIT_FAILURE;
  }

  // Headless terrain-data test: fetch + decode the heightfield and sample it.
  if (std::getenv("SAILSIM_TERRAIN_TEST")) {
    const char* host = std::getenv("SAILSIM_HOST"); if (!host) host = "localhost";
    const char* portEnv = std::getenv("SAILSIM_PORT");
    const int port = portEnv ? std::atoi(portEnv) : 9080;
    terrain::Terrain terr;
    if (!terr.load(host, port)) return EXIT_FAILURE;
    const terrain::Manifest& m = terr.manifest();
    std::printf("[terrain-test] origin(0,0) elev=%.1f m (%s)\n",
                terr.elevation(0, 0), terr.isLand(0, 0) ? "LAND" : "water");
    // Sample near the first few harbors — the shore point should read ~0 m.
    for (size_t i = 0; i < m.harbors.size() && i < 4; ++i) {
      const terrain::Harbor& h = m.harbors[i];
      std::printf("[terrain-test] harbor '%s' (%.0f,%.0f) shore=%.1f m  inland+200m=%.1f m\n",
                  h.name.c_str(), h.x, h.z, terr.elevation(h.x, h.z),
                  terr.elevation(h.x, h.z + 200.0f));
    }
    return EXIT_SUCCESS;
  }

#if defined(WEBGPU_BACKEND_WGPU)
  // Surface wgpu-native's internal logs (including WGSL compile errors).
  wgpuSetLogLevel(WGPULogLevel_Warn);
  wgpuSetLogCallback([](WGPULogLevel level, char const* msg, void*) {
    std::fprintf(stderr, "[wgpu] (%d) %s\n", (int)level, msg ? msg : "");
  }, nullptr);
#endif

  // Headless compute-only mode: run the ocean-FFT readback test with no window,
  // then exit 0/1. Ideal for CI or a quick Windows/D3D12 check.
  if (std::getenv("SAILSIM_FFT_ONLY")) {
    WGPUInstanceDescriptor instDesc = {};
    WGPUInstance inst = wgpuCreateInstance(&instDesc);
    WGPURequestAdapterOptions ao = {};
    ao.powerPreference = WGPUPowerPreference_HighPerformance;
    WGPUAdapter ad = requestAdapterSync(inst, &ao);
    if (!ad) return EXIT_FAILURE;
    WGPUAdapterProperties props = {};
    wgpuAdapterGetProperties(ad, &props);
    std::printf("[spike] headless FFT test — backend=%s device=%s\n",
                backendTypeName(props.backendType), props.name ? props.name : "?");
    WGPUDeviceDescriptor dd = {};
    dd.label = "sailsim-device";
    WGPUDevice dev = requestDeviceSync(ad, &dd);
    if (!dev) return EXIT_FAILURE;
    wgpuDeviceSetUncapturedErrorCallback(dev, onDeviceError, nullptr);
    WGPUQueue q = wgpuDeviceGetQueue(dev);
    const bool ok = runInitialSpectrumTest(dev, q);
    wgpuQueueRelease(q);
    wgpuDeviceRelease(dev);
    wgpuAdapterRelease(ad);
    wgpuInstanceRelease(inst);
    return ok ? EXIT_SUCCESS : EXIT_FAILURE;
  }

  if (!glfwInit()) {
    std::fprintf(stderr, "[spike] glfwInit failed\n");
    return EXIT_FAILURE;
  }

  // WebGPU manages the drawing surface; tell GLFW not to create an OpenGL context.
  glfwWindowHint(GLFW_CLIENT_API, GLFW_NO_API);
  GLFWwindow* window = glfwCreateWindow(1280, 720, "sail-sim native — Phase 1: camera + depth", nullptr, nullptr);
  if (!window) {
    std::fprintf(stderr, "[spike] glfwCreateWindow failed\n");
    glfwTerminate();
    return EXIT_FAILURE;
  }
  glfwSetScrollCallback(window, onScroll);   // mouse-wheel zoom

  // 1. Instance
  WGPUInstanceDescriptor instanceDesc = {};
  WGPUInstance instance = wgpuCreateInstance(&instanceDesc);
  if (!instance) {
    std::fprintf(stderr, "[spike] wgpuCreateInstance failed\n");
    return EXIT_FAILURE;
  }

  // 2. Surface (per-OS creation hidden inside glfw3webgpu)
  WGPUSurface surface = glfwGetWGPUSurface(instance, window);

  // 3. Adapter
  WGPURequestAdapterOptions adapterOpts = {};
  adapterOpts.compatibleSurface = surface;
  adapterOpts.powerPreference = WGPUPowerPreference_HighPerformance;
  WGPUAdapter adapter = requestAdapterSync(instance, &adapterOpts);
  if (!adapter) return EXIT_FAILURE;

  // Report which native backend was selected — the visible proof of the thesis.
  // wgpuAdapterGetProperties is present in both wgpu-native and Dawn 6512.
  WGPUAdapterProperties adapterProps = {};
  wgpuAdapterGetProperties(adapter, &adapterProps);
  std::printf("[spike] adapter: backend=%s  vendor=%s  device=%s\n",
              backendTypeName(adapterProps.backendType),
              adapterProps.vendorName ? adapterProps.vendorName : "?",
              adapterProps.name ? adapterProps.name : "?");

  // 4. Device + queue
  WGPUDeviceDescriptor deviceDesc = {};
  deviceDesc.label = "sailsim-device";
  WGPUDevice device = requestDeviceSync(adapter, &deviceDesc);
  if (!device) return EXIT_FAILURE;

  wgpuDeviceSetUncapturedErrorCallback(device, onDeviceError, nullptr);

  WGPUQueue queue = wgpuDeviceGetQueue(device);

  // Phase 0 criteria 3-5: prove the ocean-FFT WGSL runs natively and reads back.
  runInitialSpectrumTest(device, queue);

  // 5. Configure the surface (swapchain)
  WGPUSurfaceCapabilities caps = {};
  wgpuSurfaceGetCapabilities(surface, adapter, &caps);
  WGPUTextureFormat surfaceFormat = caps.formatCount > 0 ? caps.formats[0] : WGPUTextureFormat_BGRA8Unorm;

  int fbWidth = 0, fbHeight = 0;
  glfwGetFramebufferSize(window, &fbWidth, &fbHeight);

  WGPUSurfaceConfiguration surfaceConfig = {};
  surfaceConfig.device = device;
  surfaceConfig.format = surfaceFormat;
  surfaceConfig.usage = WGPUTextureUsage_RenderAttachment;
  surfaceConfig.width = (uint32_t)fbWidth;
  surfaceConfig.height = (uint32_t)fbHeight;
  surfaceConfig.presentMode = WGPUPresentMode_Fifo;   // vsync
  surfaceConfig.alphaMode = WGPUCompositeAlphaMode_Auto;
  if (shotPath) surfaceConfig.usage |= WGPUTextureUsage_CopySrc;   // allow screenshot readback
  wgpuSurfaceConfigure(surface, &surfaceConfig);

  std::printf("[spike] surface configured: %dx%d format=%d — entering render loop\n",
              fbWidth, fbHeight, (int)surfaceFormat);

  // Vessels are loaded lazily by slug and cached — you and remote players share a
  // hull's geometry (one copy), each drawn as its own instance. The owned hull is
  // server-authoritative (arrives in the "wallet" message); a command-line/env
  // model override (SAILSIM_MODEL / argv[1]) forces a specific GLB for testing.
  std::map<std::string, Mesh> vessels;
  auto vesselFor = [&](const std::string& slug) -> Mesh& {
    auto it = vessels.find(slug);
    if (it != vessels.end()) return it->second;
    std::string path = glbForSlug(slug);
    std::printf("[vessel] loading '%s' <- %s\n", slug.c_str(), path.c_str());
    auto res = vessels.emplace(slug, loadVessel(device, queue, surfaceFormat, path, slug));
    return res.first->second;
  };
  std::string ownVesselSlug;
  const bool ownVesselForced = (modelArg != nullptr);
  if (ownVesselForced) {
    // Infer the vessel slug from the override filename so it uses the real spec
    // (orientation/scale), else fall back to a neutral "__cli" default.
    std::string mp = modelArg, cliSlug = "__cli";
    if (mp.find("merchantman") != std::string::npos)      cliSlug = "merchantman";
    else if (mp.find("brig") != std::string::npos)        cliSlug = "brig";
    else if (mp.find("pinnace") != std::string::npos)     cliSlug = "pinnace";
    else if (mp.find("sloop") != std::string::npos || mp.find("bermuda") != std::string::npos) cliSlug = "sloop";
    vessels.emplace(cliSlug, loadVessel(device, queue, surfaceFormat, modelArg, cliSlug));
    ownVesselSlug = cliSlug;
  }

  Ocean ocean = createOcean(device, queue, surfaceFormat);
  Sky sky = createSky(device, queue, surfaceFormat);
  // Celestial textures (moon colour map + all-sky star map) fetched + decoded off
  // the render thread; uploaded and wired into the sky bind group once ready.
  std::future<sky::Image> moonFuture = std::async(std::launch::async,
      [kHost = std::string("localhost"), kPortSky = 9080] { return sky::fetch(kHost, kPortSky, "moon"); });
  std::future<sky::Image> starsFuture = std::async(std::launch::async,
      [kHost = std::string("localhost"), kPortSky = 9080] { return sky::fetch(kHost, kPortSky, "stars", 4096); });
  // Biome tiles + splat map (the Angular terrain skinning textures), off-thread.
  std::future<biome::Set> biomeFuture = std::async(std::launch::async,
      [kHost = std::string("localhost"), kPortSky = 9080] { return biome::fetchAll(kHost, kPortSky); });
  bool biomeReady = false;

  // World map (M key / minimap click; mirrors the browser's minimap.component):
  // a colour-graded heightfield raster baked once at terrain-ready, drawn through
  // ImGui with town/player/ship markers, zoom + pan, and admin right-click teleport.
  WGPUTexture mapTex = nullptr; WGPUTextureView mapView = nullptr;
  bool  mapExpanded = std::getenv("SAILSIM_MAP") != nullptr, mapViewInit = false;   // env = open at start (screenshot tests)
  float mapZoom = 1.0f, mapVCX = 0.0f, mapVCZ = 0.0f;   // view centre (world) for zoom/pan
  float mapTpX = 0.0f, mapTpZ = 0.0f;                   // right-click teleport target
  bool moonReady = false, starsReady = false;
  TerrainRender terrainR = createTerrainRender(device, queue, surfaceFormat);
  Clouds clouds = createClouds(device, queue, surfaceFormat);
  glm::vec2 cloudDrift(0.0f);   // accumulated wind drift (metres), integrated per frame
  // Weather state, eased toward Beaufort-driven targets each frame (mirrors the
  // client's cloud.service): cloudiness/storminess shape the clouds, seaAmp the swell.
  float cloudiness = 0.25f, storminess = 0.0f, seaAmp = 1.0f;

  // FFT ocean — 3 cascades (250 / 17 / 5 m tiles) with split cutoff bands so they
  // don't double-count wavelengths. 256² each. Prime one frame + sanity-check.
  const float B1 = 6.2831853f / 17.0f * 6.0f;
  const float B2 = 6.2831853f / 5.0f  * 6.0f;
  OceanFFT c0(device, queue, 256, 250.0f, 0.0001f, B1);
  OceanFFT c1(device, queue, 256, 17.0f,  B1,      B2);
  OceanFFT c2(device, queue, 256, 5.0f,   B2,      9999.0f);
  for (OceanFFT* c : { &c0, &c1, &c2 }) c->initSpectrum();
  // Pre-warm the sim: the turbulence/foam field accumulates only ~0.008/frame in the
  // merger, so it climbs from 0 (which reads as a full-surface whiteout in the foam
  // term) over a few hundred frames. Advance it here so the FIRST visible frame is at
  // steady state — foam on the crests, not the whole sea. ~5 s of sim, runs in a blink.
  for (int i = 0; i < 300; ++i) {
    float wt = (float)i * (1.0f / 60.0f);
    for (OceanFFT* c : { &c0, &c1, &c2 }) c->update(wt, 1.0f / 60.0f);
  }
  c0.sanityCheck();

  uint32_t curW = (uint32_t)fbWidth, curH = (uint32_t)fbHeight;
  WGPUTexture depthTex = makeDepthTexture(device, curW, curH);
  WGPUTextureView depthView = wgpuTextureCreateView(depthTex, nullptr);
  // Planar reflection target (colour + its own depth).
  WGPUTexture reflTex = makeColorRTT(device, curW, curH, surfaceFormat);
  WGPUTextureView reflView = wgpuTextureCreateView(reflTex, nullptr);
  WGPUTexture reflDepth = makeDepthTexture(device, curW, curH);
  WGPUTextureView reflDepthView = wgpuTextureCreateView(reflDepth, nullptr);
  // Offscreen cloud buffer (RGBA16F): the ray march writes here, then the denoise
  // pass filters it onto the frame. Its bind group is rebuilt when it resizes.
  WGPUTexture cloudTex = makeColorRTT(device, curW, curH, kCloudFormat);
  WGPUTextureView cloudView = wgpuTextureCreateView(cloudTex, nullptr);
  auto buildDenoiseBG = [&]() {
    WGPUBindGroupEntry e[3] = {};
    e[0].binding = 0; e[0].buffer = clouds.denoiseUniform; e[0].size = 16;
    e[1].binding = 1; e[1].textureView = cloudView;
    e[2].binding = 2; e[2].sampler = clouds.cloudSamp;
    WGPUBindGroupDescriptor d = {}; d.layout = clouds.denoiseBGL; d.entryCount = 3; d.entries = e;
    return wgpuDeviceCreateBindGroup(device, &d);
  };
  WGPUBindGroup denoiseBG = buildDenoiseBG();

  // God-ray occlusion mask (sun bright where sky shows, occluded by geometry), plus
  // a clamp sampler and the two-pass godray pipeline.
  WGPUTexture grTex = makeColorRTT(device, curW, curH, kGodrayFormat);
  WGPUTextureView grView = wgpuTextureCreateView(grTex, nullptr);
  WGPUSamplerDescriptor grSampDesc = {};
  grSampDesc.addressModeU = WGPUAddressMode_ClampToEdge; grSampDesc.addressModeV = WGPUAddressMode_ClampToEdge;
  grSampDesc.addressModeW = WGPUAddressMode_ClampToEdge;
  grSampDesc.magFilter = WGPUFilterMode_Linear; grSampDesc.minFilter = WGPUFilterMode_Linear;
  grSampDesc.mipmapFilter = WGPUMipmapFilterMode_Nearest; grSampDesc.lodMaxClamp = 1.0f; grSampDesc.maxAnisotropy = 1;
  WGPUSampler grSampler = wgpuDeviceCreateSampler(device, &grSampDesc);
  Godrays godrays = createGodrays(device, surfaceFormat, grSampler, grView);

  // Sailing state — arrow keys / WASD steer and trim sail; the ship sails the sea.
  float shipX = 0.0f, shipZ = 0.0f, shipHeading = 0.0f, shipSpeed = 0.0f, sail = 0.35f;
  // Ported force-based sailing physics (sail_physics.hpp). shipX/Z/heading/speed
  // mirror the vessel each frame for the camera/ocean/network.
  sail::Vessel vessel;
  sail::Rig    vrig = sail::rigForSlug("sloop");
  bool prevRaise = false, prevLower = false, prevAnchor = false;
  glm::vec3 ownBuoy(0.0f);   // heave, pitch, roll for the local hull
  // Bow orientation is now per-vessel (Mesh.bowYaw, from vesselSpecFor). World
  // velocity = knots x TRAVEL_SCALE — the client's map-compression factor (must
  // match server combat-constants.js) so distances feel right at realistic knots.
  const float kTravelScale = 3.0f;
  // Scale the wave-sim clock. Real-time (1.0) reads as too-fast chop; too slow (~0.45)
  // makes tall waves look gelatinous ("jelly") because they move slower than their
  // steepness implies. 0.6 is the compromise — a calmer swell that still flows.
  const float kWaveSpeed = 0.6f;

  // Orbit camera: chase behind the ship by default; hold LMB + drag to orbit, wheel to
  // zoom. camYawOffset is relative to the heading (0 = directly astern), so the camera
  // keeps chasing as the ship turns while any drag offset is preserved.
  float camYawOffset = 0.0f, camPitch = 0.43f, camDist = 14.3f;
  bool  camFramed = false;   // set the default chase distance from the vessel size once
  double lastMouseX = 0.0, lastMouseY = 0.0;
  glfwGetCursorPos(window, &lastMouseX, &lastMouseY);

  // ── Dear ImGui: login screen + in-game HUD ────────────────────────────────
  IMGUI_CHECKVERSION();
  ImGui::CreateContext();
  ImGuiIO& imio = ImGui::GetIO();
  imio.IniFilename = nullptr;   // don't write imgui.ini next to the exe
  // Embedded fonts, rasterised at the display's content scale for crisp text on
  // HiDPI; FontGlobalScale then brings them back to logical size. Inter is the
  // default (body) font; Cinzel is kept for titles (pushed where needed).
  float uiScaleX = 1.0f, uiScaleY = 1.0f;
  glfwGetWindowContentScale(window, &uiScaleX, &uiScaleY);
  if (uiScaleX <= 0.0f) uiScaleX = 1.0f;
  ImFontConfig fontCfg;
  fontCfg.FontDataOwnedByAtlas = false;   // static arrays — don't let ImGui free them
  imio.Fonts->AddFontFromMemoryTTF((void*)UI_FONT_BODY, (int)UI_FONT_BODY_SIZE,
                                   18.0f * uiScaleX, &fontCfg);   // default = body
  ImFont* fontTitle = imio.Fonts->AddFontFromMemoryTTF((void*)UI_FONT_TITLE, (int)UI_FONT_TITLE_SIZE,
                                                       30.0f * uiScaleX, &fontCfg);
  imio.FontGlobalScale = 1.0f / uiScaleX;
  styleSailSim();
  ImGui_ImplGlfw_InitForOther(window, true);
  ImGui_ImplWGPU_InitInfo imguiInit;
  imguiInit.Device = device;
  imguiInit.NumFramesInFlight = 3;
  imguiInit.RenderTargetFormat = surfaceFormat;
  imguiInit.DepthStencilFormat = kDepthFormat;   // must match the main pass's depth attachment
  ImGui_ImplWGPU_Init(&imguiInit);

  // App state: sign in first, then sail. The ocean scene renders behind the login.
  enum class AppState { Login, Connecting, Sailing };
  AppState appState = AppState::Login;
  const std::string kHost = "localhost";
  const int         kPort = 9080;
  char uiUser[64] = "", uiPass[64] = "", uiCallsign[64] = "";
  bool uiRegisterMode = false, uiRemember = false;
  std::string uiError, authToken, authCallsign, authUsername, authRole;
  std::future<net::AuthResult> authFuture;

  // Admin panel (backtick toggles; admin/owner role only — mirrors the browser
  // client's admin-panel.component). Weather/time overrides are server-authoritative:
  // the server broadcasts the change to every player; we only send the request.
  bool  adminOpen = std::getenv("SAILSIM_ADMIN_PANEL") != nullptr, prevBacktick = false;   // env = open at start (screenshot tests)
  float admWindSpeed = 10.0f, admWindDir = 0.0f, admCloud = 0.25f, admHour = 12.0f;
  float admTpX = 0.0f, admTpZ = 0.0f;
  std::string admStatus, admVerb;              // last result line + in-flight action name
  std::future<net::AdminResult> admFuture;     // one admin call in flight at a time
  bool  admApplyTeleport = false;              // move the vessel when the gate says ok
  float admPendTpX = 0.0f, admPendTpZ = 0.0f;

  // Chat panel (mirrors the browser's chat.component): Main tab + a tab per DM
  // partner, message log, input row. Enter (while not typing) focuses the input.
  std::vector<mp::ChatMessage> chatLog;        // full received history (capped)
  std::vector<std::string> chatDmTabs;         // open DM tabs (callsigns)
  std::string chatActiveTab;                   // "" = Main, else a DM callsign
  char chatInput[512] = "";
  bool chatFocusInput = false, chatStickBottom = true;

  // Multiplayer: connected on entering Sailing, closed on logout. Our pose is
  // sent ~10 Hz; remote players/wind arrive on the client's own thread.
  mp::Client mpClient;
  uint32_t netSeq = 0;
  bool mpConnected = false;

  // Terrain: fetch + decode the world heightfield off-thread; upload the height
  // texture and place the ship near land once it arrives.
  terrain::Terrain terr;
  std::future<bool> terrFuture = std::async(std::launch::async,
      [&terr, kHost, kPort] { return terr.load(kHost, kPort); });
  bool terrHandled = false;

  // "Remember me": if a saved session exists, validate its token via /user/me and,
  // if still good, drop the player straight into the game. A 401 clears it.
  session::Saved saved;
  bool restoringSession = false;
  if (session::load(saved)) {
    uiRemember = true;
    restoringSession = true;
    std::strncpy(uiUser, saved.username.c_str(), sizeof(uiUser) - 1);  // prefill if it fails
    appState = AppState::Connecting;
    std::string host = kHost, tok = saved.token;
    int port = kPort;
    authFuture = std::async(std::launch::async, net::me, host, port, tok);
  }

  // 6. Render loop: reflection pass, then sky + ocean + ship.
  while (!glfwWindowShouldClose(window)) {
    glfwPollEvents();
    if (maxFrames > 0 && frame >= maxFrames) break;
    ++frame;

    // Handle window resize: reconfigure the surface and rebuild the depth buffer.
    int w = 0, h = 0;
    glfwGetFramebufferSize(window, &w, &h);
    if (w > 0 && h > 0 && ((uint32_t)w != curW || (uint32_t)h != curH)) {
      curW = (uint32_t)w; curH = (uint32_t)h;
      surfaceConfig.width = curW; surfaceConfig.height = curH;
      wgpuSurfaceConfigure(surface, &surfaceConfig);
      wgpuTextureViewRelease(depthView);
      wgpuTextureRelease(depthTex);
      depthTex = makeDepthTexture(device, curW, curH);
      depthView = wgpuTextureCreateView(depthTex, nullptr);
      wgpuTextureViewRelease(reflView);   wgpuTextureRelease(reflTex);
      wgpuTextureViewRelease(reflDepthView); wgpuTextureRelease(reflDepth);
      reflTex = makeColorRTT(device, curW, curH, surfaceFormat);
      reflView = wgpuTextureCreateView(reflTex, nullptr);
      reflDepth = makeDepthTexture(device, curW, curH);
      reflDepthView = wgpuTextureCreateView(reflDepth, nullptr);
      wgpuTextureViewRelease(cloudView); wgpuTextureRelease(cloudTex);
      cloudTex = makeColorRTT(device, curW, curH, kCloudFormat);
      cloudView = wgpuTextureCreateView(cloudTex, nullptr);
      wgpuBindGroupRelease(denoiseBG);
      denoiseBG = buildDenoiseBG();
      wgpuTextureViewRelease(grView); wgpuTextureRelease(grTex);
      grTex = makeColorRTT(device, curW, curH, kGodrayFormat);
      grView = wgpuTextureCreateView(grTex, nullptr);
      rebuildGodrayBlurBind(device, godrays, grView, grSampler);
    }

    float aspect = (float)curW / (float)curH;
    float t = (float)frame * (1.0f / 60.0f);
    float waveT = t * kWaveSpeed;   // slowed sim clock for the wave fields
    const float dt = 1.0f / 60.0f;

    // Terrain arrived? Upload its height texture and start the ship near a harbour.
    if (!terrHandled && terrFuture.valid() &&
        terrFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
      if (terrFuture.get() && terr.loaded()) {
        const terrain::Manifest& tm = terr.manifest();
        uploadTerrainHeight(device, queue, terrainR, tm.width, tm.height, terr.field().data());
        // Bake the world-map raster: the minimap colour ramp (exact port of the
        // client's minimap-bake-compute bands), subsampled to 1024².
        {
          const int MR = 1024;
          std::vector<uint8_t> px((size_t)MR * MR * 4);
          const float peak = terrainR.peakH;
          for (int y = 0; y < MR; ++y) {
            int sy = (int)((int64_t)y * tm.height / MR);
            for (int x = 0; x < MR; ++x) {
              int sx = (int)((int64_t)x * tm.width / MR);
              float e = terr.field()[(size_t)sy * tm.width + sx];
              // Water: a readable blue, shaded by depth (pale turquoise shallows on
              // the reefs -> ocean blue in the deep) instead of the near-black navy.
              float d = std::clamp(-e / 80.0f, 0.0f, 1.0f);
              uint8_t r = (uint8_t)(70.0f - 46.0f * d);
              uint8_t g = (uint8_t)(150.0f - 74.0f * d);
              uint8_t b = (uint8_t)(180.0f - 62.0f * d);
              if (e > 0.01f) {
                float n = e / peak;
                if      (n < 0.03f) { r = 170; g = 148; b = 110; }   // sand
                else if (n < 0.25f) { r = 63;  g = 104; b = 48;  }   // lowland green
                else if (n < 0.55f) { r = 95;  g = 83;  b = 65;  }   // mid brown
                else if (n < 0.80f) { r = 72;  g = 64;  b = 57;  }   // upland
                else                { r = 56;  g = 52;  b = 52;  }   // peak
              }
              size_t o = ((size_t)y * MR + x) * 4;
              px[o] = r; px[o + 1] = g; px[o + 2] = b; px[o + 3] = 255;
            }
          }
          mapTex = makeSampledRGBA(device, queue, MR, MR, px.data(), true);
          mapView = wgpuTextureCreateView(mapTex, nullptr);
        }
        if (!tm.harbors.empty()) {
          const terrain::Harbor* best = &tm.harbors[0]; float bestD = 1e30f;
          for (const terrain::Harbor& h : tm.harbors) {
            float d = h.x * h.x + h.z * h.z; if (d < bestD) { bestD = d; best = &h; }
          }
          float hr = glm::radians(best->heading);
          glm::vec3 seaward(std::sin(hr), 0.0f, -std::cos(hr));   // 0=N(-Z), 90=E(+X)
          vessel.x = best->x + seaward.x * 700.0f;
          vessel.z = best->z + seaward.z * 700.0f;
          vessel.heading = hr + glm::pi<float>();   // bow toward the harbour
          shipX = vessel.x; shipZ = vessel.z; shipHeading = vessel.heading;
          std::printf("[terrain] start near '%s' at (%.0f, %.0f)\n", best->name.c_str(), shipX, shipZ);
        }
      }
      terrHandled = true;
    }

    // ── Dear ImGui frame: login / HUD ─────────────────────────────────────
    ImGui_ImplWGPU_NewFrame();
    ImGui_ImplGlfw_NewFrame();
    ImGui::NewFrame();
    ImGuiIO& io = ImGui::GetIO();

    // Resolve an in-flight auth request (posted off-thread so the sea keeps moving).
    if (appState == AppState::Connecting && authFuture.valid() &&
        authFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
      net::AuthResult res = authFuture.get();
      if (res.ok) {
        authToken = res.token; authUsername = res.username; authRole = res.role;
        // /user/me (session restore) doesn't return the callsign — keep the saved one.
        authCallsign = res.callsign.empty() ? saved.callsign : res.callsign;
        uiError.clear();
        std::memset(uiPass, 0, sizeof(uiPass));
        if (uiRemember) session::save({ authToken, authUsername, authCallsign, authRole });
        mpClient.connect(kHost, kPort, authToken);   // open the gameplay socket
        mpConnected = true;
        appState = AppState::Sailing;
      } else {
        // A rejected token (401/403) clears the remembered session; a mere
        // can't-reach-server (status 0) keeps it for next time.
        if (restoringSession) {
          if (res.status == 401 || res.status == 403) session::clear();
          uiError.clear();   // silent on a background restore
        } else {
          uiError = res.error.empty() ? "Sign-in failed." : res.error;
        }
        appState = AppState::Login;
      }
      restoringSession = false;
    }

    // Login / register panel, centred over the landing screen.
    if (appState == AppState::Login || appState == AppState::Connecting) {
      ImGui::SetNextWindowPos(ImVec2(io.DisplaySize.x * 0.5f, io.DisplaySize.y * 0.5f),
                              ImGuiCond_Always, ImVec2(0.5f, 0.5f));
      ImGui::Begin("##login", nullptr,
                   ImGuiWindowFlags_NoResize | ImGuiWindowFlags_NoMove |
                   ImGuiWindowFlags_NoCollapse | ImGuiWindowFlags_AlwaysAutoResize |
                   ImGuiWindowFlags_NoTitleBar);
      const float fieldW = 300.0f;
      // Nudge the cursor so the next single-line item is centred in the content area.
      auto center = [&](const char* s) {
        float avail = ImGui::GetContentRegionAvail().x, tw = ImGui::CalcTextSize(s).x;
        if (avail > tw) ImGui::SetCursorPosX(ImGui::GetCursorPosX() + (avail - tw) * 0.5f);
      };

      ImGui::PushFont(fontTitle);
      center("SAIL-SIM"); ImGui::TextUnformatted("SAIL-SIM");
      ImGui::PopFont();
      const char* sub = uiRegisterMode ? "Create your account" : "Sign in to set sail";
      center(sub); ImGui::TextDisabled("%s", sub);
      ImGui::Dummy(ImVec2(0, 8));

      const bool busy = (appState == AppState::Connecting);
      ImGui::BeginDisabled(busy);
      ImGui::SetNextItemWidth(fieldW);
      ImGui::InputTextWithHint("##user", "Username", uiUser, sizeof(uiUser));
      if (uiRegisterMode) {
        ImGui::SetNextItemWidth(fieldW);
        ImGui::InputTextWithHint("##callsign", "Callsign", uiCallsign, sizeof(uiCallsign));
      }
      ImGui::SetNextItemWidth(fieldW);
      ImGui::InputTextWithHint("##pass", "Password", uiPass, sizeof(uiPass), ImGuiInputTextFlags_Password);
      ImGui::Checkbox("Remember me", &uiRemember);
      ImGui::Dummy(ImVec2(0, 4));

      const bool canSubmit = uiUser[0] && uiPass[0] && (!uiRegisterMode || uiCallsign[0]);
      ImGui::BeginDisabled(!canSubmit);
      if (ImGui::Button(uiRegisterMode ? "Create account" : "Log in", ImVec2(fieldW, 0))) {
        uiError.clear();
        std::string u = uiUser, p = uiPass, cs = uiCallsign, host = kHost;
        int port = kPort;
        authFuture = uiRegisterMode
          ? std::async(std::launch::async, net::registerUser, host, port, u, cs, p)
          : std::async(std::launch::async, net::login, host, port, u, p);
        appState = AppState::Connecting;
      }
      ImGui::EndDisabled();

      const char* toggle = uiRegisterMode ? "Back to sign in" : "Create an account";
      const float bw = 200.0f;
      ImGui::SetCursorPosX(ImGui::GetCursorPosX() + (fieldW - bw) * 0.5f);
      if (ImGui::Button(toggle, ImVec2(bw, 0))) uiRegisterMode = !uiRegisterMode;
      ImGui::EndDisabled();   // busy

      ImGui::Dummy(ImVec2(0, 2));
      if (busy) { center("Connecting..."); ImGui::TextUnformatted("Connecting..."); }
      if (!uiError.empty()) { center(uiError.c_str());
        ImGui::TextColored(ImVec4(0.95f, 0.45f, 0.45f, 1.0f), "%s", uiError.c_str()); }
      char srv[96]; std::snprintf(srv, sizeof(srv), "server: %s:%d", kHost.c_str(), kPort);
      center(srv); ImGui::TextDisabled("%s", srv);
      ImGui::End();
    }

    // A dropped/expired gameplay token (ws close 4401) forces re-login.
    if (appState == AppState::Sailing && mpClient.state() == mp::ConnState::AuthFailed) {
      mpClient.close(); mpConnected = false;
      session::clear();
      authToken.clear(); authCallsign.clear(); authUsername.clear(); authRole.clear();
      uiError = "Session expired - please sign in again.";
      appState = AppState::Login;
    }

    // In-game HUD: identity, connection, nearby players, wind.
    if (appState == AppState::Sailing) {
      const mp::ConnState cs = mpClient.state();
      std::vector<mp::RemotePlayer> others = mpClient.players();
      mp::WaveState wv = mpClient.wave();

      // Wind relative to the bow (0 = wind on the nose), and point of sail.
      float headingDeg = glm::degrees(shipHeading);
      float windFromDeg = wv.valid ? wv.windBearing : 270.0f;
      float rel = std::fmod(windFromDeg - headingDeg + 360.0f, 360.0f);   // wind FROM, bow-relative
      float windAngle = rel > 180.0f ? 360.0f - rel : rel;               // 0..180 off the wind
      const char* pos = windAngle < 32 ? "In Irons" : windAngle < 45 ? "Close Hauled"
                      : windAngle < 60 ? "Close Reach" : windAngle < 90 ? "Beam Reach"
                      : windAngle < 145 ? "Broad Reach" : windAngle < 165 ? "Running" : "Dead Downwind";

      // ── Top-left: wind gauge + readouts ──
      ImGui::SetNextWindowPos(ImVec2(12, 12), ImGuiCond_Always);
      ImGui::Begin("hud", nullptr, ImGuiWindowFlags_NoResize | ImGuiWindowFlags_NoMove |
                   ImGuiWindowFlags_AlwaysAutoResize | ImGuiWindowFlags_NoTitleBar);
      ImGui::Text("%s", authCallsign.empty() ? authUsername.c_str() : authCallsign.c_str());

      // Wind gauge: bow points up; the arrow shows where the wind blows FROM, and a
      // red wedge marks the no-go zone (+/- the rig's min tack angle around the eye).
      const float G = 132.0f;
      ImVec2 p0 = ImGui::GetCursorScreenPos();
      ImGui::Dummy(ImVec2(G, G));
      ImDrawList* dl = ImGui::GetWindowDrawList();
      ImVec2 c(p0.x + G * 0.5f, p0.y + G * 0.5f);
      float R = G * 0.5f - 6.0f;
      auto dirAt = [&](float deg) {
        float r = glm::radians(deg);
        return ImVec2(c.x + R * std::sin(r), c.y - R * std::cos(r));
      };
      // No-go wedge around the wind eye.
      { std::vector<ImVec2> w; w.push_back(c);
        for (float a = rel - vrig.minTackAngle; a <= rel + vrig.minTackAngle; a += 5.0f) w.push_back(dirAt(a));
        w.push_back(dirAt(rel + vrig.minTackAngle));
        dl->AddConvexPolyFilled(w.data(), (int)w.size(), IM_COL32(210, 70, 60, 70)); }
      dl->AddCircleFilled(c, R, IM_COL32(20, 34, 48, 160));
      dl->AddCircle(c, R, IM_COL32(150, 180, 205, 200), 48, 1.5f);
      // Wind arrow: rim (FROM) -> toward centre (the way it blows).
      ImVec2 wt = dirAt(rel), wh(c.x + (wt.x - c.x) * 0.30f, c.y + (wt.y - c.y) * 0.30f);
      dl->AddLine(wt, wh, IM_COL32(90, 180, 240, 255), 3.0f);
      { ImVec2 d(wh.x - wt.x, wh.y - wt.y); float l = std::hypot(d.x, d.y); if (l > 1e-3f) { d.x /= l; d.y /= l; }
        ImVec2 n(-d.y, d.x);
        dl->AddTriangleFilled(wh, ImVec2(wh.x - d.x*10 + n.x*6, wh.y - d.y*10 + n.y*6),
                              ImVec2(wh.x - d.x*10 - n.x*6, wh.y - d.y*10 - n.y*6), IM_COL32(90, 180, 240, 255)); }
      // Ship (bow up).
      dl->AddTriangleFilled(ImVec2(c.x, c.y - 15), ImVec2(c.x - 9, c.y + 11), ImVec2(c.x + 9, c.y + 11), IM_COL32(235, 235, 240, 255));

      if (wv.valid) ImGui::Text("Wind %.0f kn  (B%d)", wv.windSpeed, wv.beaufort);
      ImGui::Text("Speed %.1f kn", shipSpeed);
      ImGui::TextColored(ImVec4(0.55f, 0.78f, 0.95f, 1.0f), "%s", pos);

      const char* connLabel = cs == mp::ConnState::Open ? "connected" : cs == mp::ConnState::Connecting ? "connecting..."
                            : cs == mp::ConnState::AuthFailed ? "auth failed" : "offline";
      const ImVec4 connCol = cs == mp::ConnState::Open ? ImVec4(0.45f, 0.85f, 0.55f, 1.0f) : ImVec4(0.90f, 0.70f, 0.40f, 1.0f);
      ImGui::TextColored(connCol, "Server: %s  (%d nearby)", connLabel, (int)others.size());
      ImGui::Separator();
      if (ImGui::Button("Log out")) {
        mpClient.close(); mpConnected = false;
        session::clear();
        authToken.clear(); authCallsign.clear(); authUsername.clear(); authRole.clear();
        uiError.clear();
        appState = AppState::Login;
      }
      ImGui::End();

      // ── Top-right: sail status ──
      const char* sailLabel = vessel.anchored ? "ANCHORED"
                            : vessel.sailState == 2 ? "FULL SAIL" : vessel.sailState == 1 ? "REDUCED SAIL" : "SAILS FURLED";
      const ImVec4 sailCol = vessel.anchored ? ImVec4(0.90f, 0.65f, 0.35f, 1.0f)
                           : vessel.sailState == 2 ? ImVec4(0.50f, 0.85f, 0.55f, 1.0f)
                           : vessel.sailState == 1 ? ImVec4(0.90f, 0.82f, 0.45f, 1.0f) : ImVec4(0.65f, 0.68f, 0.72f, 1.0f);
      ImGui::SetNextWindowPos(ImVec2(io.DisplaySize.x - 12, 12), ImGuiCond_Always, ImVec2(1.0f, 0.0f));
      ImGui::Begin("sailhud", nullptr, ImGuiWindowFlags_NoResize | ImGuiWindowFlags_NoMove |
                   ImGuiWindowFlags_AlwaysAutoResize | ImGuiWindowFlags_NoTitleBar);
      ImGui::PushFont(fontTitle);
      ImGui::TextColored(sailCol, "%s", sailLabel);
      ImGui::PopFont();
      ImGui::TextDisabled("W / S  sail    P  anchor");
      ImGui::End();

      // ── World map (mirrors the browser's minimap.component): a small always-on
      //    minimap bottom-right; M or a click expands to a zoomable/pannable chart
      //    with harbour towns, players, and (admins) right-click teleport. ──
      const bool isAdmin = (authRole == "Admin" || authRole == "Owner");   // server role names (middleware/auth.js)
      if (terrainR.ready && mapView) {
        const terrain::Manifest& tm = terr.manifest();
        const float worldW = (float)(tm.maxX - tm.minX), worldH = (float)(tm.maxZ - tm.minZ);
        if (ImGui::IsKeyPressed(ImGuiKey_M, false) && !io.WantTextInput) {
          mapExpanded = !mapExpanded;
          if (!mapExpanded) { mapZoom = 1.0f; mapViewInit = false; }
        }
        if (mapExpanded && ImGui::IsKeyPressed(ImGuiKey_Escape, false)) {
          mapExpanded = false; mapZoom = 1.0f; mapViewInit = false;
        }
        auto factionCol = [](const std::string& f) -> ImU32 {   // faction.config colours
          if (f == "english") return IM_COL32(204, 43, 43, 255);
          if (f == "french")  return IM_COL32(47, 111, 208, 255);
          if (f == "spanish") return IM_COL32(232, 195, 58, 255);
          if (f == "dutch")   return IM_COL32(224, 123, 42, 255);
          return IM_COL32(154, 154, 154, 255);
        };
        auto clampMapView = [&]() {
          if (!mapViewInit) { mapVCX = (float)(tm.minX + tm.maxX) * 0.5f; mapVCZ = (float)(tm.minZ + tm.maxZ) * 0.5f; mapViewInit = true; }
          float visW = worldW / mapZoom, visH = worldH / mapZoom;
          mapVCX = std::clamp(mapVCX, (float)tm.minX + visW * 0.5f, (float)tm.maxX - visW * 0.5f);
          mapVCZ = std::clamp(mapVCZ, (float)tm.minZ + visH * 0.5f, (float)tm.maxZ - visH * 0.5f);
        };

        // Draw the chart + markers into the current window at S px; handles zoom /
        // pan / right-click teleport when expanded. One body for both map sizes.
        auto drawMap = [&](float S, bool expanded) {
          clampMapView();
          float zoom = expanded ? mapZoom : 1.0f;
          float visW = worldW / zoom, visH = worldH / zoom;
          float vcx = expanded ? mapVCX : (float)(tm.minX + tm.maxX) * 0.5f;
          float vcz = expanded ? mapVCZ : (float)(tm.minZ + tm.maxZ) * 0.5f;
          float viewMinX = vcx - visW * 0.5f, viewMaxZ = vcz + visH * 0.5f;

          ImVec2 p0 = ImGui::GetCursorScreenPos();
          ImGui::InvisibleButton(expanded ? "mapbig" : "mapsmall", ImVec2(S, S));
          const bool hovered = ImGui::IsItemHovered();
          ImDrawList* mdl = ImGui::GetWindowDrawList();
          auto wx = [&](float x) { return p0.x + (x - viewMinX) / visW * S; };
          auto wz = [&](float z) { return p0.y + (viewMaxZ - z) / visH * S; };
          auto toWorld = [&](ImVec2 mp) {
            return ImVec2(viewMinX + (mp.x - p0.x) / S * visW,
                          viewMaxZ - (mp.y - p0.y) / S * visH);
          };

          // Terrain raster: blit the visible sub-rectangle of the baked chart.
          ImVec2 uv0((viewMinX - (float)tm.minX) / worldW, ((float)tm.maxZ - viewMaxZ) / worldH);
          ImVec2 uv1(uv0.x + visW / worldW, uv0.y + visH / worldH);
          mdl->AddImage((ImTextureID)mapView, p0, ImVec2(p0.x + S, p0.y + S), uv0, uv1);
          // Subtle grid.
          for (int i = 1; i < 8; ++i) {
            float g = S * (float)i / 8.0f;
            mdl->AddLine(ImVec2(p0.x + g, p0.y), ImVec2(p0.x + g, p0.y + S), IM_COL32(255, 255, 255, 10));
            mdl->AddLine(ImVec2(p0.x, p0.y + g), ImVec2(p0.x + S, p0.y + g), IM_COL32(255, 255, 255, 10));
          }

          // Interactions (expanded only): wheel-zoom toward the cursor, drag-pan,
          // admin right-click teleport.
          if (expanded) {
            if (hovered && io.MouseWheel != 0.0f) {
              ImVec2 before = toWorld(io.MousePos);
              mapZoom = std::clamp(mapZoom * std::pow(1.2f, io.MouseWheel), 1.0f, 6.0f);
              clampMapView();
              visW = worldW / mapZoom; visH = worldH / mapZoom;
              viewMinX = mapVCX - visW * 0.5f; viewMaxZ = mapVCZ + visH * 0.5f;
              ImVec2 after = toWorld(io.MousePos);
              mapVCX += before.x - after.x; mapVCZ += before.y - after.y;   // cursor's world point stays put
              clampMapView();
            }
            if (ImGui::IsItemActive() && ImGui::IsMouseDragging(ImGuiMouseButton_Left)) {
              mapVCX -= io.MouseDelta.x * (visW / S);   // grab-and-pull
              mapVCZ += io.MouseDelta.y * (visH / S);
              clampMapView();
            }
            if (isAdmin && ImGui::IsItemClicked(ImGuiMouseButton_Right)) {
              ImVec2 w = toWorld(io.MousePos);
              mapTpX = w.x; mapTpZ = w.y;
              ImGui::OpenPopup("map_teleport");
            }
          }

          // Harbour towns: faction-coloured dots with a contrast halo; hover tooltip.
          const float R = expanded ? 5.0f : 3.0f;
          for (const terrain::Harbor& hb : tm.harbors) {
            ImVec2 hp(wx(hb.x), wz(hb.z));
            if (hp.x < p0.x || hp.x > p0.x + S || hp.y < p0.y || hp.y > p0.y + S) continue;
            mdl->AddCircleFilled(hp, R + 2.0f, IM_COL32(0, 0, 0, 140));
            mdl->AddCircleFilled(hp, R, factionCol(hb.faction));
            mdl->AddCircle(hp, R, IM_COL32(0, 0, 0, 190), 0, 1.3f);
            if (expanded) {
              float d = std::hypot(io.MousePos.x - hp.x, io.MousePos.y - hp.y);
              if (hovered && d < 8.0f) {
                ImGui::BeginTooltip();
                ImGui::Text("%s", hb.name.c_str());
                if (!hb.faction.empty()) {
                  std::string fn = hb.faction; fn[0] = (char)std::toupper((unsigned char)fn[0]);
                  ImGui::TextDisabled("%s%s%s", fn.c_str(), hb.tier.empty() ? "" : " - ", hb.tier.c_str());
                }
                ImGui::EndTooltip();
              }
            }
          }

          // Other players: orange dots (+ callsign labels on the expanded chart).
          for (const mp::RemotePlayer& rp : mpClient.players()) {
            ImVec2 pp(wx(rp.x), wz(rp.z));
            if (pp.x < p0.x || pp.x > p0.x + S || pp.y < p0.y || pp.y > p0.y + S) continue;
            mdl->AddCircleFilled(pp, 3.0f, IM_COL32(255, 120, 80, 220));
            if (expanded && !rp.callsign.empty()) {
              std::string cs = rp.callsign;
              for (char& ch : cs) ch = (char)std::toupper((unsigned char)ch);
              ImVec2 ts = ImGui::CalcTextSize(cs.c_str());
              mdl->AddText(ImVec2(pp.x - ts.x * 0.5f, pp.y - ts.y - 5.0f), IM_COL32(255, 170, 120, 230), cs.c_str());
            }
          }

          // Own vessel: green heading arrow (bow toward travel).
          {
            ImVec2 vp(wx(vessel.x), wz(vessel.z));
            float sz = expanded ? 9.0f : 6.0f, ch = std::cos(vessel.heading), sh = std::sin(vessel.heading);
            auto rot = [&](float x, float y) {   // local (x up-bow) -> screen, rotated by heading
              return ImVec2(vp.x + x * ch + y * sh, vp.y + x * sh - y * ch);
            };
            // Triangle in local space: bow (0,+sz), sterns (±0.55sz, -0.7sz).
            ImVec2 bow = rot(0.0f, sz), pstn = rot(-sz * 0.55f, -sz * 0.7f), sstn = rot(sz * 0.55f, -sz * 0.7f);
            mdl->AddTriangleFilled(bow, pstn, sstn, IM_COL32(0, 255, 136, 255));
            mdl->AddTriangle(bow, pstn, sstn, IM_COL32(0, 68, 34, 255), 1.0f);
          }

          // Compass rose + border.
          mdl->AddText(ImVec2(p0.x + S - 14.0f, p0.y + 4.0f), IM_COL32(255, 255, 255, 130), "N");
          mdl->AddRect(p0, ImVec2(p0.x + S, p0.y + S), IM_COL32(255, 255, 255, 50));

          // Admin teleport confirm popup (opened by right-click above).
          if (expanded && ImGui::BeginPopup("map_teleport")) {
            char lbl[64];
            std::snprintf(lbl, sizeof(lbl), "Teleport here  (%.0f, %.0f)", mapTpX, mapTpZ);
            ImGui::BeginDisabled(admFuture.valid());
            if (ImGui::MenuItem(lbl)) {
              admVerb = "teleport"; admApplyTeleport = true;
              admPendTpX = mapTpX; admPendTpZ = mapTpZ;
              const float tx = mapTpX, tz = mapTpZ;
              admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken, tx, tz] {
                return net::teleport(host, port, token, tx, tz); });
            }
            ImGui::EndDisabled();
            ImGui::EndPopup();
          }
        };

        if (mapExpanded) {
          const float S = std::min(io.DisplaySize.x, io.DisplaySize.y) * 0.78f;
          ImGui::SetNextWindowPos(ImVec2(io.DisplaySize.x * 0.5f, io.DisplaySize.y * 0.5f),
                                  ImGuiCond_Always, ImVec2(0.5f, 0.5f));
          ImGui::Begin("World Map", &mapExpanded, ImGuiWindowFlags_NoResize | ImGuiWindowFlags_NoCollapse |
                       ImGuiWindowFlags_AlwaysAutoResize);
          drawMap(S, true);
          ImGui::TextDisabled(isAdmin ? "wheel zoom   drag pan   right-click teleport   M/Esc close"
                                      : "wheel zoom   drag pan   M/Esc close");
          ImGui::End();
          if (!mapExpanded) { mapZoom = 1.0f; mapViewInit = false; }   // closed via title-bar X
        } else {
          const float S = 200.0f;
          ImGui::SetNextWindowPos(ImVec2(io.DisplaySize.x - 12.0f, io.DisplaySize.y - 12.0f),
                                  ImGuiCond_Always, ImVec2(1.0f, 1.0f));
          ImGui::Begin("minimap", nullptr, ImGuiWindowFlags_NoResize | ImGuiWindowFlags_NoMove |
                       ImGuiWindowFlags_AlwaysAutoResize | ImGuiWindowFlags_NoTitleBar);
          drawMap(S, false);
          if (ImGui::IsItemClicked(ImGuiMouseButton_Left)) mapExpanded = true;   // click the chart to expand
          ImGui::End();
        }
      }

      // ── Admin panel (backtick; admin/owner only) ──
      const bool backtick = glfwGetKey(window, GLFW_KEY_GRAVE_ACCENT) == GLFW_PRESS;
      if (backtick && !prevBacktick && isAdmin && !io.WantTextInput) {
        adminOpen = !adminOpen;
        if (adminOpen) {   // pre-fill controls with the live weather + game clock
          if (wv.valid) { admWindSpeed = wv.windSpeed; admWindDir = wv.windBearing; admCloud = wv.cloudiness; }
          const double cyc = std::fmod((double)std::time(nullptr), 1440.0);   // 24 game-h x 60 real-s
          admHour = (float)(std::fmod(cyc + wv.timeOffsetSec, 1440.0) / 60.0);
          admStatus.clear();
        }
      }
      prevBacktick = backtick;

      // Harvest a finished admin call: report the result; teleport moves the
      // vessel only after the server's authorization gate returns 200.
      if (admFuture.valid() && admFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
        net::AdminResult ar = admFuture.get();
        if (ar.ok) {
          admStatus = admVerb + ": ok";
          if (admApplyTeleport) {
            vessel.x = admPendTpX; vessel.z = admPendTpZ;
            vessel.speed = 0.0f; vessel.yawRate = 0.0f;
            if (vessel.anchored) { vessel.anchorX = vessel.x; vessel.anchorZ = vessel.z; }
            shipX = vessel.x; shipZ = vessel.z;
          }
        } else {
          admStatus = admVerb + " failed: " + (ar.error.empty()
                        ? "HTTP " + std::to_string(ar.status) : ar.error);
        }
        admApplyTeleport = false;
      }

      if (adminOpen && isAdmin) {
        ImGui::SetNextWindowPos(ImVec2(io.DisplaySize.x * 0.5f, io.DisplaySize.y * 0.5f),
                                ImGuiCond_Appearing, ImVec2(0.5f, 0.5f));
        ImGui::SetNextWindowSize(ImVec2(380.0f, 0.0f), ImGuiCond_Appearing);
        if (ImGui::Begin("Admin Controls", &adminOpen,
                         ImGuiWindowFlags_NoCollapse | ImGuiWindowFlags_AlwaysAutoResize)) {
          const bool busy = admFuture.valid();
          const ImVec4 secCol(0.33f, 0.53f, 0.67f, 1.0f);    // section headers
          const ImVec4 onCol(0.27f, 0.87f, 0.53f, 1.0f);     // "override on" badge

          // ── Weather ──
          ImGui::TextColored(secCol, "WEATHER");
          if (wv.valid && wv.overrideOn) { ImGui::SameLine(); ImGui::TextColored(onCol, "[OVERRIDE ON]"); }
          static const char* kCardinals[16] = { "N","NNE","NE","ENE","E","ESE","SE","SSE",
                                                "S","SSW","SW","WSW","W","WNW","NW","NNW" };
          const int   bf   = std::min(12, (int)(admWindSpeed / 2.5f));
          const char* card = kCardinals[((int)std::lround(admWindDir / 22.5f)) % 16];
          const char* skyL = admCloud > 0.94f ? "Storm"    : admCloud > 0.82f ? "Rain"
                           : admCloud > 0.68f ? "Drizzle"  : admCloud > 0.50f ? "Overcast"
                           : admCloud > 0.28f ? "Partly Cloudy" : "Clear";
          ImGui::SetNextItemWidth(-90.0f);
          ImGui::SliderFloat("##wspd", &admWindSpeed, 0.0f, 30.0f, "Wind %.1f m/s");
          ImGui::SameLine(); ImGui::TextDisabled("Bf %d", bf);
          ImGui::SetNextItemWidth(-90.0f);
          ImGui::SliderFloat("##wdir", &admWindDir, 0.0f, 359.0f, "From %.0f deg");
          ImGui::SameLine(); ImGui::TextDisabled("%s", card);
          ImGui::SetNextItemWidth(-90.0f);
          ImGui::SliderFloat("##cloud", &admCloud, 0.0f, 1.0f, "Sky %.2f");
          ImGui::SameLine(); ImGui::TextDisabled("%s", skyL);
          ImGui::BeginDisabled(busy);
          if (ImGui::Button("Apply##weather")) {
            admVerb = "weather override";
            const float ws = admWindSpeed, wd = admWindDir, cl = admCloud;
            admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken, ws, wd, cl] {
              return net::setWeatherOverride(host, port, token, ws, wd, cl); });
          }
          ImGui::SameLine();
          if (ImGui::Button("Clear##weather")) {
            admVerb = "clear weather";
            admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken] {
              return net::clearWeatherOverride(host, port, token); });
          }
          ImGui::EndDisabled();

          // ── Teleport ──
          ImGui::Spacing(); ImGui::Separator(); ImGui::Spacing();
          ImGui::TextColored(secCol, "TELEPORT");
          ImGui::TextDisabled("Current: X %.0f   Z %.0f", vessel.x, vessel.z);
          ImGui::SameLine();
          if (ImGui::SmallButton("Copy")) { admTpX = vessel.x; admTpZ = vessel.z; }
          ImGui::SetNextItemWidth(150.0f);
          ImGui::InputFloat("X##tp", &admTpX, 10.0f, 100.0f, "%.0f");
          ImGui::SameLine();
          ImGui::SetNextItemWidth(150.0f);
          ImGui::InputFloat("Z##tp", &admTpZ, 10.0f, 100.0f, "%.0f");
          ImGui::BeginDisabled(busy);
          if (ImGui::Button("Teleport")) {
            admVerb = "teleport"; admApplyTeleport = true;
            admPendTpX = admTpX; admPendTpZ = admTpZ;
            const float tx = admTpX, tz = admTpZ;
            admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken, tx, tz] {
              return net::teleport(host, port, token, tx, tz); });
          }
          ImGui::EndDisabled();

          // ── Time of day: drives the native day/night sky (sun/moon/stars) via the
          //    server's broadcast time offset. ──
          ImGui::Spacing(); ImGui::Separator(); ImGui::Spacing();
          ImGui::TextColored(secCol, "TIME OF DAY");
          if (wv.valid && wv.timeOffsetSec != 0.0f) { ImGui::SameLine(); ImGui::TextColored(onCol, "[OVERRIDE ON]"); }
          char hourLabel[16];   // HH:MM as the slider text (no % -> printed verbatim)
          std::snprintf(hourLabel, sizeof(hourLabel), "%02d:%02d",
                        (int)admHour, (int)std::lround(std::fmod(admHour, 1.0f) * 60.0f) % 60);
          ImGui::SetNextItemWidth(-90.0f);
          ImGui::SliderFloat("##hour", &admHour, 0.0f, 23.75f, hourLabel);
          ImGui::BeginDisabled(busy);
          if (ImGui::Button("Apply##time")) {
            admVerb = "time offset";
            const float th = admHour;
            admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken, th] {
              return net::setTimeOffset(host, port, token, th); });
          }
          ImGui::SameLine();
          if (ImGui::Button("Clear##time")) {
            admVerb = "clear time";
            admFuture = std::async(std::launch::async, [host = kHost, port = kPort, token = authToken] {
              return net::clearTimeOffset(host, port, token); });
          }
          ImGui::EndDisabled();
          ImGui::TextDisabled("(sets the sky for everyone; shares the server clock)");

          if (busy) { ImGui::Spacing(); ImGui::TextDisabled("applying..."); }
          else if (!admStatus.empty()) {
            ImGui::Spacing();
            ImGui::TextColored(admStatus.find("failed") != std::string::npos
                                 ? ImVec4(0.95f, 0.55f, 0.45f, 1.0f) : onCol,
                               "%s", admStatus.c_str());
          }
        }
        ImGui::End();
      }

      // ── Chat panel (browser chat.component port): Main + DM tabs, log, input ──
      // Drain new lines; a DM to/from a new partner opens its tab, like the client.
      for (mp::ChatMessage& cm : mpClient.drainChat()) {
        if (cm.chatType == "dm") {
          const std::string& other = (cm.from == authCallsign) ? cm.to : cm.from;
          if (!other.empty() &&
              std::find(chatDmTabs.begin(), chatDmTabs.end(), other) == chatDmTabs.end())
            chatDmTabs.push_back(other);
        }
        if (chatLog.size() >= 400) chatLog.erase(chatLog.begin(), chatLog.begin() + 100);
        chatLog.push_back(std::move(cm));
        chatStickBottom = true;
      }
      // Enter (while not typing) jumps to the chat input — the browser's hotkey.
      if (!io.WantTextInput &&
          (ImGui::IsKeyPressed(ImGuiKey_Enter, false) || ImGui::IsKeyPressed(ImGuiKey_KeypadEnter, false)))
        chatFocusInput = true;

      ImGui::SetNextWindowPos(ImVec2(12.0f, io.DisplaySize.y - 12.0f), ImGuiCond_FirstUseEver, ImVec2(0.0f, 1.0f));
      ImGui::SetNextWindowSize(ImVec2(380.0f, 262.0f), ImGuiCond_FirstUseEver);
      ImGui::SetNextWindowSizeConstraints(ImVec2(280.0f, 170.0f), ImVec2(820.0f, 640.0f));
      if (ImGui::Begin("Chat", nullptr, ImGuiWindowFlags_NoCollapse)) {
        // Tab bar: Main + a closable tab per DM partner.
        if (ImGui::BeginTabBar("##chattabs")) {   // new DM tabs appear but don't steal focus (matches the client)
          if (ImGui::BeginTabItem("Main")) { chatActiveTab.clear(); ImGui::EndTabItem(); }
          for (size_t i = 0; i < chatDmTabs.size();) {
            bool open = true;
            if (ImGui::BeginTabItem(chatDmTabs[i].c_str(), &open)) { chatActiveTab = chatDmTabs[i]; ImGui::EndTabItem(); }
            if (!open) {   // tab closed: fall back to Main (never a dangling tab)
              if (chatActiveTab == chatDmTabs[i]) chatActiveTab.clear();
              chatDmTabs.erase(chatDmTabs.begin() + (long)i);
            } else ++i;
          }
          ImGui::EndTabBar();
        }

        // Message log. Sticks to the newest line unless the user scrolled up.
        const char* kSysFrom = "\xE2\x9A\x93 System";   // "⚓ System" (anchor glyph isn't in the font atlas)
        ImGui::BeginChild("##chatlog", ImVec2(0.0f, -ImGui::GetFrameHeightWithSpacing()));
        const bool wasAtBottom = ImGui::GetScrollY() >= ImGui::GetScrollMaxY() - ImGui::GetTextLineHeightWithSpacing();
        for (const mp::ChatMessage& m : chatLog) {
          if (chatActiveTab.empty()) {
            if (m.chatType == "dm") continue;   // DMs live on their own tab
          } else if (m.chatType != "dm" ||
                     !(m.from == chatActiveTab || (m.from == authCallsign && m.to == chatActiveTab))) {
            continue;
          }
          const bool mine = (m.from == authCallsign);
          const bool sys  = (m.chatType == "system" || m.from == kSysFrom);
          const ImVec4 col = sys ? ImVec4(0.95f, 0.80f, 0.40f, 1.0f)
                           : m.chatType == "squadron" ? ImVec4(0.55f, 0.85f, 0.55f, 1.0f)
                           : m.chatType == "dm" ? ImVec4(0.80f, 0.62f, 0.95f, 1.0f)
                           : mine ? ImVec4(0.55f, 0.88f, 0.85f, 1.0f) : ImVec4(0.60f, 0.78f, 0.95f, 1.0f);
          ImGui::TextColored(col, "%s:", sys ? "System" : mine ? "You" : m.from.c_str());
          ImGui::SameLine();
          ImGui::PushTextWrapPos(0.0f);
          ImGui::TextUnformatted(m.text.c_str());
          ImGui::PopTextWrapPos();
        }
        if (chatLog.empty()) ImGui::TextDisabled("No messages yet.");
        if (chatStickBottom && wasAtBottom) ImGui::SetScrollHereY(1.0f);
        chatStickBottom = false;
        ImGui::EndChild();

        // Input row. Plain text: Main broadcasts, a DM tab whispers to its player.
        // Slash commands go to the server verbatim (it parses /t, /s, /squad, admin
        // commands and rejects unknowns) — except /help, which is answered locally.
        if (chatFocusInput) { ImGui::SetKeyboardFocusHere(); chatFocusInput = false; }
        ImGui::SetNextItemWidth(-30.0f);
        bool send = ImGui::InputText("##chatin", chatInput, sizeof(chatInput),
                                     ImGuiInputTextFlags_EnterReturnsTrue);
        ImGui::SameLine();
        send = ImGui::Button(">", ImVec2(22.0f, 0.0f)) || send;
        if (send) {
          std::string text(chatInput);
          const size_t b = text.find_first_not_of(" \t");
          text = (b == std::string::npos) ? std::string()
               : text.substr(b, text.find_last_not_of(" \t") - b + 1);
          chatInput[0] = '\0';
          if (!text.empty()) {
            if (text == "/help" || text.rfind("/help ", 0) == 0) {
              mp::ChatMessage h;
              h.chatType = "system"; h.from = kSysFrom;
              h.text = "Commands:\n"
                       "/t \"<name>\" <msg> - direct-message a player\n"
                       "/s <msg> - message your squadron only\n"
                       "/squad invite \"<name>\" | accept | decline | leave\n"
                       "/friend \"<name>\" - toggle a friend\n"
                       "/help - show this help";
              if (isAdmin)
                h.text += "\n- Admin -\n"
                          "/promote /demote /kick /ban /unban \"<name>\"\n"
                          "/teleport \"<name>\" <X> <Y>   /teleporto \"<name>\"\n"
                          "/repair /crew \"<name>\"   /givegold \"<name>\" <amt>\n"
                          "/diplomacy [<A> <B> war|peace|alliance]\n"
                          "/godmode  /mast [hp]  /pirates  /reloadassets";
              h.text += "\nTip: quote callsigns containing spaces, e.g. /t \"Red Sail\" ahoy";
              chatLog.push_back(std::move(h));
            } else if (!text.empty() && text[0] != '/' && !chatActiveTab.empty()) {
              mpClient.sendChat("/t \"" + chatActiveTab + "\" " + text);
            } else {
              mpClient.sendChat(text);
            }
            chatStickBottom = true;
          }
        }
      }
      ImGui::End();

      // Broadcast our pose ~10 Hz. Heading is sent in DEGREES (server/client convention).
      if (cs == mp::ConnState::Open && (frame % 6) == 0) {
        const char* sailState = vessel.anchored ? "anchor"
                              : (vessel.sailState == 2 ? "full" : vessel.sailState == 1 ? "half" : "furled");
        mp::PlayerUpdate pu;
        pu.x = shipX; pu.z = shipZ; pu.heading = glm::degrees(shipHeading); pu.speed = shipSpeed;
        pu.sailState = sailState;
        pu.vesselName = ownVesselSlug; pu.vesselSlug = ownVesselSlug;
        pu.callsign = authCallsign;
        mpClient.sendUpdate(pu, netSeq++);
      }
    }
    ImGui::Render();

    // Sailing input + ported force physics. A/D (or arrows) = helm; W/S = raise /
    // lower sail (furled -> half -> full); P = drop/weigh anchor.
    if (appState == AppState::Sailing) {
      auto down = [&](int k1, int k2) { return glfwGetKey(window, k1) == GLFW_PRESS || glfwGetKey(window, k2) == GLFW_PRESS; };
      int rudder = 0;
      if (!io.WantCaptureKeyboard) {
        rudder = (down(GLFW_KEY_D, GLFW_KEY_RIGHT) ? 1 : 0) - (down(GLFW_KEY_A, GLFW_KEY_LEFT) ? 1 : 0);
        bool raise = down(GLFW_KEY_W, GLFW_KEY_UP), lower = down(GLFW_KEY_S, GLFW_KEY_DOWN);
        bool anchor = glfwGetKey(window, GLFW_KEY_P) == GLFW_PRESS;
        if (raise && !prevRaise) vessel.sailState = std::min(2, vessel.sailState + 1);
        if (lower && !prevLower) vessel.sailState = std::max(0, vessel.sailState - 1);
        if (anchor && !prevAnchor) {
          vessel.anchored = !vessel.anchored;
          if (vessel.anchored) { vessel.anchorX = vessel.x; vessel.anchorZ = vessel.z; }
        }
        prevRaise = raise; prevLower = lower; prevAnchor = anchor;
      }
      vrig = sail::rigForSlug(ownVesselSlug.empty() ? "sloop" : ownVesselSlug);
      mp::WaveState wv = mpClient.wave();
      float windFromDeg = wv.valid ? wv.windBearing : 270.0f;
      float windKn      = wv.valid ? wv.windSpeed  : 8.0f;
      float seaRough    = glm::clamp((wv.valid ? (float)wv.beaufort : 3.0f) / 8.0f, 0.0f, 1.0f);
      sail::step(vessel, vrig, dt, windFromDeg, windKn, seaRough, rudder, kTravelScale);
      shipX = vessel.x; shipZ = vessel.z; shipHeading = vessel.heading; shipSpeed = vessel.speed;
    }
    glm::vec3 fwd(std::sin(shipHeading), 0.0f, std::cos(shipHeading));

    // Advance all cascades, then read their displacement back so buoyancy is driven
    // by the REAL FFT surface (not the analytic Gerstner field). Only while sailing —
    // the login/landing screen draws no scene, so there's nothing to simulate.
    const bool sailing = (appState == AppState::Sailing);
    if (sailing) {
      c0.update(waveT, 1.0f / 60.0f);
      c1.update(waveT, 1.0f / 60.0f);
      c2.update(waveT, 1.0f / 60.0f);
      c0.readbackDisplacement();
      c1.readbackDisplacement();
      c2.readbackDisplacement();
    }

    // Weather: ease cloudiness/storminess/sea amplitude toward Beaufort-driven
    // targets (server wave_state). Sea amplitude scales the FFT swell + buoyancy.
    {
      mp::WaveState wv = mpClient.wave();
      float beau = wv.valid ? (float)wv.beaufort : 3.0f;
      bool  beauDbg = false;
      if (const char* bo = std::getenv("SAILSIM_BEAUFORT")) { beau = (float)std::atof(bo); beauDbg = true; }   // debug override
      // Cloud cover comes straight from the server's weather state (which is what the
      // admin override pins); only the offline/debug fallback derives it from Beaufort.
      float targetCloud = (wv.valid && !beauDbg) ? wv.cloudiness
                        : glm::clamp(0.18f + beau * 0.080f, 0.0f, 0.97f);
      // Storm look from wind, or from heavy cloud (admin can dial a storm sky at any wind).
      float targetStorm = glm::max(glm::clamp((beau - 4.0f) / 6.0f, 0.0f, 1.0f),
                                   glm::clamp((targetCloud - 0.68f) / 0.26f, 0.0f, 1.0f));
      cloudiness += (targetCloud - cloudiness) * glm::min(1.0f, dt * 0.70f);
      storminess += (targetStorm - storminess) * glm::min(1.0f, dt * 0.55f);
      seaAmp      = glm::clamp(0.45f + beau * 0.19f, 0.45f, 2.2f);   // Beaufort 3 ~= 1.0
    }

    // Water height at a world (x,z) = summed vertical displacement, wind-scaled.
    auto fftHeight = [&](float x, float z) {
      float dx, dy, dz, h = 0.0f;
      c0.sampleDisplacement(x, z, dx, dy, dz); h += dy;
      c1.sampleDisplacement(x, z, dx, dy, dz); h += dy;
      c2.sampleDisplacement(x, z, dx, dy, dz); h += dy;
      return h * seaAmp;
    };

    // Buoyancy for the local hull (needs fftHeight): heave/pitch/roll from the
    // 8-point wave sample, filtered per-vessel. Applied in ownShipModel below.
    if (sailing) {
      sail::Buoy b = sail::buoyancy(vessel, vrig, dt, [&](float x, float z) { return fftHeight(x, z); });
      ownBuoy = glm::vec3(b.heave, b.pitchRad, b.rollRad);
    }

    // Camera input: hold LMB + drag to orbit, wheel to zoom.
    double mx = 0.0, my = 0.0;
    glfwGetCursorPos(window, &mx, &my);
    double mdx = mx - lastMouseX, mdy = my - lastMouseY;
    lastMouseX = mx; lastMouseY = my;
    const bool camActive = (appState == AppState::Sailing);
    if (camActive && !io.WantCaptureMouse &&
        glfwGetMouseButton(window, GLFW_MOUSE_BUTTON_LEFT) == GLFW_PRESS) {
      camYawOffset += (float)mdx * 0.005f;   // drag right -> orbit right (sign matches the mirrored projection)
      camPitch     -= (float)mdy * 0.005f;   // drag up    -> look from higher
      camPitch = glm::clamp(camPitch, 0.05f, 1.45f);
    }
    if (g_scrollAccum != 0.0) {
      if (camActive && !io.WantCaptureMouse) {
        camDist *= std::pow(0.9f, (float)g_scrollAccum);   // wheel up -> zoom in
        camDist = glm::clamp(camDist, 4.0f, 80.0f);
      }
      g_scrollAccum = 0.0;
    }

    // ── Day/night: derive the game clock from wall time + the server's admin time
    //    offset (so every client shares the sky), then place the sun/moon. ──
    float gameHours = 12.0f;
    {
      mp::WaveState wvt = mpClient.wave();
      const double CYCLE = 1440.0;   // 24 game-hours x 60 real-seconds
      // Sub-second precision (Date.now()/1000 in the client): std::time() is whole
      // seconds, which makes the sun/moon jump once per second — use a fractional clock.
      double epoch = std::chrono::duration<double>(
          std::chrono::system_clock::now().time_since_epoch()).count();
      double wall = std::fmod(epoch + wvt.timeOffsetSec, CYCLE);
      if (wall < 0) wall += CYCLE;
      gameHours = (float)(wall / 60.0);
    }
    if (const char* th = std::getenv("SAILSIM_HOUR")) gameHours = (float)std::atof(th);   // debug: pin the hour
    const glm::vec3 sunDir  = computeSunDir(gameHours);
    const glm::vec3 moonDir = -sunDir;
    const float sunEl = sunDir.y;                                  // -1 midnight .. +1 noon
    const float dayK  = glm::clamp((sunEl + 0.10f) / 0.20f, 0.0f, 1.0f);   // 1 day, 0 night
    const float starFade = glm::clamp((-sunEl - 0.02f) / 0.16f, 0.0f, 1.0f);
    const float moonFade = glm::clamp((0.04f - sunEl) / 0.16f, 0.0f, 1.0f);
    // Scene light follows the sun by day, the moon by night (both give a lit side
    // rather than a pitch-black world at midnight).
    const glm::vec3 lightDir = (sunEl > 0.0f) ? sunDir : moonDir;
    const glm::vec3 sun = sunDir;   // kept name for the shared writers below

    // Orbit camera: astern of the ship (offset by camYawOffset), pitched up, at camDist.
    float shipY = fftHeight(shipX, shipZ);
    glm::vec3 shipPos(shipX, shipY, shipZ);
    glm::vec3 back = glm::normalize(glm::vec3(glm::rotate(glm::mat4(1.0f), camYawOffset, glm::vec3(0, 1, 0)) * glm::vec4(-fwd, 0.0f)));
    glm::vec3 eye = shipPos + back * (camDist * std::cos(camPitch)) + glm::vec3(0.0f, camDist * std::sin(camPitch), 0.0f);
    glm::vec3 lookTarget = shipPos + glm::vec3(0.0f, 1.0f, 0.0f);
    glm::vec3 lookUp(0.0f, 1.0f, 0.0f);
    if (std::getenv("SAILSIM_SKYLOOK")) {   // debug: aim at the moon to inspect stars/moon
      lookTarget = eye + moonDir;
      if (std::abs(moonDir.y) > 0.95f) lookUp = glm::vec3(0.0f, 0.0f, 1.0f);   // avoid lookAt degeneracy near-vertical
    }
    if (std::getenv("SAILSIM_SUNLOOK")) {   // debug: aim at the sun to inspect god rays
      lookTarget = eye + sunDir;
      if (std::abs(sunDir.y) > 0.95f) lookUp = glm::vec3(0.0f, 0.0f, 1.0f);
    }
    if (std::getenv("SAILSIM_CLOUDLOOK")) {   // debug: aim up and AWAY from the sun (front-lit clouds)
      glm::vec3 away = glm::normalize(glm::vec3(-sunDir.x, 0.0f, -sunDir.z) + glm::vec3(0.0f, 1.4f, 0.0f));
      lookTarget = eye + away;
    }
    glm::mat4 viewM = glm::lookAt(eye, lookTarget, lookUp);
    glm::mat4 proj  = glm::perspective(glm::radians(55.0f), aspect, 2.0f, 40000.0f);
    // Mirror clip-space X: the world uses compass conventions (+X east, +Z north,
    // heading clockwise) like the browser's left-handed Babylon scene, but a
    // right-handed camera puts east on the LEFT — mirroring the coastlines and
    // reversing apparent A/D turn direction. Safe: every pipeline culls None.
    proj[0][0] = -proj[0][0];
    glm::mat4 viewProj = proj * viewM;

    // Our hull is server-authoritative — adopt the slug from the "wallet" message
    // (unless a CLI/env model override forced one).
    if (!ownVesselForced) {
      std::string s = mpClient.ownedShip();
      if (!s.empty()) ownVesselSlug = s;
    }
    // Frame the chase camera to the vessel's real length (set once) — big hulls
    // (24-30 m) need the camera much farther back than the small ones (~8 m).
    if (!camFramed && !ownVesselSlug.empty()) {
      camDist = 2.0f * vesselSpecFor(ownVesselSlug).hullHalfLen * 1.9f;
      camFramed = true;
    }
    if (const char* cd = std::getenv("SAILSIM_CAMDIST")) camDist = (float)std::atof(cd);   // debug zoom

    // Place a ship on the wave field: heave to the surface, tilt to its normal
    // (central differences of the FFT height, ~2 m step), yaw to heading, then
    // scale + keel-align per that hull.
    auto shipModel = [&](float x, float z, float heading, const Mesh& m) {
      float y = fftHeight(x, z);
      const float ee = 2.0f;
      float gx = fftHeight(x + ee, z) - fftHeight(x - ee, z);
      float gz = fftHeight(x, z + ee) - fftHeight(x, z - ee);
      glm::vec3 up = glm::normalize(glm::vec3(-gx / (2.0f * ee), 1.0f, -gz / (2.0f * ee)));
      glm::mat4 mm = glm::translate(glm::mat4(1.0f), glm::vec3(x, y - m.draft, z));
      glm::vec3 axis = glm::cross(glm::vec3(0, 1, 0), up);
      float axisLen = glm::length(axis);
      if (axisLen > 1e-5f)
        mm = mm * glm::rotate(glm::mat4(1.0f), std::asin(glm::clamp(axisLen, 0.0f, 1.0f)), axis / axisLen);
      mm = glm::rotate(mm, heading + m.bowYaw, glm::vec3(0, 1, 0));
      mm = glm::scale(mm, glm::vec3(m.shipScale));
      mm = glm::translate(mm, -m.keelCenter);
      return mm;
    };

    // Our hull uses the ported buoyancy (heave + pitch/roll) and sailing heel,
    // applied in the ship's own frame (yaw -> pitch -> roll -> model bow-yaw).
    auto ownShipModel = [&](const Mesh& m) {
      glm::mat4 mm = glm::translate(glm::mat4(1.0f), glm::vec3(shipX, ownBuoy.x - m.draft, shipZ));
      mm = glm::rotate(mm, shipHeading, glm::vec3(0, 1, 0));
      mm = glm::rotate(mm, -ownBuoy.y, glm::vec3(1, 0, 0));                          // pitch (bow up on +)
      mm = glm::rotate(mm, ownBuoy.z + glm::radians(vessel.heelDeg), glm::vec3(0, 0, 1));  // roll + heel
      mm = glm::rotate(mm, m.bowYaw, glm::vec3(0, 1, 0));
      mm = glm::scale(mm, glm::vec3(m.shipScale));
      mm = glm::translate(mm, -m.keelCenter);
      return mm;
    };

    // Draw list: our ship first (so it takes reflection slot 0), then remote players.
    struct ShipInst { Mesh* mesh; glm::mat4 model; };
    std::vector<ShipInst> ships;
    Mesh* ownMesh = nullptr;
    if (sailing && !ownVesselSlug.empty()) {
      ownMesh = &vesselFor(ownVesselSlug);
      ships.push_back({ ownMesh, ownShipModel(*ownMesh) });
    }
    if (sailing) {
      for (const mp::RemotePlayer& rp : mpClient.players()) {
        Mesh& rmv = vesselFor(rp.vesselSlug.empty() ? "pinnace" : rp.vesselSlug);
        ships.push_back({ &rmv, shipModel(rp.x, rp.z, glm::radians(rp.heading), rmv) });   // server heading is degrees
      }
    }

    // Upload the celestial maps once their async fetch+decode completes, then wire
    // them into the sky bind group (params flags flip the shader off placeholders).
    if (!moonReady && moonFuture.valid() &&
        moonFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
      sky::Image im = moonFuture.get();
      if (im.ok) {
        wgpuTextureViewRelease(sky.moonView); wgpuTextureRelease(sky.moonTex);
        sky.moonTex  = makeSampledRGBA(device, queue, (uint32_t)im.w, (uint32_t)im.h, im.rgba.data(), true);
        sky.moonView = wgpuTextureCreateView(sky.moonTex, nullptr);
        rebuildSkyBind(device, sky);
        moonReady = true;
      }
    }
    if (!starsReady && starsFuture.valid() &&
        starsFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
      sky::Image im = starsFuture.get();
      if (im.ok) {
        wgpuTextureViewRelease(sky.starsView); wgpuTextureRelease(sky.starsTex);
        sky.starsTex  = makeSampledRGBA(device, queue, (uint32_t)im.w, (uint32_t)im.h, im.rgba.data(), true);
        sky.starsView = wgpuTextureCreateView(sky.starsTex, nullptr);
        rebuildSkyBind(device, sky);
        starsReady = true;
      }
    }
    // Biome tiles arrived? Upload + rewire the terrain bind group (works whether
    // the heightfield is already in or still pending — see rebuildTerrainBind).
    if (!biomeReady && biomeFuture.valid() &&
        biomeFuture.wait_for(std::chrono::seconds(0)) == std::future_status::ready) {
      biome::Set bs = biomeFuture.get();
      biomeReady = true;   // one shot either way — a failed fetch keeps the fallback colours
      if (bs.ok) uploadTerrainBiome(device, queue, terrainR, bs);
    }
    const glm::vec4 skyMoon(moonDir, moonFade);
    const glm::vec4 skyParams(starFade, starsReady ? 1.0f : 0.0f, moonReady ? 1.0f : 0.0f, 0.0f);

    // ── Reflection pass: sky + ship through a mirror camera (reflected across y=0),
    //    rendered into reflView. Queue-ordered uniform writes let one buffer serve
    //    both passes. Skipped on the landing screen. ──
    if (sailing) {
      glm::mat4 mirror = glm::scale(glm::mat4(1.0f), glm::vec3(1.0f, -1.0f, 1.0f));
      glm::mat4 reflVP = proj * viewM * mirror;
      glm::vec3 reflEye(eye.x, -eye.y, eye.z);
      SkyUniform rs{ glm::inverse(reflVP), glm::vec4(reflEye, 1.0f), glm::vec4(sun, 0.0f),
                     skyMoon, skyParams };
      wgpuQueueWriteBuffer(queue, sky.uniformBuf, 0, &rs, sizeof(rs));
      if (ownMesh) {
        MeshUniforms rm{ reflVP * ships[0].model, ships[0].model, glm::vec4(reflEye, 1.0f),
                         glm::vec4(lightDir, dayK), glm::vec4(ownMesh->maskFloorY, 0.0f, 0.0f, 0.0f) };
        wgpuQueueWriteBuffer(queue, ownMesh->uniformBuf, 0, &rm, sizeof(rm));   // slot 0
      }

      WGPUCommandEncoder renc = wgpuDeviceCreateCommandEncoder(device, nullptr);
      WGPURenderPassColorAttachment rc = {};
      rc.view = reflView; rc.loadOp = WGPULoadOp_Clear; rc.storeOp = WGPUStoreOp_Store;
      rc.clearValue = WGPUColor{ 0.55, 0.72, 0.88, 1.0 };
      WGPURenderPassDepthStencilAttachment rd = {};
      rd.view = reflDepthView; rd.depthLoadOp = WGPULoadOp_Clear; rd.depthStoreOp = WGPUStoreOp_Store; rd.depthClearValue = 1.0f;
      rd.stencilLoadOp = WGPULoadOp_Clear; rd.stencilStoreOp = WGPUStoreOp_Discard;   // stencil unused here (format has it)
      WGPURenderPassDescriptor rp_desc = {};
      rp_desc.colorAttachmentCount = 1; rp_desc.colorAttachments = &rc; rp_desc.depthStencilAttachment = &rd;
      WGPURenderPassEncoder rp = wgpuCommandEncoderBeginRenderPass(renc, &rp_desc);
      wgpuRenderPassEncoderSetPipeline(rp, sky.pipeline);
      wgpuRenderPassEncoderSetBindGroup(rp, 0, sky.bindGroup, 0, nullptr);
      wgpuRenderPassEncoderDraw(rp, 3, 1, 0, 0);
      if (ownMesh) {
        uint32_t zeroOff = 0;
        wgpuRenderPassEncoderSetPipeline(rp, ownMesh->pipeline);
        wgpuRenderPassEncoderSetVertexBuffer(rp, 0, ownMesh->vbuf, 0, WGPU_WHOLE_SIZE);
        wgpuRenderPassEncoderSetIndexBuffer(rp, ownMesh->ibuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
        for (size_t i = 0; i < ownMesh->submeshes.size(); ++i) {
          wgpuRenderPassEncoderSetBindGroup(rp, 0, ownMesh->bindGroups[i], 1, &zeroOff);
          wgpuRenderPassEncoderDrawIndexed(rp, ownMesh->submeshes[i].indexCount, 1, ownMesh->submeshes[i].indexOffset, 0, 0);
        }
      }
      wgpuRenderPassEncoderEnd(rp);
      wgpuRenderPassEncoderRelease(rp);
      WGPUCommandBuffer rcmd = wgpuCommandEncoderFinish(renc, nullptr);
      wgpuQueueSubmit(queue, 1, &rcmd);
      wgpuCommandBufferRelease(rcmd);
      wgpuCommandEncoderRelease(renc);
    }

    // ── Main-pass uniforms ──
    glm::vec4 oceanParams(c0.lengthScale(), c1.lengthScale(), c2.lengthScale(), seaAmp);
    glm::vec4 oceanScreen((float)curW, (float)curH, shipX, shipZ);   // zw = ocean origin
    // Near grid: full displacement, no discard. Far ring: flat (vertexAmp 0), but
    // discards the centre so the detailed near grid shows there.
    const glm::vec4 oceanSun(lightDir, dayK);
    OceanCamera oc{ viewProj, glm::vec4(eye, 1.0f), oceanParams, oceanScreen,
                    glm::vec4(seaAmp, 0.0f, 0.0f, 0.0f), oceanSun };
    wgpuQueueWriteBuffer(queue, ocean.uniformBuf, 0, &oc, sizeof(oc));
    OceanCamera ocFar{ viewProj, glm::vec4(eye, 1.0f), oceanParams, oceanScreen,
                       glm::vec4(0.0f, 1400.0f, 0.0f, 0.0f), oceanSun };
    wgpuQueueWriteBuffer(queue, ocean.farUniformBuf, 0, &ocFar, sizeof(ocFar));
    SkyUniform sku{ glm::inverse(viewProj), glm::vec4(eye, 1.0f), glm::vec4(sun, 0.0f),
                    skyMoon, skyParams };
    wgpuQueueWriteBuffer(queue, sky.uniformBuf, 0, &sku, sizeof(sku));

    // ── God rays: sun screen position + exposure. Exposure fades in just above the
    //    horizon and out toward high noon (shafts read as dramatic streaks when the
    //    sun is low), and to nothing at night — mirroring the client's godRays. ──
    {
      glm::vec4 sclip = viewProj * glm::vec4(eye + sunDir * 100000.0f, 1.0f);
      bool sunFront = sclip.w > 0.0f;
      glm::vec2 sunUV(0.5f, 0.5f);
      if (sunFront) {
        glm::vec3 sndc = glm::vec3(sclip) / sclip.w;
        sunUV = glm::vec2(sndc.x * 0.5f + 0.5f, 0.5f - sndc.y * 0.5f);   // NDC -> framebuffer UV (y down)
      }
      float dayUp   = glm::clamp((sunEl + 0.02f) / 0.10f, 0.0f, 1.0f);   // fade in just above the horizon
      float lowSun  = 1.0f - glm::clamp(sunEl / 0.55f, 0.0f, 1.0f);      // strongest when the sun is low
      float exposure = 0.55f * dayUp * (0.35f + 0.65f * lowSun);
      GodrayOcc go{ glm::inverse(viewProj), glm::vec4(eye, 1.0f), glm::vec4(sunDir, dayUp) };
      wgpuQueueWriteBuffer(queue, godrays.occUniform, 0, &go, sizeof(go));
      float inView = (sunFront && exposure > 0.001f &&
                      sunUV.x > -1.0f && sunUV.x < 2.0f && sunUV.y > -1.0f && sunUV.y < 2.0f) ? 1.0f : 0.0f;
      // weight is per-sample; with 48 samples accumulating along the ray it must be
      // small (~0.05) or the shafts blow out to white.
      GodrayBlur gb{ glm::vec4(sunUV.x, sunUV.y, exposure, 0.96f),
                     glm::vec4(0.05f, 0.9f, 48.0f, inView) };
      wgpuQueueWriteBuffer(queue, godrays.blurUniform, 0, &gb, sizeof(gb));
    }
    if (terrainR.ready) {
      const terrain::Manifest& tm = terr.manifest();
      TerrainU tu{ viewProj, glm::vec4(eye, 1.0f),
                   glm::vec4((float)tm.minX, (float)tm.maxX, (float)tm.minZ, (float)tm.maxZ),
                   glm::vec4((float)tm.width, (float)tm.height, shipX, shipZ),
                   glm::vec4(lightDir, dayK),   // land lit by sun (day) / moon (night); w = daylight
                   glm::vec4(terrainR.peakH, terrainR.hasBiome ? 1.0f : 0.0f, 0.0f, 0.0f) };
      wgpuQueueWriteBuffer(queue, terrainR.uniformBuf, 0, &tu, sizeof(tu));
    }
    // Clouds: integrate wind drift, derive time-of-day light, write uniforms. The
    // sun/sky/ground colour model + coverage/type mirror the client's cloud plugin.
    {
      mp::WaveState wv = mpClient.wave();
      float windSpeed = wv.valid ? wv.windSpeed : 0.0f;
      float windRad = glm::radians(wv.windBearing);
      cloudDrift += glm::vec2(std::sin(windRad), std::cos(windRad)) * (windSpeed * 0.08f * dt);
      // Light the clouds from the sun by day, the moon by night (sd.y stays > 0
      // in both since moonDir = -sunDir); dayK cross-fades warm sun ↔ cool moon.
      glm::vec3 sd = glm::normalize(lightDir);
      float el = glm::max(0.0f, sd.y);
      // Coverage/type/base from the eased weather state (client's cloud.service model).
      float cov = std::pow(cloudiness, 1.8f);
      float ctype = 0.40f + storminess * 0.55f;
      float cloudBase = 900.0f - storminess * 220.0f;
      float cloudTop = cloudBase + (600.0f + storminess * 700.0f);
      // Bright enough that the sunlit cloud faces saturate to white (the tops SHOULD be
      // white); paired with the low ambient above, that gives strong white-top ↔
      // dark-shadow contrast rather than a flat blob.
      float sunBright = 0.05f + 1.5f * el;
      glm::vec3 dayLit(sunBright, sunBright * (0.52f + 0.48f * el), sunBright * (0.34f + 0.62f * el));
      glm::vec3 moonLit = glm::vec3(0.28f, 0.34f, 0.50f) * (0.25f + 0.75f * el);   // dim silver
      glm::vec3 sunCol = glm::mix(moonLit, dayLit, dayK);
      float stormDim = glm::max(0.08f, 1.0f - glm::max(0.0f, cov - 0.45f) * 1.5f);
      glm::vec3 daySky(stormDim * (0.12f + 1.8f * el), stormDim * (0.15f + 1.9f * el), stormDim * (0.20f + 2.0f * el));
      glm::vec3 dayGrnd(stormDim * (0.05f + 0.16f * el), stormDim * (0.07f + 0.20f * el), stormDim * (0.09f + 0.26f * el));
      glm::vec3 skyC  = glm::mix(stormDim * glm::vec3(0.03f, 0.045f, 0.075f), daySky,  dayK);
      glm::vec3 grndC = glm::mix(stormDim * glm::vec3(0.02f, 0.025f, 0.040f), dayGrnd, dayK);
      CloudU cu{ glm::inverse(viewProj), glm::vec4(eye, 1.0f), glm::vec4(sd, 0.0f),
                 glm::vec4(sunCol, 0.0f), glm::vec4(skyC, 0.0f), glm::vec4(grndC, 0.0f),
                 glm::vec4(cloudBase, cloudTop, cov, ctype),
                 glm::vec4(t, cloudDrift.x, cloudDrift.y, 120000.0f) };
      wgpuQueueWriteBuffer(queue, clouds.uniformBuf, 0, &cu, sizeof(cu));
    }
    // Every ship's uniforms into its vessel's dynamic-offset slots (same per-mesh
    // ordering as the draw loop below, so slot indices line up).
    {
      std::map<Mesh*, uint32_t> slot;
      for (const ShipInst& s : ships) {
        uint32_t idx = slot[s.mesh];
        if (idx >= kMaxShipInstances) continue;
        MeshUniforms mu{ viewProj * s.model, s.model, glm::vec4(eye, 1.0f),
                         glm::vec4(lightDir, dayK), glm::vec4(s.mesh->maskFloorY, 0.0f, 0.0f, 0.0f) };
        wgpuQueueWriteBuffer(queue, s.mesh->uniformBuf,
                             (uint64_t)idx * s.mesh->uniformStride, &mu, sizeof(mu));
        slot[s.mesh] = idx + 1;
      }
    }

    WGPUSurfaceTexture surfaceTex;
    wgpuSurfaceGetCurrentTexture(surface, &surfaceTex);
    if (!surfaceTex.texture) continue;  // e.g. minimised / needs reconfigure

    WGPUTextureView view = wgpuTextureCreateView(surfaceTex.texture, nullptr);

    WGPUCommandEncoderDescriptor encDesc = {};
    WGPUCommandEncoder encoder = wgpuDeviceCreateCommandEncoder(device, &encDesc);

    WGPURenderPassColorAttachment colorAttachment = {};
    colorAttachment.view = view;
    colorAttachment.loadOp = WGPULoadOp_Clear;
    colorAttachment.storeOp = WGPUStoreOp_Store;
    // Sky-blue behind the sailing scene; plain brown behind the login/landing screen.
    colorAttachment.clearValue = sailing ? WGPUColor{0.75, 0.85, 0.92, 1.0}
                                         : WGPUColor{0.24, 0.16, 0.10, 1.0};
    // (Newer webgpu.h adds colorAttachment.depthSlice = WGPU_DEPTH_SLICE_UNDEFINED here;
    //  wgpu-native v0.19 has no such field — zero-init leaves it correctly unset.)

    WGPURenderPassDepthStencilAttachment depthAttachment = {};
    depthAttachment.view = depthView;
    depthAttachment.depthLoadOp = WGPULoadOp_Clear;
    depthAttachment.depthStoreOp = WGPUStoreOp_Store;
    depthAttachment.stencilLoadOp = WGPULoadOp_Clear;    // hull mask stamped + consumed in this pass
    depthAttachment.stencilStoreOp = WGPUStoreOp_Store;  // format carries stencil; later passes reload it
    depthAttachment.depthClearValue = 1.0f;

    WGPURenderPassDescriptor passDesc = {};
    passDesc.colorAttachmentCount = 1;
    passDesc.colorAttachments = &colorAttachment;
    passDesc.depthStencilAttachment = &depthAttachment;

    WGPURenderPassEncoder pass = wgpuCommandEncoderBeginRenderPass(encoder, &passDesc);
    WGPUBindGroup oceanBG = nullptr, oceanBGfar = nullptr;   // created below when the scene draws
    if (sailing) {
    // Sky first (background; doesn't write depth).
    wgpuRenderPassEncoderSetPipeline(pass, sky.pipeline);
    wgpuRenderPassEncoderSetBindGroup(pass, 0, sky.bindGroup, 0, nullptr);
    wgpuRenderPassEncoderDraw(pass, 3, 1, 0, 0);

    // Terrain (islands) — displaced height grid, depth-tested against the water.
    if (terrainR.ready) {
      wgpuRenderPassEncoderSetPipeline(pass, terrainR.pipeline);
      wgpuRenderPassEncoderSetBindGroup(pass, 0, terrainR.bindGroup, 0, nullptr);
      wgpuRenderPassEncoderSetVertexBuffer(pass, 0, terrainR.vbuf, 0, WGPU_WHOLE_SIZE);
      wgpuRenderPassEncoderSetIndexBuffer(pass, terrainR.ibuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
      wgpuRenderPassEncoderDrawIndexed(pass, terrainR.indexCount, 1, 0, 0, 0);
    }
    // Hull water mask: stamp every masked vessel's hull into the stencil plane
    // BEFORE the ocean draws (same per-instance uniform slots as the ship draws
    // below, so the stamp rides the exact buoyancy/heel transform). The ocean's
    // stencil test (NotEqual ref) then rejects those pixels — no sea on the deck.
    {
      HullStencil& hs = hullStencil(device, surfaceFormat);
      bool stencilBound = false;
      std::map<Mesh*, uint32_t> slot;
      for (const ShipInst& s : ships) {
        Mesh* m = s.mesh;
        uint32_t idx = slot[m];
        if (idx >= kMaxShipInstances) continue;
        slot[m] = idx + 1;                       // keep slot numbering aligned with the draw loop
        if (!m->oceanMask || m->hullRanges.empty()) continue;
        if (!stencilBound) { wgpuRenderPassEncoderSetPipeline(pass, hs.pipeline); stencilBound = true; }
        uint32_t dynOff = idx * m->uniformStride;
        wgpuRenderPassEncoderSetVertexBuffer(pass, 0, m->vbuf, 0, WGPU_WHOLE_SIZE);
        wgpuRenderPassEncoderSetIndexBuffer(pass, m->ibuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
        wgpuRenderPassEncoderSetBindGroup(pass, 0, m->stencilBind, 1, &dynOff);
        wgpuRenderPassEncoderSetStencilReference(pass, kHullStencilRef);
        for (const auto& r : m->hullRanges)
          wgpuRenderPassEncoderDrawIndexed(pass, r.second, 1, r.first, 0, 0);
      }
    }
    // The ocean tests against the stamped ref; ships after it ignore the reference
    // (their stencil compare is Always).
    wgpuRenderPassEncoderSetStencilReference(pass, kHullStencilRef);
    // Ocean — the real FFT shader on BOTH rings (shared cascade textures). The two
    // bind groups differ only in the uniform buffer: near = displaced detail; far =
    // geometrically flat but fully wave-shaded, reaching the horizon without alias.
    WGPUBindGroupEntry oe[12] = {};
    oe[1].binding = 1;  oe[1].textureView  = c0.displacement();
    oe[2].binding = 2;  oe[2].textureView  = c0.derivatives();
    oe[3].binding = 3;  oe[3].textureView  = c0.turbulence();
    oe[4].binding = 4;  oe[4].textureView  = c1.displacement();
    oe[5].binding = 5;  oe[5].textureView  = c1.derivatives();
    oe[6].binding = 6;  oe[6].textureView  = c1.turbulence();
    oe[7].binding = 7;  oe[7].textureView  = c2.displacement();
    oe[8].binding = 8;  oe[8].textureView  = c2.derivatives();
    oe[9].binding = 9;  oe[9].textureView  = c2.turbulence();
    oe[10].binding = 10; oe[10].sampler = ocean.sampler;
    oe[11].binding = 11; oe[11].textureView = reflView;
    oe[0].binding = 0;  oe[0].buffer = ocean.farUniformBuf; oe[0].size = sizeof(OceanCamera);
    WGPUBindGroupDescriptor obdF = {}; obdF.layout = ocean.bgl; obdF.entryCount = 12; obdF.entries = oe;
    oceanBGfar = wgpuDeviceCreateBindGroup(device, &obdF);
    oe[0].buffer = ocean.uniformBuf;
    WGPUBindGroupDescriptor obd = {}; obd.layout = ocean.bgl; obd.entryCount = 12; obd.entries = oe;
    oceanBG = wgpuDeviceCreateBindGroup(device, &obd);

    wgpuRenderPassEncoderSetPipeline(pass, ocean.pipeline);
    // Far ring first (fills to the horizon), then the detailed near grid over it.
    wgpuRenderPassEncoderSetBindGroup(pass, 0, oceanBGfar, 0, nullptr);
    wgpuRenderPassEncoderSetVertexBuffer(pass, 0, ocean.farVbuf, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderSetIndexBuffer(pass, ocean.farIbuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderDrawIndexed(pass, ocean.farIndexCount, 1, 0, 0, 0);
    wgpuRenderPassEncoderSetBindGroup(pass, 0, oceanBG, 0, nullptr);
    wgpuRenderPassEncoderSetVertexBuffer(pass, 0, ocean.vbuf, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderSetIndexBuffer(pass, ocean.ibuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderDrawIndexed(pass, ocean.indexCount, 1, 0, 0, 0);

    // Ships: one draw per instance, each selecting its uniform slot via dynamic offset.
    {
      std::map<Mesh*, uint32_t> slot;
      for (const ShipInst& s : ships) {
        Mesh* m = s.mesh;
        uint32_t idx = slot[m];
        if (idx >= kMaxShipInstances) continue;
        uint32_t dynOff = idx * m->uniformStride;
        wgpuRenderPassEncoderSetPipeline(pass, m->pipeline);
        wgpuRenderPassEncoderSetVertexBuffer(pass, 0, m->vbuf, 0, WGPU_WHOLE_SIZE);
        wgpuRenderPassEncoderSetIndexBuffer(pass, m->ibuf, WGPUIndexFormat_Uint32, 0, WGPU_WHOLE_SIZE);
        for (size_t i = 0; i < m->submeshes.size(); ++i) {
          const Submesh& sm = m->submeshes[i];
          wgpuRenderPassEncoderSetBindGroup(pass, 0, m->bindGroups[i], 1, &dynOff);
          wgpuRenderPassEncoderDrawIndexed(pass, sm.indexCount, 1, sm.indexOffset, 0, 0);
        }
        slot[m] = idx + 1;
      }
    }

    }  // end if (sailing) scene draws
    wgpuRenderPassEncoderEnd(pass);
    wgpuRenderPassEncoderRelease(pass);

    // ── God-ray occlusion: the sun's brightness where the sky shows, depth-tested
    //    against the scene so terrain/ocean/ships silhouette it into shafts. ──
    if (sailing) {
      WGPURenderPassColorAttachment ca = {};
      ca.view = grView; ca.loadOp = WGPULoadOp_Clear; ca.storeOp = WGPUStoreOp_Store;
      ca.clearValue = WGPUColor{ 0.0, 0.0, 0.0, 1.0 };
      WGPURenderPassDepthStencilAttachment da = {};
      da.view = depthView; da.depthLoadOp = WGPULoadOp_Load; da.depthStoreOp = WGPUStoreOp_Store;
      da.stencilLoadOp = WGPULoadOp_Load; da.stencilStoreOp = WGPUStoreOp_Store;   // untouched pass-through
      WGPURenderPassDescriptor gpd = {};
      gpd.colorAttachmentCount = 1; gpd.colorAttachments = &ca; gpd.depthStencilAttachment = &da;
      WGPURenderPassEncoder gp = wgpuCommandEncoderBeginRenderPass(encoder, &gpd);
      wgpuRenderPassEncoderSetPipeline(gp, godrays.occPipeline);
      wgpuRenderPassEncoderSetBindGroup(gp, 0, godrays.occBind, 0, nullptr);
      wgpuRenderPassEncoderDraw(gp, 3, 1, 0, 0);
      wgpuRenderPassEncoderEnd(gp);
      wgpuRenderPassEncoderRelease(gp);
    }

    // ── Cloud pass: ray-march into the offscreen RGBA16F buffer, occluded by the
    //    scene depth (load, no write). Only while sailing. ──
    if (sailing) {
      float dsz[4] = { (float)curW, (float)curH, 0.0f, 0.0f };
      wgpuQueueWriteBuffer(queue, clouds.denoiseUniform, 0, dsz, sizeof(dsz));
      WGPURenderPassColorAttachment ca = {};
      ca.view = cloudView; ca.loadOp = WGPULoadOp_Clear; ca.storeOp = WGPUStoreOp_Store;
      ca.clearValue = WGPUColor{ 0.0, 0.0, 0.0, 0.0 };
      WGPURenderPassDepthStencilAttachment da = {};
      da.view = depthView; da.depthLoadOp = WGPULoadOp_Load; da.depthStoreOp = WGPUStoreOp_Store;
      da.stencilLoadOp = WGPULoadOp_Load; da.stencilStoreOp = WGPUStoreOp_Store;   // untouched pass-through
      WGPURenderPassDescriptor cpd = {};
      cpd.colorAttachmentCount = 1; cpd.colorAttachments = &ca; cpd.depthStencilAttachment = &da;
      WGPURenderPassEncoder cp = wgpuCommandEncoderBeginRenderPass(encoder, &cpd);
      wgpuRenderPassEncoderSetPipeline(cp, clouds.pipeline);
      wgpuRenderPassEncoderSetBindGroup(cp, 0, clouds.bindGroup, 0, nullptr);
      wgpuRenderPassEncoderDraw(cp, 3, 1, 0, 0);
      wgpuRenderPassEncoderEnd(cp);
      wgpuRenderPassEncoderRelease(cp);
    }

    // ── Final pass: denoise-composite the clouds over the scene (sailing), then
    //    Dear ImGui (login panel / HUD) on top. ──
    {
      WGPURenderPassColorAttachment ca = {};
      ca.view = view; ca.loadOp = WGPULoadOp_Load; ca.storeOp = WGPUStoreOp_Store;
      WGPURenderPassDepthStencilAttachment da = {};
      da.view = depthView; da.depthLoadOp = WGPULoadOp_Load; da.depthStoreOp = WGPUStoreOp_Store;
      da.stencilLoadOp = WGPULoadOp_Load; da.stencilStoreOp = WGPUStoreOp_Store;   // untouched pass-through
      WGPURenderPassDescriptor fpd = {};
      fpd.colorAttachmentCount = 1; fpd.colorAttachments = &ca; fpd.depthStencilAttachment = &da;
      WGPURenderPassEncoder fp = wgpuCommandEncoderBeginRenderPass(encoder, &fpd);
      if (sailing) {
        wgpuRenderPassEncoderSetPipeline(fp, clouds.denoisePipeline);
        wgpuRenderPassEncoderSetBindGroup(fp, 0, denoiseBG, 0, nullptr);
        wgpuRenderPassEncoderDraw(fp, 3, 1, 0, 0);
        // God-ray shafts, additively blended over the composited scene.
        wgpuRenderPassEncoderSetPipeline(fp, godrays.blurPipeline);
        wgpuRenderPassEncoderSetBindGroup(fp, 0, godrays.blurBind, 0, nullptr);
        wgpuRenderPassEncoderDraw(fp, 3, 1, 0, 0);
      }
      ImGui_ImplWGPU_RenderDrawData(ImGui::GetDrawData(), fp);
      wgpuRenderPassEncoderEnd(fp);
      wgpuRenderPassEncoderRelease(fp);
    }

    WGPUCommandBufferDescriptor cmdDesc = {};
    WGPUCommandBuffer cmd = wgpuCommandEncoderFinish(encoder, &cmdDesc);
    wgpuQueueSubmit(queue, 1, &cmd);

    if (shotPath && frame == shotFrame) {
      captureSurface(device, queue, surfaceTex.texture, curW, curH, shotPath);
      glfwSetWindowShouldClose(window, GLFW_TRUE);
    }

    wgpuCommandBufferRelease(cmd);
    wgpuCommandEncoderRelease(encoder);
    if (oceanBG) wgpuBindGroupRelease(oceanBG);
    if (oceanBGfar) wgpuBindGroupRelease(oceanBGfar);
    wgpuTextureViewRelease(view);

#ifndef __EMSCRIPTEN__
    wgpuSurfacePresent(surface);
#endif

    // Let Dawn/wgpu service their internal work queues each frame.
#if defined(WEBGPU_BACKEND_DAWN)
    wgpuDeviceTick(device);
#elif defined(WEBGPU_BACKEND_WGPU)
    wgpuDevicePoll(device, false, nullptr);
#endif
  }

  std::printf("[spike] render loop exited after %ld frames — tearing down cleanly\n", frame);

  // 7. Teardown
  wgpuTextureViewRelease(depthView);
  wgpuTextureRelease(depthTex);
  wgpuTextureViewRelease(reflView);      wgpuTextureRelease(reflTex);
  wgpuTextureViewRelease(reflDepthView); wgpuTextureRelease(reflDepth);
  wgpuRenderPipelineRelease(sky.pipeline);
  wgpuBindGroupRelease(sky.bindGroup);
  wgpuBufferRelease(sky.uniformBuf);
  wgpuSamplerRelease(sky.sampler);
  wgpuTextureViewRelease(sky.moonView);  wgpuTextureRelease(sky.moonTex);
  wgpuTextureViewRelease(sky.starsView); wgpuTextureRelease(sky.starsTex);
  wgpuShaderModuleRelease(sky.module);
  wgpuRenderPipelineRelease(godrays.occPipeline);  wgpuRenderPipelineRelease(godrays.blurPipeline);
  wgpuBindGroupRelease(godrays.occBind);           wgpuBindGroupRelease(godrays.blurBind);
  wgpuBufferRelease(godrays.occUniform);           wgpuBufferRelease(godrays.blurUniform);
  wgpuShaderModuleRelease(godrays.module);
  wgpuTextureViewRelease(grView); wgpuTextureRelease(grTex); wgpuSamplerRelease(grSampler);
  wgpuRenderPipelineRelease(ocean.pipeline);
  wgpuSamplerRelease(ocean.sampler);
  wgpuBufferRelease(ocean.vbuf);
  wgpuBufferRelease(ocean.ibuf);
  wgpuBufferRelease(ocean.uniformBuf);
  wgpuShaderModuleRelease(ocean.module);
  for (auto& kv : vessels) {
    Mesh& m = kv.second;
    wgpuRenderPipelineRelease(m.pipeline);
    for (WGPUBindGroup bg : m.bindGroups) wgpuBindGroupRelease(bg);
    for (WGPUTextureView v : m.views) wgpuTextureViewRelease(v);
    for (WGPUTexture t : m.textures) wgpuTextureRelease(t);
    wgpuSamplerRelease(m.sampler);
    wgpuBufferRelease(m.vbuf);
    wgpuBufferRelease(m.ibuf);
    wgpuBufferRelease(m.uniformBuf);
    wgpuShaderModuleRelease(m.module);
  }
  ImGui_ImplWGPU_Shutdown();
  ImGui_ImplGlfw_Shutdown();
  ImGui::DestroyContext();
  wgpuQueueRelease(queue);
  wgpuDeviceRelease(device);
  wgpuAdapterRelease(adapter);
  wgpuSurfaceRelease(surface);
  wgpuInstanceRelease(instance);
  glfwDestroyWindow(window);
  glfwTerminate();
  return EXIT_SUCCESS;
}
