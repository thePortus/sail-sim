// Grid of XZ positions spanning [-half, half]; the shader recentres it on the ship.
static void makeXZGrid(int N, float half, std::vector<float>& v, std::vector<uint32_t>& idx) {
  v.reserve((size_t)(N + 1) * (N + 1) * 2);
  for (int j = 0; j <= N; ++j)
    for (int i = 0; i <= N; ++i) {
      v.push_back(-half + (float)i / N * 2.0f * half);
      v.push_back(-half + (float)j / N * 2.0f * half);
    }
  idx.reserve((size_t)N * N * 6);
  for (int j = 0; j < N; ++j)
    for (int i = 0; i < N; ++i) {
      uint32_t a = (uint32_t)(j * (N + 1) + i), b = a + 1, c = a + (N + 1), d = c + 1;
      idx.insert(idx.end(), { a, c, b, b, c, d });
    }
}

