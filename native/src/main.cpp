// sail-sim native client — Phase 0 spike: Dawn (WebGPU) device bringup + clear-colour loop.
//
// This is the smallest program that proves the PORTING.md thesis on real hardware:
// a Dawn-backed WebGPU device, running on D3D12 (Windows) or Metal (macOS), driving a
// swapchain. It prints the resolved backend so you can see D3D12/Metal/Vulkan at a glance.
//
// The WebGPU C API (webgpu.h) is version-sensitive. This file targets the "classic"
// callback style shipped by the eliemichel/WebGPU-distribution `dawn` branch, where
// requestAdapter/requestDevice resolve their callbacks synchronously. If your pinned
// header differs, the two request helpers below and the surface-status check are the
// only spots likely to need a one-line reconcile — see native/README.md.

#include <webgpu/webgpu.h>
#if defined(WEBGPU_BACKEND_WGPU)
#include <webgpu/wgpu.h>   // wgpu-native extensions (e.g. wgpuDevicePoll)
#endif
#include <glfw3webgpu.h>
#include <GLFW/glfw3.h>

#include <cstdio>
#include <cstdlib>

#define GLM_FORCE_DEPTH_ZERO_TO_ONE   // WebGPU clip-space Z is [0,1], like D3D/Metal
#include <glm/glm.hpp>
#include <glm/gtc/matrix_transform.hpp>

#include "fft_test.hpp"
#include "cube_wgsl.h"   // generated by CMake: inline const char* CUBE_WGSL

// ── async request helpers (resolve synchronously on Dawn/wgpu in this distribution) ──

static WGPUAdapter requestAdapterSync(WGPUInstance instance, const WGPURequestAdapterOptions* options) {
  struct Result { WGPUAdapter adapter = nullptr; bool done = false; } result;
  auto onAdapter = [](WGPURequestAdapterStatus status, WGPUAdapter adapter,
                      char const* message, void* userdata) {
    auto* r = static_cast<Result*>(userdata);
    if (status == WGPURequestAdapterStatus_Success) r->adapter = adapter;
    else std::fprintf(stderr, "[spike] requestAdapter failed: %s\n", message ? message : "(no message)");
    r->done = true;
  };
  wgpuInstanceRequestAdapter(instance, options, onAdapter, &result);
  // If a future header makes this genuinely async, pump events here instead of asserting.
  if (!result.done) std::fprintf(stderr, "[spike] requestAdapter did not resolve synchronously\n");
  return result.adapter;
}

static WGPUDevice requestDeviceSync(WGPUAdapter adapter, const WGPUDeviceDescriptor* descriptor) {
  struct Result { WGPUDevice device = nullptr; bool done = false; } result;
  auto onDevice = [](WGPURequestDeviceStatus status, WGPUDevice device,
                     char const* message, void* userdata) {
    auto* r = static_cast<Result*>(userdata);
    if (status == WGPURequestDeviceStatus_Success) r->device = device;
    else std::fprintf(stderr, "[spike] requestDevice failed: %s\n", message ? message : "(no message)");
    r->done = true;
  };
  wgpuAdapterRequestDevice(adapter, descriptor, onDevice, &result);
  if (!result.done) std::fprintf(stderr, "[spike] requestDevice did not resolve synchronously\n");
  return result.device;
}

static void onDeviceError(WGPUErrorType type, char const* message, void*) {
  std::fprintf(stderr, "[spike] uncaptured device error (%d): %s\n",
               (int)type, message ? message : "(no message)");
}

static const WGPUTextureFormat kDepthFormat = WGPUTextureFormat_Depth24Plus;

// A framebuffer-sized depth texture, recreated on resize.
static WGPUTexture makeDepthTexture(WGPUDevice device, uint32_t w, uint32_t h) {
  WGPUTextureDescriptor td = {};
  td.usage = WGPUTextureUsage_RenderAttachment;
  td.dimension = WGPUTextureDimension_2D;
  td.size = { w, h, 1 };
  td.format = kDepthFormat;
  td.mipLevelCount = 1;
  td.sampleCount = 1;
  return wgpuDeviceCreateTexture(device, &td);
}

// Phase 1: a 3D cube driven by an MVP uniform, depth-tested. Everything a mesh
// draw needs — vertex + index buffers, a camera bind group, a depth-stencil
// pipeline state — in one place.
struct Cube {
  WGPURenderPipeline pipeline;
  WGPUBuffer         vbuf, ibuf, camBuf;
  WGPUBindGroup      bindGroup;
  WGPUShaderModule   module;
  uint32_t           indexCount;
};

static Cube createCube(WGPUDevice device, WGPUQueue queue, WGPUTextureFormat colorFormat) {
  // 8 corners: position (x,y,z) + colour (r,g,b).
  const float V[] = {
    -0.5f,-0.5f,-0.5f,  0,0,0,   0.5f,-0.5f,-0.5f,  1,0,0,
     0.5f, 0.5f,-0.5f,  1,1,0,  -0.5f, 0.5f,-0.5f,  0,1,0,
    -0.5f,-0.5f, 0.5f,  0,0,1,   0.5f,-0.5f, 0.5f,  1,0,1,
     0.5f, 0.5f, 0.5f,  1,1,1,  -0.5f, 0.5f, 0.5f,  0,1,1,
  };
  const uint16_t I[] = {
    0,1,2, 0,2,3,   4,6,5, 4,7,6,   4,5,1, 4,1,0,
    3,2,6, 3,6,7,   4,0,3, 4,3,7,   1,5,6, 1,6,2,
  };

  WGPUBufferDescriptor vbd = {};
  vbd.usage = WGPUBufferUsage_Vertex | WGPUBufferUsage_CopyDst; vbd.size = sizeof(V);
  WGPUBuffer vbuf = wgpuDeviceCreateBuffer(device, &vbd);
  wgpuQueueWriteBuffer(queue, vbuf, 0, V, sizeof(V));

  WGPUBufferDescriptor ibd = {};
  ibd.usage = WGPUBufferUsage_Index | WGPUBufferUsage_CopyDst; ibd.size = sizeof(I);
  WGPUBuffer ibuf = wgpuDeviceCreateBuffer(device, &ibd);
  wgpuQueueWriteBuffer(queue, ibuf, 0, I, sizeof(I));

  WGPUBufferDescriptor cbd = {};
  cbd.usage = WGPUBufferUsage_Uniform | WGPUBufferUsage_CopyDst; cbd.size = sizeof(glm::mat4);
  WGPUBuffer camBuf = wgpuDeviceCreateBuffer(device, &cbd);

  WGPUShaderModuleWGSLDescriptor wgsl = {};
  wgsl.chain.sType = WGPUSType_ShaderModuleWGSLDescriptor;
  wgsl.code = CUBE_WGSL;
  WGPUShaderModuleDescriptor smd = {};
  smd.nextInChain = &wgsl.chain;
  WGPUShaderModule module = wgpuDeviceCreateShaderModule(device, &smd);

  // camera uniform @group(0) @binding(0), visible to the vertex stage
  WGPUBindGroupLayoutEntry bgle = {};
  bgle.binding = 0;
  bgle.visibility = WGPUShaderStage_Vertex;
  bgle.buffer.type = WGPUBufferBindingType_Uniform;
  WGPUBindGroupLayoutDescriptor bgld = {};
  bgld.entryCount = 1; bgld.entries = &bgle;
  WGPUBindGroupLayout bgl = wgpuDeviceCreateBindGroupLayout(device, &bgld);

  WGPUBindGroupEntry bge = {};
  bge.binding = 0; bge.buffer = camBuf; bge.size = sizeof(glm::mat4);
  WGPUBindGroupDescriptor bgd = {};
  bgd.layout = bgl; bgd.entryCount = 1; bgd.entries = &bge;
  WGPUBindGroup bindGroup = wgpuDeviceCreateBindGroup(device, &bgd);

  WGPUPipelineLayoutDescriptor pld = {};
  pld.bindGroupLayoutCount = 1; pld.bindGroupLayouts = &bgl;
  WGPUPipelineLayout pl = wgpuDeviceCreatePipelineLayout(device, &pld);

  WGPUVertexAttribute attrs[2] = {};
  attrs[0].format = WGPUVertexFormat_Float32x3; attrs[0].offset = 0;                 attrs[0].shaderLocation = 0;
  attrs[1].format = WGPUVertexFormat_Float32x3; attrs[1].offset = 3 * sizeof(float); attrs[1].shaderLocation = 1;
  WGPUVertexBufferLayout vbl = {};
  vbl.arrayStride = 6 * sizeof(float);
  vbl.stepMode = WGPUVertexStepMode_Vertex;
  vbl.attributeCount = 2; vbl.attributes = attrs;

  WGPUDepthStencilState ds = {};
  ds.format = kDepthFormat;
  ds.depthWriteEnabled = true;
  ds.depthCompare = WGPUCompareFunction_Less;
  ds.stencilFront.compare = WGPUCompareFunction_Always;
  ds.stencilFront.failOp = WGPUStencilOperation_Keep;
  ds.stencilFront.depthFailOp = WGPUStencilOperation_Keep;
  ds.stencilFront.passOp = WGPUStencilOperation_Keep;
  ds.stencilBack = ds.stencilFront;
  ds.stencilReadMask = 0xFFFFFFFFu; ds.stencilWriteMask = 0xFFFFFFFFu;

  WGPUColorTargetState target = {};
  target.format = colorFormat;
  target.writeMask = WGPUColorWriteMask_All;
  WGPUFragmentState frag = {};
  frag.module = module; frag.entryPoint = "fs_main";
  frag.targetCount = 1; frag.targets = &target;

  WGPURenderPipelineDescriptor rpd = {};
  rpd.layout = pl;
  rpd.vertex.module = module;
  rpd.vertex.entryPoint = "vs_main";
  rpd.vertex.bufferCount = 1; rpd.vertex.buffers = &vbl;
  rpd.primitive.topology = WGPUPrimitiveTopology_TriangleList;
  rpd.primitive.frontFace = WGPUFrontFace_CCW;
  rpd.primitive.cullMode = WGPUCullMode_None;   // depth test handles occlusion
  rpd.depthStencil = &ds;
  rpd.multisample.count = 1;
  rpd.multisample.mask = 0xFFFFFFFFu;
  rpd.fragment = &frag;
  WGPURenderPipeline pipeline = wgpuDeviceCreateRenderPipeline(device, &rpd);

  wgpuPipelineLayoutRelease(pl);
  wgpuBindGroupLayoutRelease(bgl);
  return { pipeline, vbuf, ibuf, camBuf, bindGroup, module, (uint32_t)(sizeof(I) / sizeof(I[0])) };
}

static const char* backendTypeName(WGPUBackendType t) {
  switch (t) {
    case WGPUBackendType_D3D11:  return "D3D11";
    case WGPUBackendType_D3D12:  return "D3D12";
    case WGPUBackendType_Metal:  return "Metal";
    case WGPUBackendType_Vulkan: return "Vulkan";
    case WGPUBackendType_OpenGL: return "OpenGL";
    case WGPUBackendType_WebGPU: return "WebGPU";
    default:                     return "unknown";
  }
}

int main() {
  // Flush per line so `[spike] …` progress shows even when piped or killed.
  std::setvbuf(stdout, nullptr, _IOLBF, 0);

  // Optional headless cap: render N frames then exit cleanly (for CI / smoke tests).
  const char* maxFramesEnv = std::getenv("SAILSIM_MAX_FRAMES");
  const long maxFrames = maxFramesEnv ? std::atol(maxFramesEnv) : 0;
  long frame = 0;

#if defined(WEBGPU_BACKEND_WGPU)
  // Surface wgpu-native's internal logs (including WGSL compile errors).
  wgpuSetLogLevel(WGPULogLevel_Warn);
  wgpuSetLogCallback([](WGPULogLevel level, char const* msg, void*) {
    std::fprintf(stderr, "[wgpu] (%d) %s\n", (int)level, msg ? msg : "");
  }, nullptr);
#endif

  // Headless compute-only mode: run the ocean-FFT readback test with no window,
  // then exit 0/1. Ideal for CI or a quick Windows/D3D12 check.
  if (std::getenv("SAILSIM_FFT_ONLY")) {
    WGPUInstanceDescriptor instDesc = {};
    WGPUInstance inst = wgpuCreateInstance(&instDesc);
    WGPURequestAdapterOptions ao = {};
    ao.powerPreference = WGPUPowerPreference_HighPerformance;
    WGPUAdapter ad = requestAdapterSync(inst, &ao);
    if (!ad) return EXIT_FAILURE;
    WGPUAdapterProperties props = {};
    wgpuAdapterGetProperties(ad, &props);
    std::printf("[spike] headless FFT test — backend=%s device=%s\n",
                backendTypeName(props.backendType), props.name ? props.name : "?");
    WGPUDeviceDescriptor dd = {};
    dd.label = "sailsim-device";
    WGPUDevice dev = requestDeviceSync(ad, &dd);
    if (!dev) return EXIT_FAILURE;
    wgpuDeviceSetUncapturedErrorCallback(dev, onDeviceError, nullptr);
    WGPUQueue q = wgpuDeviceGetQueue(dev);
    const bool ok = runInitialSpectrumTest(dev, q);
    wgpuQueueRelease(q);
    wgpuDeviceRelease(dev);
    wgpuAdapterRelease(ad);
    wgpuInstanceRelease(inst);
    return ok ? EXIT_SUCCESS : EXIT_FAILURE;
  }

  if (!glfwInit()) {
    std::fprintf(stderr, "[spike] glfwInit failed\n");
    return EXIT_FAILURE;
  }

  // WebGPU manages the drawing surface; tell GLFW not to create an OpenGL context.
  glfwWindowHint(GLFW_CLIENT_API, GLFW_NO_API);
  GLFWwindow* window = glfwCreateWindow(1280, 720, "sail-sim native — Phase 1: camera + depth", nullptr, nullptr);
  if (!window) {
    std::fprintf(stderr, "[spike] glfwCreateWindow failed\n");
    glfwTerminate();
    return EXIT_FAILURE;
  }

  // 1. Instance
  WGPUInstanceDescriptor instanceDesc = {};
  WGPUInstance instance = wgpuCreateInstance(&instanceDesc);
  if (!instance) {
    std::fprintf(stderr, "[spike] wgpuCreateInstance failed\n");
    return EXIT_FAILURE;
  }

  // 2. Surface (per-OS creation hidden inside glfw3webgpu)
  WGPUSurface surface = glfwGetWGPUSurface(instance, window);

  // 3. Adapter
  WGPURequestAdapterOptions adapterOpts = {};
  adapterOpts.compatibleSurface = surface;
  adapterOpts.powerPreference = WGPUPowerPreference_HighPerformance;
  WGPUAdapter adapter = requestAdapterSync(instance, &adapterOpts);
  if (!adapter) return EXIT_FAILURE;

  // Report which native backend was selected — the visible proof of the thesis.
  // wgpuAdapterGetProperties is present in both wgpu-native and Dawn 6512.
  WGPUAdapterProperties adapterProps = {};
  wgpuAdapterGetProperties(adapter, &adapterProps);
  std::printf("[spike] adapter: backend=%s  vendor=%s  device=%s\n",
              backendTypeName(adapterProps.backendType),
              adapterProps.vendorName ? adapterProps.vendorName : "?",
              adapterProps.name ? adapterProps.name : "?");

  // 4. Device + queue
  WGPUDeviceDescriptor deviceDesc = {};
  deviceDesc.label = "sailsim-device";
  WGPUDevice device = requestDeviceSync(adapter, &deviceDesc);
  if (!device) return EXIT_FAILURE;

  wgpuDeviceSetUncapturedErrorCallback(device, onDeviceError, nullptr);

  WGPUQueue queue = wgpuDeviceGetQueue(device);

  // Phase 0 criteria 3-5: prove the ocean-FFT WGSL runs natively and reads back.
  runInitialSpectrumTest(device, queue);

  // 5. Configure the surface (swapchain)
  WGPUSurfaceCapabilities caps = {};
  wgpuSurfaceGetCapabilities(surface, adapter, &caps);
  WGPUTextureFormat surfaceFormat = caps.formatCount > 0 ? caps.formats[0] : WGPUTextureFormat_BGRA8Unorm;

  int fbWidth = 0, fbHeight = 0;
  glfwGetFramebufferSize(window, &fbWidth, &fbHeight);

  WGPUSurfaceConfiguration surfaceConfig = {};
  surfaceConfig.device = device;
  surfaceConfig.format = surfaceFormat;
  surfaceConfig.usage = WGPUTextureUsage_RenderAttachment;
  surfaceConfig.width = (uint32_t)fbWidth;
  surfaceConfig.height = (uint32_t)fbHeight;
  surfaceConfig.presentMode = WGPUPresentMode_Fifo;   // vsync
  surfaceConfig.alphaMode = WGPUCompositeAlphaMode_Auto;
  wgpuSurfaceConfigure(surface, &surfaceConfig);

  std::printf("[spike] surface configured: %dx%d format=%d — entering render loop\n",
              fbWidth, fbHeight, (int)surfaceFormat);

  // Phase 1: cube pipeline (needs the surface colour format) + a depth buffer.
  Cube cube = createCube(device, queue, surfaceFormat);
  uint32_t curW = (uint32_t)fbWidth, curH = (uint32_t)fbHeight;
  WGPUTexture depthTex = makeDepthTexture(device, curW, curH);
  WGPUTextureView depthView = wgpuTextureCreateView(depthTex, nullptr);

  // 6. Render loop: clear to sea-blue, then draw the spinning, depth-tested cube.
  while (!glfwWindowShouldClose(window)) {
    glfwPollEvents();
    if (maxFrames > 0 && frame >= maxFrames) break;
    ++frame;

    // Handle window resize: reconfigure the surface and rebuild the depth buffer.
    int w = 0, h = 0;
    glfwGetFramebufferSize(window, &w, &h);
    if (w > 0 && h > 0 && ((uint32_t)w != curW || (uint32_t)h != curH)) {
      curW = (uint32_t)w; curH = (uint32_t)h;
      surfaceConfig.width = curW; surfaceConfig.height = curH;
      wgpuSurfaceConfigure(surface, &surfaceConfig);
      wgpuTextureViewRelease(depthView);
      wgpuTextureRelease(depthTex);
      depthTex = makeDepthTexture(device, curW, curH);
      depthView = wgpuTextureCreateView(depthTex, nullptr);
    }

    // Camera: spin the cube and look at it from an angle.
    float aspect = (float)curW / (float)curH;
    float angle = (float)frame * 0.01f;
    glm::mat4 model = glm::rotate(glm::mat4(1.0f), angle, glm::normalize(glm::vec3(0.3f, 1.0f, 0.2f)));
    glm::mat4 viewM = glm::lookAt(glm::vec3(2.2f, 1.8f, 2.6f), glm::vec3(0.0f), glm::vec3(0, 1, 0));
    glm::mat4 proj  = glm::perspective(glm::radians(45.0f), aspect, 0.1f, 100.0f);
    glm::mat4 mvp   = proj * viewM * model;
    wgpuQueueWriteBuffer(queue, cube.camBuf, 0, &mvp, sizeof(mvp));

    WGPUSurfaceTexture surfaceTex;
    wgpuSurfaceGetCurrentTexture(surface, &surfaceTex);
    if (!surfaceTex.texture) continue;  // e.g. minimised / needs reconfigure

    WGPUTextureView view = wgpuTextureCreateView(surfaceTex.texture, nullptr);

    WGPUCommandEncoderDescriptor encDesc = {};
    WGPUCommandEncoder encoder = wgpuDeviceCreateCommandEncoder(device, &encDesc);

    WGPURenderPassColorAttachment colorAttachment = {};
    colorAttachment.view = view;
    colorAttachment.loadOp = WGPULoadOp_Clear;
    colorAttachment.storeOp = WGPUStoreOp_Store;
    colorAttachment.clearValue = WGPUColor{0.10, 0.32, 0.45, 1.0};
    // (Newer webgpu.h adds colorAttachment.depthSlice = WGPU_DEPTH_SLICE_UNDEFINED here;
    //  wgpu-native v0.19 has no such field — zero-init leaves it correctly unset.)

    WGPURenderPassDepthStencilAttachment depthAttachment = {};
    depthAttachment.view = depthView;
    depthAttachment.depthLoadOp = WGPULoadOp_Clear;
    depthAttachment.depthStoreOp = WGPUStoreOp_Store;
    depthAttachment.depthClearValue = 1.0f;

    WGPURenderPassDescriptor passDesc = {};
    passDesc.colorAttachmentCount = 1;
    passDesc.colorAttachments = &colorAttachment;
    passDesc.depthStencilAttachment = &depthAttachment;

    WGPURenderPassEncoder pass = wgpuCommandEncoderBeginRenderPass(encoder, &passDesc);
    wgpuRenderPassEncoderSetPipeline(pass, cube.pipeline);
    wgpuRenderPassEncoderSetBindGroup(pass, 0, cube.bindGroup, 0, nullptr);
    wgpuRenderPassEncoderSetVertexBuffer(pass, 0, cube.vbuf, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderSetIndexBuffer(pass, cube.ibuf, WGPUIndexFormat_Uint16, 0, WGPU_WHOLE_SIZE);
    wgpuRenderPassEncoderDrawIndexed(pass, cube.indexCount, 1, 0, 0, 0);
    wgpuRenderPassEncoderEnd(pass);
    wgpuRenderPassEncoderRelease(pass);

    WGPUCommandBufferDescriptor cmdDesc = {};
    WGPUCommandBuffer cmd = wgpuCommandEncoderFinish(encoder, &cmdDesc);
    wgpuQueueSubmit(queue, 1, &cmd);

    wgpuCommandBufferRelease(cmd);
    wgpuCommandEncoderRelease(encoder);
    wgpuTextureViewRelease(view);

#ifndef __EMSCRIPTEN__
    wgpuSurfacePresent(surface);
#endif

    // Let Dawn/wgpu service their internal work queues each frame.
#if defined(WEBGPU_BACKEND_DAWN)
    wgpuDeviceTick(device);
#elif defined(WEBGPU_BACKEND_WGPU)
    wgpuDevicePoll(device, false, nullptr);
#endif
  }

  std::printf("[spike] render loop exited after %ld frames — tearing down cleanly\n", frame);

  // 7. Teardown
  wgpuTextureViewRelease(depthView);
  wgpuTextureRelease(depthTex);
  wgpuRenderPipelineRelease(cube.pipeline);
  wgpuBindGroupRelease(cube.bindGroup);
  wgpuBufferRelease(cube.vbuf);
  wgpuBufferRelease(cube.ibuf);
  wgpuBufferRelease(cube.camBuf);
  wgpuShaderModuleRelease(cube.module);
  wgpuQueueRelease(queue);
  wgpuDeviceRelease(device);
  wgpuAdapterRelease(adapter);
  wgpuSurfaceRelease(surface);
  wgpuInstanceRelease(instance);
  glfwDestroyWindow(window);
  glfwTerminate();
  return EXIT_SUCCESS;
}
